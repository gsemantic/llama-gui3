/*
 * plugin_identity.h — имя плагина как идентификатор, а не как произвольная
 * строка (R0.3).
 *
 * ДО ЭТОГО. Имя приходило из `ll_plugin_info()->name` (сам плагин его
 * объявляет) и проверялось ровно на непустоту
 * (`plugin_manager.cpp`, «Invalid plugin info»). Схема `plugin.schema.json`
 * требует `^[a-z][a-z0-9_-]*$`, но схема кодом НЕ применяется — её читает
 * редактор/CI, а не загрузчик. Значит .so мог назвать себя `../../etc` или
 * `wp coder!` — и это имя уходило в меню, в `__plugin_sep__<name>`, в имена
 * окон, в ключи настроек и (с R1) в имя RAG-скоупа, где оно становится
 * частью пути на диске.
 *
 * ПОЧЕМУ ЭТО НЕ «РАНО». Пока имя было только подписью в UI, кривое имя
 * давало кривую подпись — косметика. Как только имя становится частью
 * пути (`<data_dir>/rag_scopes/<scope>/`, R1) или ключа настроек
 * (`plugin.<name>.rag.*`, R3), `../` в имени — это запись за пределы
 * каталога, а `:`/`/` — неоднозначные разделители. Санитизация,
 * сделанная после появления потребителей, пришлась бы на уже
 * записанные данные; сделанная до — на пустые.
 *
 * ЧТО СЧИТАЕТСЯ ВАЛИДНЫМ. `^[a-z][a-z0-9_-]{0,63}$`: первая буква
 * строчная, дальше строчные буквы, цифры, дефис и подчёркивание, длина
 * 1..64. Ровно то, что уже написано в схеме манифеста — но теперь
 * проверяемое кодом. Заглавные и точки запрещены не из вредности:
 * заглавные на Windows-ФС неразличимы с строчными (два плагина
 * `Foo`/`foo` столкнутся), точка — разделитель расширений и `..`.
 *
 * ЧТО ДЕЛАЕТ SANITIZE. Приводит имя к валидному, а не отказывает:
 * плагин с именем `WP Coder` должен загрузиться как `wp_coder`, иначе
 * пользователь видит «плагин не загрузился» там, где дело в подписи.
 * Недопустимые символы → `_`, схлопывание повторов, обрезка до 64,
 * пустой результат → `plugin`. Оригинал не теряется: вызывающий
 * (PluginManager) пишет его в лог, а при необходимости — в отдельное
 * поле диагностики.
 *
 * ГРАНИЦА. Здесь нет загрузки .so, чтения манифеста и работы с ФС:
 * только строки. Поэтому функция проверяется тестом на десятках имён без
 * плагинов и без диска — как `gbnf_from_schema` в плагине.
 */

#include <string>

namespace llama_gui {
namespace plugin {

/* Верно ли имя как идентификатор плагина.
 *
 * Пустое, начинающееся не с буквы, содержащее точку/двоеточе/слеш/пробел
 * или длиннее 64 символов — неверно. */
bool plugin_name_is_valid(const std::string& name);

/* Привести имя к валидному виду.
 *
 * - недопустимые символы → `_`;
 * - повторы `_` схлопываются;
 * - ведущие не-буквы срезаются (чтобы имя начиналось с буквы);
 * - длина ограничена 64;
 * - пустой результат → `"plugin"`.
 *
 * Идемпотентна: sanitize(sanitize(x)) == sanitize(x). */
std::string plugin_name_sanitize(const std::string& name);

} // namespace plugin
} // namespace llama_gui