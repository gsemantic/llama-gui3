#pragma once

#include <string>

namespace news_rewriter {

// Транслитерация кириллицы (RU-подобные буквы) в латиницу. Латинские символы
// и прочие остаются без изменений. Результат — строчные латинские буквы для
// кириллических вхождений (оригинальный регистр латиницы сохраняется).
std::string transliterate_to_latin(const std::string& s);

// Строит SEO-friendly slug из произвольной строки (обычно focus_keyword):
//   - транслитерация кириллицы,
//   - приведение к нижнему регистру,
//   - вырезка стоп-слов (RU/EN, короткие предлоги/союзы),
//   - не-буквы/цифры заменяются на '-', повторы схлопываются, краевые '-' обрезаются.
// Результат пригоден для WP post_name (slug).
std::string make_slug(const std::string& s);

} // namespace news_rewriter
