#pragma once

/*
 * llm_blocking.{h,cpp} — блокирующий вызов хоста, переживающий отмену (И6.6).
 *
 * Зачем файл, если вызов — три строки. Затем, что отменяемость этого вызова
 * была дефектом, который не виден ни в коде, ни в тестах, и именно поэтому
 * он вынесен сюда, а не остался в точке входа.
 *
 * Что было не так (И2.2, комментарий «"Стоп" прерывает ожидание, не дожидаясь
 * ответа провайдера»):
 *
 *   1. std::async возвращает future, ДЕСТРУКТОР которого блокирует до конца
 *      задачи. «Стоп» и «таймаут» делали вид, что вернулись, а на деле
 *      ждали провайдера целиком. Проверено отдельной программой: задача в 2 с
 *      при wait_for(50 мс) даёт 2012 мс на деструкторе.
 *   2. Ответ — malloc-строка хоста. Если её никто не забрал (отмена,
 *      таймаут), она не освобождалась НИКОГДА: утечка на каждый «Стоп».
 *
 * Чего этот файл НЕ может и не обещает: отменить сам запрос. У хоста нет
 * поля llm_chat_messages_cancel, и блокирующий путь до конца генерации
 * доживает — останавливается только ожидание. Настоящая отмена стриминга
 * живёт в LlmClient через llm_chat_cancel. Различие названо прямо, потому
 * что иначе «Стоп» обещал бы больше, чем даёт.
 */

#include "llm_stream_probe.h"

#include <functional>
#include <string>

namespace coder {
namespace host {

/* Итог блокирующего вызова. */
enum class BlockingOutcome {
    Answered,  /* хост ответил, out_json заполнен */
    Aborted,   /* вызывающий попросил остановиться (пользователь) */
    TimedOut   /* истекло llm_timeout_ms */
};

/*
 * Вызвать llm_chat_messages в отдельном потоке и дождаться ответа.
 *
 * is_cancelled опрашивается, пока идёт ожидание, поэтому отмена видна
 * немедленно, а не по остатку таймаута. timeout_ms < 0 — без срока.
 *
 * Возвращаемая строка освобождается в ЛЮБОМ исходе: забрали мы её или
 * пришлось выбросить, когда никто уже не заберёт.
 */
BlockingOutcome call_llm_chat_messages(const LlamaHostApi* api,
                                       LlamaPluginHost* host,
                                       const std::string& sys_prompt,
                                       const std::string& messages_json,
                                       const std::function<bool()>& is_cancelled,
                                       int timeout_ms,
                                       std::string& out_json);

} // namespace host
} // namespace coder
