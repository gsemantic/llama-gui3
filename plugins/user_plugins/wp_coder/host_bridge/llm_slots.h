/*
 * llm_slots.h — слоты LLM и AST, расставленные по возможностям хоста (И13.8).
 *
 * Зачем файл, если это шесть присваиваний: потому что проверялось оно
 * ничем. Слоты ставились прямо в src/plugin_main.cpp, а src/ в сборку
 * тестов НЕ входит (правило И0.9: в src/ только точка входа), то есть
 * «какой слот у какого хоста» было знанием, доступным только чтением.
 *
 * Это и есть слой ДЕГРАДАЦИИ — тот, о котором задача И13.8: хост старше
 * плагина лишается полей, и плагин обязан продолжить работать, потеряв
 * ровно то, чего у хоста нет, и СКАЗАТЬ об этом. Слотов шесть, и
 * запасной путь у каждого свой:
 *
 *   llm_chat_stream  нет у хоста → пустой слот, LlmClient::fetch зовёт
 *                      llm_source::fetch: блокирующий llm_chat, история
 *                      и метрики ЦЕЛЫ, теряется только живая доставка;
 *   llm_chat_cancel  нет у хоста → отмена означает «перестать ждать»
 *                      (core/llm_client.h), поток доходит до конца;
 *   llm_ast_symbols  нет у хоста → пустой слот, обзор проекта уходит на
 *                      строковый скан, и core/ast_symbols.cpp называет
 *                      причину вслух прямо в обзоре;
 *   llm_chat         нет у хоста → пустой слот, llm_source::fetch зовёт
 *                      одногилый llm_complete: история заменяется
 *                      последней репликой пользователя, метрики
 *                      неизвестны и НЕ выдумываются (core/llm_source.cpp).
 *
 * Правило, ради которого файл и написан: СЛОТ ЗАПОЛНЯЕТСЯ ТОЛЬКО ЕСЛИ У
 * ХОСТА ЕСТЬ СООТВЕТСТВУЮЩЕЕ ПОЛЕ, и проверка идёт по размеру структуры
 * хоста (host::has_*), а не по факту вызова. Слот, заполненный «на
 * всякий случай», — это чтение поля, которого у хоста нет, то есть ровно
 * тот segfault на PC=0x1, которым стоила И0.2.
 *
 * ЧЕГО ТУТ НЕТ, и это граница, о которой стоит знать до расширения:
 *   - слотов НЕ ЛЛМ/АСТ (пути, настройки, rag, agent_mode): их хост
 *     отдаёт всегда, деградации у них нет, и они остаются в точке входа;
 *   - самого решения «что делать при пустом слоте»: оно живёт в ядре
 *     у того, кто слот читает (LlmClient, llm_source, ast_symbols).
 *     Здесь только соответствие слотов хосту — иначе «деградация» снова
 *     стала бы размазанной по двум половинам.
 */

#include "llm_stream_probe.h"
#include "core/engine.h"

namespace coder {
namespace host {

/*
 * Заполнить слоты LLM и AST по возможностям хоста.
 *
 * api и host — те самые, что переданы в ll_plugin_init; слоты захватывают
 * их ПО ЗНАЧЕНИЮ, потому что колбэки живут дольше вызова (требование
 * И6.4 в plugin_api.h) и после ll_plugin_shutdown глобальные хендлы уже
 * обнулены.
 *
 * cb заполняется ЧАСТИЧНО: пустой слот — это ответ, а не недоделка.
 * Уже заполненные слоты не трогаются: у вызывающего их может быть
 * несколько (тесты собирают наборы слотов сами), и молча перетирать их
 * было бы тем же «работает на моём наборе», что и проверка без
 * отрицательного контроля.
 */
void install_llm_slots(HostCallbacks& cb, const LlamaHostApi* api,
                       LlamaPluginHost* host);

} // namespace host
} // namespace coder