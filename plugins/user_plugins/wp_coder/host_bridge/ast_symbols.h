/*
 * ast_symbols.h — мост к полю хоста llm_ast_symbols (И13.5).
 *
 * Живёт в host_bridge/ по той же причине, что и llm_stream_shim: только
 * здесь законно знать про LlamaHostApi, а ядро плагина от хоста не
 * зависит (D-7). Ядро получает std::function и сырой JSON, и ни одного
 * байта ABI не видит.
 *
 * Отличие от остальных вызовов хоста: этот НЕ имеет запасного пути внутри
 * моста. У llm_chat_stream запасной путь — блокирующий llm_chat, и он
 * отдаёт тот же результат. Здесь запасной путь — строковый скан в ядре, и
 * он даёт заметно меньше (на проверенном материале: у python-файла скан
 * находит одну настоящую функцию из четырёх и одну выдуманную, взятую из
 * комментария). Поэтому «мост ничего не вернул» и «мост сказал, что
 * символов нет» — разные вещи, и обе должны дойти до вызывающего как
 * разные: решение принимает ядро (core/ast_symbols.cpp), где и лежит
 * правило, а не молчаливый возврат пустой строки.
 */

#include "llm_stream_probe.h"

#include <string>

namespace coder {
namespace host {

/*
 * Символы одного файла по полю llm_ast_symbols.
 *
 * language пустая — ход по расширению (у хоста одна таблица расширений на
 * весь проект, и вторая таблица в плагине разошлась бы с ней при первом
 * же новом расширении).
 *
 * Возвращает malloc'd JSON хоста, уже скопированный и освобождённый через
 * free_string, либо пустую строку — если поля у хоста нет, оно равно
 * nullptr или сам хост вернул nullptr. Пустая строка означает «спросить
 * некого», а не «символов нет»: эти два случая вызывающий обязан различать
 * сам, иначе отказ хоста станет «файл без символов».
 */
std::string call_ast_symbols(const LlamaHostApi* api, LlamaPluginHost* host,
                             const std::string& path,
                             const std::string& language);

} // namespace host
} // namespace coder
