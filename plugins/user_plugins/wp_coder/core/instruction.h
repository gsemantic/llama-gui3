#pragma once

/*
 * instruction.h — инструкции проекта и пользователя (И9.1,
 * порт opencode session/instruction.ts).
 *
 * До И9 правила проекта ждали, пока их впишут в каждый запрос: файл
 * AGENTS.md в репозитории не делал ничего, и агент о нём не знал. Здесь
 * он читается ОДИН раз за сессию и уезжает в системный промпт отдельным
 * блоком на каждый источник.
 *
 * Почему блок на источник, а не один общий текст: модели нужно знать,
 * ЧТО и ОТКУДА применяется. Склеенные инструкции выглядели бы как
 * требования автора промпта, а правила проекта — как часть системного
 * протокола; при конфликте (а он возможен: проект может требовать не
 * ровно того, что требует базовый промпт) невозможно понять, что важнее.
 *
 * Что НЕ здесь и почему:
 *   - proximity-attach (И9.2). Сейчас читаются только файлы в корне
 *     проекта и явно перечисленные источники. Подъём от каталога
 *     прочитанного файла — отдельная задача, и она приклеивается сюда
 *     же (Instruction::resolve), а не второй разбором тех же файлов;
 *   - порядок блоков в промпте (И9.3) и env-блок (И9.4). Сборка
 *     системного промпта живёт в Engine::build_system_prompt; отсюда
 *     приходит только готовый текст и список источников.
 *
 * Формат блока назван в kBaseSystemPrompt — по общему правилу файла
 * (D2): строка формата, о которой модель не знает, ею и не пользуется.
 */

#include <functional>
#include <string>
#include <vector>

namespace coder {

/* Один источник инструкций: файл или URL. */
struct Instruction {
    /* Как источник назван в промпте — ровно то, что видит модель.
     * Для файла внутри проекта — путь относительно корня («AGENTS.md»),
     * для глобального — «~/.config/wp_coder/AGENTS.md», для URL — сам URL. */
    std::string label;
    /* Путь, который открывали, или URL. Нужен для диагностики, дедупликации
     * и для И9.2: подняться от каталога ИСТОЧНИКА, а не от его названия. */
    std::string origin;
    /* Содержимое без BOM, переводы строк — LF. */
    std::string body;
};

namespace instruction {

/* Загрузчик одного URL. Возвращает false, если взять не удалось; out при
 * этом не имеет значения.
 *
 * Отдельный тип, а не прямой вызов curl внутри load(), по двум причинам:
 * тест не должен ходить в сеть (проверка, зависящая от внешнего сервера,
 * через год станет проверкой сети), и решение «чем качать» не должно
 * быть аргументом загрузки инструкций. */
using UrlFetcher = std::function<bool(const std::string& url, std::string& out)>;

/* Настоящая загрузка по HTTP: curl с предельным временем из limits.h.
 * Команда уходит через core/shell.h — свой запуск процесса запрещён. */
bool fetch_url(const std::string& url, std::string& out);

/* Развернуть «~» и «~/…» в домашний каталог. Остальное — как есть.
 * Пусто, если домашнего каталога узнать не удалось: подставлять вместо
 * него корень файловой системы нельзя, это прочитало бы чужой файл. */
std::string expand_home(const std::string& path);

/* Разобрать значение настройки `wp_coder.instructions`.
 *
 * Формат — JSON-массив строк, ровно как у соседней настройки
 * `wp_cader.permission_rules` (permission_engine.cpp): хост хранит
 * пользовательские настройки строками, и второй формат («просто строка с
 * путём», «путь, запятая, путь») разошёлся бы с первым при первой же
 * правке. Второй формат означал бы, что разбирать надо оба, а
 * непонятная запись молча дала бы НОЛЬ инструкций вместо понятной ошибки.
 *
 * Мусор в одной записи не лишает остальных: не-строки и пустые строки
 * пропускаются (пропущенное печатается в лог загрузчиком). */
std::vector<std::string> parse_config_list(const std::string& json_text);

/* Есть ли в строке символы шаблона пути. */
bool has_glob_magic(const std::string& pattern);

/* Загрузить инструкции в порядке плана (9.1):
 *
 *   1. ~/.config/wp_coder/AGENTS.md — общие для пользователя;
 *   2. AGENTS.md, затем CLAUDE.md в корне проекта;
 *   3. записи `config.instructions` в порядке настройки.
 *
 * Подъёма «от cwd к worktree» в плане нет не по недосмотку: у плагина
 * единственный каталог — wp_coder.project_dir, он и cwd, и корень
 * worktree, так что список файлов совпадает с портом, а подниматься
 * некуда. Ближайший к прочитанному файлу AGENTS.md — это И9.2.
 *
 * Один и тот же файл, названный дважды (явно в настройке и как
 * AGENTS.md проекта), попадает в список ОДИН раз: инструкции, продублированные
 * в промпте, стоят токенов и провоцируют противоречия. Первое упоминание
 * выигрывает, потому что порядок выше — это приоритет.
 *
 * Незагруженный источник (нет файла, битый путь, недоступный URL) НЕ
 * превращается в блок с текстом ошибки: в промпте ошибка выглядит как
 * инструкция от автора. Причина идёт в лог загрузчика. */
std::vector<Instruction> load(const std::string& project_dir,
                              const std::string& config_instructions,
                              const UrlFetcher& fetch = fetch_url);

/* Собрать текст для системного промпта: по блоку на источник, каждый
 * с заголовком «## Instructions from: {label}». Пустой список — пустая
 * строка (инструкций нет, и блока быть не должно). */
std::string render(const std::vector<Instruction>& items);

/* И9.2: инструкции, относящиеся к конкретному прочитанному файлу.
 *
 * Подъём от каталога файла к корню проекта, БЛИЖАЙШИЕЙ ПЕРВЫМИ: правила
 * каталога относятся к коду рядом и потому важнее общих, а в промпте
 * читаются сверху вниз. В каждом каталоге AGENTS.md раньше CLAUDE.md —
 * тот же приоритет имён, что в load().
 *
 * Возвращает ВСЕ найденное, а не один ближайший файл: правила каталога
 * родителя относятся к тому же коду, и молча выбросить их, оставив только
 * самый близкий, значило бы применить половину требований. Что из этого
 * уже в промпте, решает вызывающий (append_new).
 *
 * Файл ВНЕ корня проекта не даёт ничего: инструкции чужого дерева
 * каталогов к нашему коду не относятся, а подъём оттуда вверх собрал бы
 * правила какого-нибудь родительского каталога (часто ~/.config или /tmp) и
 * прикрепил бы их к сессии молча. */
std::vector<Instruction> resolve(const std::string& file,
                                 const std::string& project_dir);

/* Дописать в список только те источники, которых в нём ещё нет.
 *
 * Ключ — origin (канонический путь или URL), и это тот же ключ, по
 * которому load() снимает дубли: дедупликация в двух местах означала бы
 * две разные её версии, а правило «источник попадает в промпт один раз»
 * обязано быть одно. Возвращает, сколько источников реально добавилось, —
 * вызывающему нужно знать, стоит ли сбрасывать кэш промпта. */
size_t append_new(std::vector<Instruction>& into,
                  std::vector<Instruction> more);

} // namespace instruction
} // namespace coder