#pragma once

/*
 * harness_profile.h — профили harness: JSON-файлы набора параметров (И9.7).
 *
 * Четыре файла в `profiles/wp_coder` (`fast_local.json`,
 * `accurate_cloud.json`, `secure_audit.json`, `debug_verbose.json`) лежали
 * в дереве плагина без единого читателя: их поля повторяют конфиг мёртвой
 * системы B (§0.1 плана, `src/agents/terminal_agent.cpp`), и ни плагин, ни
 * хост их не открывали.
 * Задача 9.7 — не «включить готовую вещь», а решить, что эти поля значат
 * для живого ядра, и не выдать за профиль набор обещаний, которые
 * плагин выполнить не может.
 *
 * ЧТО ПРОФИЛЬ МОЖЕТ, а что не может — проверено по коду, а не по названию
 * полей (журнал И9.1–9.6, п. 8). Применимо:
 *
 *   timeout_ms        → EngineState::llm_timeout_ms, то же поле, что и
 *                       настройка wp_coder.llm_timeout_ms; читает
 *                       src/plugin_main.cpp на блокирующем пути, который
 *                       цикл агента действительно ходит.
 *   allowed_commands  → сужение allowlist политики команд (И3).
 *   tools_policy      → ЗАПРЕТЫ ключей разрешений (И2), по которым
 *                       инструменты ещё и убираются из каталога модели.
 *   description       → текст для человека.
 *
 * Применяется, и это записано наравне с неприменённым, а не оставлено
 * на потом врать:
 *
 *   temperature, max_tokens — ПРИМЕНЯЮТСЯ с И11.14: это единственное
 *       место, где параметры генерации доезжают до хоста, потому что
 *       `llm_chat_stream` принимает request_json, а хост читает из него
 *       эти поля (src/plugins/plugin_manager.cpp:585). До И11.14 цикл
 *       агента шёл мимо стриминга (D23), LlmClient слал пустую строку, и
 *       поля разбирались и хранились «впрок». Теперь применяются, но
 *       ТОЛЬКО заданные: без профиля (или без этих полей в нём)
 *       request_json пуст и хост берёт свои умолчания.
 *
 * НЕ применяется, и это записано, а не оставлено на потом врать:
 *
 *   model             — в этих профилях это НЕ имя модели, а подсказка
 *       «local»/«cloud»; через ABI хост не сообщает имя модели вовсе, так
 *       что значение нечему соответствовать (отклонение 97).
 *   allowed_extensions— потребителя нет: фильтра по расширениям в
 *       инструментах не существует, и заводить его здесь означало бы
 *       второе место у правила, которого нет.
 *   rag_enabled       — RAG живёт в хосте (src/core/rag_index_profile.cpp),
 *       ядро плагина его не касается.
 *
 * ПОЧЕМУ КАТАЛОГ ПРИХОДИТ АРГУМЕНТОМ. И9.6 уже поплатился за синглтон,
 * из которого нельзя было взять ветку «пусто»: каталог передаётся
 * параметром, поэтому проверка может дать и каталог без профилей, и
 * профиль из своего каталога, не трогая общее состояние.
 *
 * ПОЧЕМУ ЗАПРЕТЫ ПОЛУЧАЮТСЯ ИЗ ФЛАГОВ. Список инструментов, которые
 * профиль запрещает, выводится из реестра и его флагов (TF_READ_ONLY и
 * прочие), а не перечисляется руками: ручной список однажды забыли бы, и
 * запрет молча перестал бы действовать — то самое тихое расхождение,
 * ради которого каталог инструментов и строится из схемы (И1.5).
 * Единственное исключение — `strict`, у него нет флагового смысла
 * («вообще ничего не делать, кроме чтения»), и его полный набор
 * проверяется тестом на ТОТАЛЬНОСТЬ: любой новый ключ обязан либо
 * попасть в разрешённые, либо в запрещённые, иначе проверка падает.
 */

#include "tool.h"

#include <string>
#include <vector>

namespace coder {

class CommandPolicy;

namespace harness {

/* Один профиль. Поля «разобрано, но не применяется» остаются в
 * структуре намеренно (см. шапку): выбросить их — значит через
 * И11.14 выяснить заново, что в файлах написано. */
struct Profile {
    std::string name;        /* имя файла без .json */
    std::string description; /* для человека: что профиль делает */

    /* Подсказка «local»/«cloud», НЕ имя модели: применять нечем. */
    std::string model_hint;

    bool has_temperature = false;
    double temperature = 0.0;
    bool has_max_tokens = false;
    int max_tokens = 0;

    std::string tools_policy;   /* standard|restricted|strict|verbose */
    bool has_timeout_ms = false;
    int timeout_ms = 0;

    std::vector<std::string> allowed_commands;
    /* Потребителя нет (шапка): сохраняется, чтобы решение «фильтра по
     * расширениям нет» было видно из данных, а не только из комментария. */
    std::vector<std::string> allowed_extensions;
    bool rag_enabled = false;

    /* Ключи, которые в файле есть, а плагин не знает. Не ошибка:
     * профили писались под harness, часть полей — его. Печатаются
     * один раз при загрузке, чтобы видна была опечатка. */
    std::vector<std::string> unknown_keys;
    std::string source_path;
};

/* --- Разбор --- */

/* Разобрать текст профиля. Строго, как всё остальное в плагине (И8.2,
 * И9.1): неверный тип поля и недопустимое значение ОТКЛОНЯЮТ файл, а не
 * молча заменяются дефолтом — иначе опечатка в `timeout_ms` выглядела бы
 * как профиль с настройкой.
 *
 * Отказ — по-русски и с названием виновного поля: файл читает человек,
 * и «не удалось разобрать» заставило бы искать ошибку в парсере JSON. */
bool parse_profile(const std::string& text, Profile* out, std::string* why);

/* --- Файлы --- */

/* Прочитать `<dir>/<name>.json`. Каталог и имя — параметрами (шапка). */
bool load_profile(const std::string& dir, const std::string& name, Profile* out,
                  std::string* why);

/* Имена профилей в каталоге, поимённо отсортированные — для сообщения
 * «профиля с таким именем нет, доступны: …». Пустой каталог даёт пустой
 * список, а не исключение: его отсутствие — не ошибка (то же, что у
 * load_agents_from_directory, И8.2). */
std::vector<std::string> profile_names(const std::string& dir);

/* Допустимо ли имя профиля. why — необязательный, по-русски. Имя
 * подставляется в путь, поэтому «../» и пустое имя отвергаются. */
bool valid_profile_name(const std::string& name, std::string* why);

/* --- Политика инструментов --- */

/* Известные значения tools_policy — в том же порядке. */
const std::vector<std::string>& tools_policy_names();
bool valid_tools_policy(const std::string& policy);

/* КЛЮЧИ, которые профиль запрещает целиком (правило «ключ: * → запретить»).
 *
 * Смысл значений (порты из четырёх файлов профилей, смысл — из их
 * описаний, а не из названия):
 *   standard  — ничего не сужает; обычная работа с правилами сессии;
 *   verbose   — тоже ничего: журналирование в плагине не настраивается
 *               настройкой профиля, и принимать значение молча значило бы
 *               обещать подробный лог, которого не будет. Значение
 *               ПРИЗНАТО (иначе профиль отвергался бы), но оно ничего не
 *               меняет — и это написано здесь, а не оставлено догадкой;
 *   restricted— «только чтение и план»: запрещён ключ, у которого НЕ ВСЕ
 *               инструменты помечены TF_READ_ONLY. Список выводится из
 *               флагов, поэтому новый инструмент попадает в него сам;
 *   strict    — «только чтение»: кроме того, запрещён и `todo`, то есть
 *               агент не ведёт план. Разница видна не только в правилах:
 *               у агента с закрытым `todo` из промпта уходит и сам блок
 *               плана (И8.7). Флагом это не выводится — «не вести план»
 *               не про чтение, — поэтому набор разрешённых ключей задан
 *               здесь и проверяется на полноту.
 *
 * Ключ — единица ЗАПРЕТА, поэтому смешанный ключ (в `git` есть и читающий,
 * и пишущий инструмент) закрывается целиком: поделить его нечем, а
 * «оставить, раз есть читатель» означало бы, что restricted называется
 * «только чтение», а коммитит. Обоснование — в .cpp.
 *
 * all — реестр инструментов ПАРАМЕТРОМ, а не через синглтон: проверка
 * собирает свой список и не зависит от того, что успели зарегистрировать
 * другие файлы тестов.
 *
 * Результат отсортирован (набор попадает в правила разрешений и в дамп,
 * а порядок должен быть один). */
std::vector<std::string> denied_keys(const std::string& policy,
                                     const std::vector<ToolDef>& all,
                                     std::string* why);

/* Ключи, которые `strict` оставляет. Открытая функция, а не константа в
 * .cpp: тест на тотальность сверяет с ней то, что реально запрещено, и
 * падает, если появился ключ, который не разрешён и не запрещён. */
const std::vector<std::string>& strict_allowed_keys();

/* --- Команды --- */

/* Применить `allowed_commands` к политике: ТОЛЬКО СУЗИТЬ.
 *
 * Профиль не может РАСШИРИТЬ allowlist: список команд — не украшение, а
 * граница (И3), и файл в каталоге плагина не должен открывать то, что
 * закрыто по умолчанию. Поэтому берётся пересечение с текущим списком,
 * а всё остальное выбрасывается; пустой список команд профиля границу не
 * двигает (у профиля может не быть этого поля вовсе).
 *
 * policy передаётся параметром — как denied_keys, по той же причине:
 * command_policy() — синглтон, живущий между проверками. */
bool apply_allowed_commands(CommandPolicy& policy,
                            const std::vector<std::string>& cmds,
                            std::string* why);

} // namespace harness
} // namespace coder
