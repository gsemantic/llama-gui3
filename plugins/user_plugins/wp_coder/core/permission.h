#pragma once

/*
 * permission.h — Система разрешений (И2, порт opencode permission/index.ts).
 *
 * До И2 в плагине был ровно один вид разрешения: PermissionGate спрашивал
 * пользователя про путь ЗА пределами проекта. Всё остальное — запуск
 * произвольной команды, деплой, перезапуск сервиса, доступ по ssh,
 * создание БД — молча разрешалось, потому что политики режимов
 * (И1.7) отвечают на другой вопрос: «можно ли в режиме research»,
 * а не «можно ли вообще, без участия человека».
 *
 * Здесь появляется то, чего не хватало: упорядоченный список правил
 * вида «ключ разрешения + паттерн → действие». Три свойства перенесены
 * из opencode и должны остаться такими же, потому что на них держатся
 * и настройки агентов (И8), и наследование разрешений субагентом (И8.10):
 *
 *   1. Порядок правил = семантика, а не оформление. Совпавшее ПОСЛЕДНИМ
 *      правило выигрывает (last match wins): так пользователь дописывает
 *      исключение в конец списка и не обязан знать, где стоит
 *      «умолчание», которое он перекрывает. Обратный порядок означал бы,
 *      что любое правило, забытое автором над последним, невозможно
 *      перекрыть, и deny перестал бы работать как задумано.
 *
 *   2. Ключ разрешения («permission») не равен имени инструмента. Он
 *      общий для группы инструментов: bash и python_run оба
 *      живут под ключом «bash», и правило «bash → ask» спрашивает
 *      пользователя один раз за настройку, а не пятьдесят.
 *
 *   3. Паттерн — вилка: «*» ловит всё, «*.env» — файлы с суффиксом.
 *      Совпадение проверяет Wildcard::match (И2.2), а не std::regex:
 *      правила читает и пишет человек в настройках, и регулярное
 *      выражение там ошибка на каждом втором символе.
 *
 * Отсутствие правил — это НЕ «разрешить». evaluate() возвращает Ask,
 * и Ask — состояние по умолчанию везде: не описанное поведение
 * спрашивает пользователя, а не молча делает.
 */

#include <string>
#include <vector>

namespace coder {

/* --- Сопоставление паттерна (И2.2) ---
 *
 * Правила разрешений пишет человек в настройках агента, поэтому язык
 * узоров должен быть таким же простым, как в opencode: «*» — любая
 * последовательность символов (в том числе пустая), «?» — ровно один
 * символ. Никаких регулярных выражений: «*.env» в regex означал бы
 * «что угодно, точка, env», и пользователь, написавший это про файл
 * конфигурации, получил бы правило, которое ловит всё подряд.
 *
 * Реализация — итеративная с откатом по последней `*`, а не рекурсия
 * и не std::regex: рекурсия на длинной строке из тысяч символов (путь
 * внутри shell-команды) съела бы стек, а regex на каждом вызове
 * инструмента заново компилировал бы выражение из настроек.
 */
class Wildcard {
public:
    static bool match(const std::string& pattern, const std::string& value);
};

/* --- Действие правила --- */
enum class PermissionAction {
    Allow,   /* можно выполнять, не спрашивая */
    Deny,    /* нельзя: вызов отклоняется сразу и без UI */
    Ask      /* спросить пользователя (состояние по умолчанию) */
};

/* Имя действия по-русски — для UI и сообщений модели. */
const char* permission_action_name(PermissionAction a);

/* --- Правило ---
 *
 * permission: имя ключа («bash», «read», «deploy», «external_directory»)
 *             либо «*» — правило относится ко всем ключам.
 * pattern:    вилка,matched против конкретного значения (путь, команда,
 *             имя хоста): «*», «*.env», «/home/user/notes*».
 * action:     что делать при совпадении.
 * comment:    необязательное пояснение для пользователя; на решение
 *             не влияет, но попадает в дамп правил и в диалог.
 */
struct Rule {
    std::string permission = "*";
    std::string pattern = "*";
    PermissionAction action = PermissionAction::Ask;
    std::string comment;
};

/* --- Упорядоченный набор правил ---
 *
 * Просто вектор с сохранением порядка: отдельная структура данных тут
 * не нужна, а любое «упорядочивание» внутри контейнера (например,
 * перестановка по приоритету) тихо ломает last-match-wins.
 */
class Ruleset {
public:
    /* Добавить правило в конец — так оно и перекрывает предыдущие. */
    void add(Rule r);
    /* Добавить с перегрузкой: add(permission, pattern, action). */
    void add(const std::string& permission, const std::string& pattern,
             PermissionAction action);

    void clear();
    bool empty() const;
    size_t size() const;
    const std::vector<Rule>& rules() const;

    /* Решение для пары (ключ, значение). Совпавшее последним правило
     * выигрывает; если не совпало ни одно — Ask. */
    PermissionAction evaluate(const std::string& permission,
                              const std::string& pattern) const;

    /* То же, но С ПРИЗНАКОМ СОВПАДЕНИЯ. Нужен там, где наборы правил
     * накладываются друг на друга (И8.4: правила агента поверх
     * замороженных, ответы «всегда» поверх обоих). Без признака
     * «правил не было» не отличить от «решили спросить», и наложение
     * тихо превращало бы «запретить» в «спросить» — то есть
     * ЗАПРЕТНИК превратился бы в вопрос пользователю. */
    PermissionAction evaluate_matched(const std::string& permission,
                                      const std::string& pattern,
                                      bool* matched) const;

    /* Есть ли правило ровно с таким ключом (без учёта паттерна).
     * Нужно, чтобы отличать «ключ описан явно» от «подпал под звёздочку»:
     * для второго действуют дефолты уровня агента (И2.4). */
    bool mentions_key(const std::string& permission) const;

    /* Есть ли правило, запрещающее ключ целиком (pattern == "*",
     * action == Deny) — по нему инструмент убирается из схемы (И2.8). */
    bool denies_all(const std::string& permission) const;

    /* Правила по-русски, по одному в строке — для панели настроек и
     * для сообщения об ошибке конфигурации. */
    std::string dump() const;

private:
    std::vector<Rule> rules_;
};

} // namespace coder
