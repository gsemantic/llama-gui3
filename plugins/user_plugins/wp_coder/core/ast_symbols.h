#pragma once

/*
 * ast_symbols.h — символы файла для обзора проекта: AST хоста, а если его
 * нет или он не ответил — строковый скан (И13.5).
 *
 * Почему это отдельный файл, а не пара строк в base_tools.cpp: правило
 * «AST или скан» — это решение, у которого три разных отказа и один
 * неочевидный случай (пустой список символов). Запрятанное в тело обхода
 * дерева, оно читалось бы как частность repo_map, а оно касается каждого
 * места, которому понадобится список символов.
 *
 * Ответ хоста (И6.3, три состояния) разбирается здесь, целиком:
 *
 *   {"ok":0,"error":"..."}                  — отказ: уходим на скан
 *   {"ok":1,"ast":false,"reason":"..."}     — грамматики нет: скан
 *   {"ok":1,"ast":true,"symbols":[...]}      — разобрали: берём символы
 *
 * И ЧЕТВЁРТОЕ, которого в ABI нет и ради которого этот файл и написан:
 * ok:1 ast:true с ПУСТЫМ списком. На проверенном материале (php-файл при
 * грамматике новее установленной библиотеки tree-sitter) хост отвечает
 * ровно так: разбор не удался, но parse_source признака неудачи не имеет и
 * возвращает корень без детей. Снаружи это неотличимо от «файл без
 * определений», а разница для обзора проекта — весь обзор: пустой список
 * на файле с двадцатью функциями выглядит так же, как файл без функций.
 * Поэтому пустой список тоже уводит на скан, и причина идёт в обзор
 * словами, а не остаётся в коде.
 *
 * ГРАНИЦА, которую знать при расширении: хост отдаёт ТОЛЬКО символы
 * верхнего уровня (extract_top_level_nodes). Метод внутри класса и
 * определение внутри namespace в списке не бывают — проверено на живом
 * материале: на cpp-файле с namespace, классом, структурой, enum, typedef
 * и функцией приходит один символ, имя namespace. Отсюда два решения:
 *   - поле parent не используется: на живом материале оно всегда пустое
 *     (у верхнеуровневых узлов класса-родителя нет), и ветка «Parent::имя»
 *     была бы кодом под признаком, который не наступает;
 *   - скан НЕ дописывается к AST: у скана своя ложь — имена из комментариев
 *     и строк (проверено: f:commented_out из строки комментария,
 *     c:NotAString из строкового литерала), и дописывание вернуло бы в
 *     обзор ровно то, ради чего уходили в AST. Недостающие вложенные
 *     определения — это ограничение ABI, и оно названо в обзоре и в
 *     промпте, а не закрыто уловками.
 *
 * Чего здесь нет: обхода дерева (у вызывающего свои правила пропуска и
 * лимиты), имён файлов (их знает обход) и таблицы языков (язык по
 * расширению определяет хост — у него единственная таблица расширений).
 */

#include "engine.h"

#include <string>
#include <vector>

namespace coder {
namespace ast_symbols {

/*
 * Короткая запись символа в том виде, в каком она печатается в обзоре:
 * метка + имя. Метки — те же, что и у строкового скана (f:, c:, h:), плюс
 * четыре новых для видов, которых скан не видел в принципе: n: (namespace),
 * e: (enum), t: (typedef), m: (macro). Словарь видов на стороне хоста
 * закрытый, и вид, которому здесь не назначена метка, пропускается молча:
 * придумывать для него букву значило бы печатать модели символ, смысл
 * которого никто не проверял.
 */
struct Symbol {
    std::string tag;    /* "f", "c", "n", "e", "t", "m", "h" */
    std::string name;
};

/* Один файл: символы, хуки и признак, откуда всё это взялось.
 *
 * Хуки — это add_action / add_filter / add_shortcode. AST их не отдаёт
 * НИКОГДА: хост отдаёт объявления, а вызов add_action — это вызов функции,
 * и в списке символов его нет. Поэтому хуки ищутся строкой по-прежнему, и
 * отказ от строкового скана здесь означал бы потеру ровно той части
 * обзора, ради которой repo_map и зовут в проекте WordPress. Дубликаты
 * имён сохраняются: два add_action на один хук — это два места
 * регистрации, и обзор должен видеть оба.
 */
struct FileSymbols {
    /* Определения: из AST хоста либо из строкового скана. */
    std::vector<Symbol> symbols;
    /* Хуки WordPress — всегда строковым сканом (см. FileSymbols). */
    std::vector<Symbol> hooks;
    /* true — определения пришли из AST хоста; false — собраны сканом. */
    bool from_ast = false;
    /* Непусто — ПОЧЕМУ ушли на скан. Пусто при from_ast == true. */
    std::string degrade;
};

/*
 * Символы и хуки одного файла: спросить хост, разобрать ответ, при
 * негодном ответе — прочитать файл строкой.
 *
 * cb — слот хоста. Пустой слот (старый хост) — не ошибка: уходим на скан с
 * названной причиной.
 *
 * Файл не открывается — пустой список, и degrade ПУСТ: читать нечего, и
 * называть это деградацией значило бы врать (деградация — когда символы
 * добываются хуже, а не когда их негде взять).
 */
FileSymbols file_symbols(const HostCallbacks& cb, const std::string& path);

/* Текст символа так, как он печатается в обзоре: "f:name". */
std::string symbol_text(const Symbol& s);

} // namespace ast_symbols
} // namespace coder
