#pragma once

/*
 * tool_display.h — И11.4: виджет вызова по ТИПУ инструмента.
 *
 * ---------------------------------------------------------------------------
 * ЧТО ЭТО И ОТКУДА ВЗЯЛОСЬ
 * ---------------------------------------------------------------------------
 *
 * Строка задачи 11.4 перечисляет шесть видов показа: `bash` (ввод + вывод +
 * exit), `read` (превью), `edit`/`write`/`apply_patch` (diff), `grep`/`glob`
 * (список), `task` (вложенное дерево субагента), `todowrite` (чек-лист).
 *
 * `toolDisplay` — ИМЯ ИЗ СТРОКИ ЗАДАЧИ, а не найденный источник. Исходников
 * opencode в окружении нет и веб-поиск недоступно, поэтому 11.1–11.3 сделаны
 * по описанию из строки задачи, и так же сделана 11.4: это написано в
 * шапках core/diff.h и core/timeline.h, и повторяется здесь, чтобы правка
 * кода не превратилась в «мы где-то это видели». Портов из opencode здесь
 * нет, и утверждать обратное было бы выдумкой.
 *
 * ---------------------------------------------------------------------------
 * ГДЕ ЖИВЁТ ЛОГИКА, А ГДЕ РИСОВАНИЕ
 * ---------------------------------------------------------------------------
 *
 * Как в 11.1, 11.2 и 11.3: решение принимает core, рисует ui/coder_window.cpp
 * тонким слоем. Причина та же и называется прямо — тестового харнесса для
 * ImGui нет, а 11.13 (golden-снапшоты рендера) сверяет ГОТОВУЮ строку и её
 * вид. Собранная в окне строка непроверяема: проверять её было бы нечем.
 *
 * Здесь ровно то, что решается без окна: вид вызова по имени инструмента,
 * что показывать в шапке виджета, какие строки тела и в каком порядке, где
 * взяты числа, что сказать словами, когда данных нет, и сколько чего
 * осталось за кадром. Окно получает готовые строки и красит их, а виджет
 * diff у него УЖЕ ЕСТЬ — `render_diff_rows` в ui/coder_window.cpp, тот же,
 * что рисует diff уровня и diff вызова (11.1, 11.2). Второй виджет diff
 * рядом заведён быть не может: два способа показать одну правку разъедутся
 * номерами строк и цветами (Д2, Д12).
 *
 * ---------------------------------------------------------------------------
 * КЛЮЧ ВИДА — ИМЯ ИНСТРУМЕНТА, И ПЕРЕЧЕНЬ ОБЯЗАН БЫТЬ ПОЛНЫМ
 * ---------------------------------------------------------------------------
 *
 * В строке задачи названы шесть видов, а инструментов в живом реестре 57
 * (счётчик `every_tool_has_permission_key`, правило 12). Значит, у 46
 * инструментов своего вида нет, и для них нужен осмысленный откат. Он
 * здесь и называется: КИД `Text` — «текст вывода», то есть виджет
 * показывает заголовок, который поставил сам инструмент, и текст его
 * вывода. Молчаливый откат был бы хуже отсутствия: человек увидел бы
 * одинаковые серые блоки и не понял бы, что это «я не описал этот
 * инструмент», а не «инструменту нечего показать».
 *
 * Откат объявлен ЯВНО (`text_kind_tools()` — полный перечень), и проверка
 * сверяет его с живым реестром: новый инструмент без вида уронит её с его
 * именем. Это ровно тот приём, что у счётчиков инструментов: перечень,
 * который молча расходится с реестром, хуже отсутствия перечня.
 *
 * Инструмент с именем `test_*` в сверке не участвует — такие регистрируют
 * юнит-тесты, в плагине их нет, и счётчик зависел бы от того, какие тесты
 * уже отработали (правило 12).
 *
 * ---------------------------------------------------------------------------
 * ИНВЕНТАРЬ: ЧТО КАЖДЫЙ ВИД ДЕЙСТВИТЕЛЬНО ИМЕЕТ
 * ---------------------------------------------------------------------------
 *
 * Перечень снят с кода, а не придуман: ключи метаданных взяты из
 * `core/base_tools.cpp` и `core/subagent.cpp`, строки вывода — оттуда же.
 * Выдумывать ключи нельзя, поэтому чего нет — названо словами.
 *
 *   - `bash` (Command). Аргумент `cli`; в метаданных `exit_code`,
 *     `bytes`, `elapsed_ms`, `timed_out`, `truncated`, `output_path`.
 *     ЧЕГО НЕТ: `cancelled` — признак отмены человеком лежит только в
 *     ТЕКСТЕ ответа (метка `<shell_metadata>`), в метаданные он не
 *     копируется, и панель не имеет права выдумывать ключ. Показывается
 *     то, что есть: код возврата, таймаут, признак усечения и путь к
 *     полному выводу.
 *   - `read_file` (Preview). В метаданных `path`, `lines`, `offset`,
 *     `limit`, `more` и `loaded` (найденные рядом инструкции проекта).
 *     Тело превью — строки ВЫВОДА: содержимое файла приходит текстом, и
 *     второго источника у него нет.
 *   - `write_file`, `search_replace`, `edit_file`, `apply_patch` (Diff).
 *     Единственный источник правки — `metadata.filediff`, и он читается
 *     ОДНИМ вызовом `diff::filediff_from_metadata` (11.2, отклонение 149):
 *     второй разбор развёл бы номера строк и счётчики (Д2, Д12). Правки
 *     не несёт отказ («ничего не изменилось») — тогда виджет говорит
 *     это словами и показывает текст ответа.
 *   - `grep_search`, `glob`, `list` (List). Тело — строки вывода: у
 *     `grep_search` это `путь:строка  текст`, у `glob` и `list` — пути.
 *     ЧЕГО НЕТ: `grep_search` не пишет в метаданные НИЧЕГО, поэтому у него
 *     нет числа совпадений в шапке — панель не показывает то, чего
 *     инструмент не отдал, и не разбирает его текст на число (разбор
 *     чужого формата был бы вторым источником того же факта).
 *     У `glob` и `list` числа есть: `count`, `matched`, `truncated`,
 *     `depth`, `root`.
 *   - `task` (Task). В метаданных `agent`, `depth`, `task` (название
 *     задачи), `session_id`, `background`, а у нефоновой ветки ещё `steps`
 *     и `session_saved`. Вложенное дерево субагента строится из ФАЙЛА его
 *     сессии и рисуется ТЕМ ЖЕ деревом, что и основное (core/timeline.h) —
 *     второе дерево вызовов разъехалось бы с первым при первом же новом
 *     поле. Чего нет: у фоновой постановки нет ни `steps`, ни ответа —
 *     работа ещё не идёт, и виджет говорит об этом, а не показывает нули.
 *   - `todowrite` (Checklist). Пункты приходят АРГУМЕНТАМИ (`todos`:
 *     `{id, content, status, priority}`), а не метаданными: в метаданных
 *     лежат только `count` и `normalized` (сколько полей пришлось
 *     нормализовать). Чек-лист строится по аргументам — это единственное
 *     место, где виджет вообще читает аргументы, и читает ровно одно
 *     поле. Статусы берутся из `engine.h::kTodoStatuses`, то есть из
 *     того же списка, что и у инструмента: свой список значил бы, что
 *     панель считает готовым не то, что посчитал агент (Д2).
 *   - ВСЁ ОСТАЛЬНОЕ (Text). У 46 инструментов в метаданных НИЧЕГО нет:
 *     ни `git_*`, ни `docker_*`, ни `wp_*`, ни модулей python/devops не
 *     пишут ни одного поля (`core/tools_registry.cpp` добавляет
 *     `truncated`/`output_path` только при общем усечении). Поэтому
 *     «код возврата» для них недоступен в принципе, и виджет показывает
 *     заголовок инструмента и его текст вывода.
 *
 * ---------------------------------------------------------------------------
 * ПРАВИЛО БЛОКИРОВОК (то же, что у 11.2 и 11.3, и по той же причине)
 * ---------------------------------------------------------------------------
 *
 * `state_.mtx` НЕ держится под ImGui (правило 3 SESSION_START, дефект D1):
 * окно снимает снимок под локом и отпускает его, а виджеты строит уже без
 * лока. Поэтому снимок (`snapshot`) — это копия, а не ссылка: ссылка на
 * часть сессии после отпускания лока была бы чтением из-под чужого лока на
 * следующем кадре.
 *
 * Копируется ровно то, что виджету нужно, и по пределу: вывод обрезается по
 * СИМВОЛАМ (`text::utf8_prefix_chars`), потому что кириллица занимает два
 * байта на букту и обрез по байтам разрезал бы русский вывод пополам —
 * человек увидел бы битый байт (то же основание, что у якоря-реплики в
 * дереве, отклонение 155). Признак «обрезано» берётся ИЗ САМОГО ОБРЕЗА, а
 * не из сравнения длин: починенный битый байт занимает три байта вместо
 * одного, то есть на сломанном тексте результат обреза длиннее исходника и
 * сравнение сказало бы «обрезания не было» ровно там, где текст сломан.
 *
 * Снимок берётся только для РАСКРЫТЫХ веток и только в количестве
 * `limits::kMaxToolDisplayOpen`: закрытый вызов не читается вовсе, а тело
 * виджета нужно ровно тем веткам, которые человек раскрыл. Пропущенное
 * называется числом — молчаливое усечение выглядело бы как «показано всё».
 */

