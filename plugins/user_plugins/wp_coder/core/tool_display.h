/* ---------------------------------------------------------------------------
 * ВИД ВЫЗОВА
 * ---------------------------------------------------------------------------
 *
 * Перечислятель, а не строка: вид решает, какое тело у виджета, и решение
 * принимается по одному разы на вызов, а не ищется сравнением строк в
 * шести местах. При этом СВОЙ перечислятель статусов здесь не заводится
 * (Д2, Д12): вид — не состояние вызова, состояние живёт в `ToolState` и
 * рисуется таймлайном.
 */
enum class Kind {
    Command,    /* bash: команда, вывод, код возврата */
    Preview,    /* чтение файла: превью содержимого */
    Diff,       /* правка файла: виджет diff (11.1) */
    List,       /* поиск и обход: список совпадений или путей */
    Task,       /* субагент: вложенное дерево его ходов */
    Checklist,  /* план задачи: чек-лист пунктов */
    Text,       /* ОТКАТ: заголовок инструмента и текст его вывода */
};

const char* kind_name(Kind kind);

/* Вид по ИМЕНИ инструмента. Имя, которого в перечне нет, даёт `Text`:
 * инструмент из будущей итерации обязан показаться текстом, а не
 * исчезнуть из дерева. */
Kind kind_of(const std::string& tool_name);

/* Инструменты, оставленные откату `Text`, — полный перечень и тот же
 * источник, что и `kind_of`. Нужен окну (сколько инструментов виджет не
 * описывает) и проверке (перечень обязан совпадать с живым реестром). */
const std::vector<std::string>& text_kind_tools();

/* Сколько инструментов описано своим видом (не откатом). Тот же источник. */
size_t classified_tool_count();

/* ---------------------------------------------------------------------------
 * СНИМОК ВЫЗОВА — копия, снятая ПОД ЛОКОМ
 * ---------------------------------------------------------------------------
 *
 * Всё, что виджету нужно, и ничего лишнего: вывод обрезан по пределу,
 * метаданные скопированы как есть (они малы — вид diff у них единственный
 * тяжёлый, и он уже ограничен пределом файла патча). Ссылки на сессию
 * здесь быть не может: снимок переживает отпускание лока (см. шапку).
 */
struct CallView {
    std::string tool;
    std::string call_id;
    ToolState status = ToolState::Pending;
/* Текст вывода НЕПУСТ — отдельный признак, а не выведенный из вывода
     * факт: вызова ещё нет (Pending/Running), вывод пуст (инструменту
     * нечего писать), вывод очищен прореживанием (И7.9) и вызов отказан
     * (Error, текст в `error`) — это четыре разных состояния, и виджет
     * говорит о них разными словами. */
    bool has_output = false;
    std::string title;
    std::string error;
    bool output_cleared = false;
    /* Вывод САМИМ инструментом усечён (лимит вывода, И4.10) — и это не то
     * же, что обрез снимка по пределу показа. */
    bool truncated = false;
    /* Обрез СНИМКА по limits::kMaxToolDisplayChars: символы вывода в снимке
     * короче вывода инструмента. Признак приходит из самого обреза. */
    bool clipped = false;
    size_t clipped_chars = 0;   /* символов вывода в снимке */
    size_t output_chars = 0;    /* символов в ПОЛНОМ выводе инструмента */
    std::string output;
    json::JsonValue args;
    json::JsonValue metadata;
};

/* Снимок одного вызова. `max_chars` — предел вывода в снимке. */
CallView snapshot(const MessagePart& part, size_t max_chars);

/* ---------------------------------------------------------------------------
 * СБОРКА СНИМКОВ ДЛЯ ПАНЕЛИ
 * ---------------------------------------------------------------------------
 *
 * Отдельная функция, а не цикл в окне, по той же причине, что у проекции
 * дерева (11.3): правило «что и в каком порядке показывается» должно быть
 * проверяемым, а собранное в окне осталось бы непроверяемым.
 *
 * Раскрытые вызовы приходят списком идентификаторов — их знает окно, оно
 * ими и управляет (ImGui). Снимок берётся по одному проходу истории и
 * только для этих вызовов, в порядке ИСТОРИИ: порядок частей внутри хода и
 * есть смысл хода (то же основание, что у дерева).
 *
 * Предел `max_open` применяет ЭТА функция, и пропущенные считает она же:
 * второе место, где применяется предел, дало бы второе число рядом с
 * первым, и разошлись бы они тихо.
 *
 * И11.5: снимок на ИДЕНТИФИКАТОР один, сколько бы частей с ним ни было.
 * Окно ищет тело первым совпадением, поэтому лишний снимок не нарисовался бы
 * никогда, а слот предела занимал бы. Пропущенным повтор не считается:
 * пропущено то, что должно было показаться и не влезло. */
struct Snapshots {
    std::vector<CallView> views;
    size_t omitted = 0;   /* вызовов, не попавших в кадр */
};

Snapshots snapshot_open_calls(const std::vector<Message>& history,
                              const std::vector<std::string>& open_call_ids,
                              size_t max_open,
                              size_t max_chars);

/* ---------------------------------------------------------------------------
 * ТЕЛО ВИДЖЕТА: ГОТОВЫЕ СТРОКИ
 * ---------------------------------------------------------------------------
 *
 * Один формат на весь виджет, иначе окно собирало бы строки само и формат
 * разошёлся бы с тем, который показывают проверки (и golden-снапшоты 11.13).
 *
 * Для `Kind::Diff` заполняется `files` — список `diff::FileDiff`, и окно
 * рисует его УЖЕ НАПИСАННЫМ виджетом (11.1). Для остальных видов `files`
 * пуст, и всё содержимое — в `lines`.
 */
struct Widget {
    Kind kind = Kind::Text;
    std::string head;    /* шапка: чем закончился вызов, по-человечески */
    std::vector<std::string> lines;
    std::vector<diff::FileDiff> files;
    /* Оговорка словами: чего виджет НЕ показал и почему. Пустая — всё
     * показано. Оговорка обязательна там, где данные кончились: молчаливое
     * усечение выглядело бы как «это весь вывод». */
    std::string note;
    size_t omitted_lines = 0;   /* строк тела, оставшихся за пределом */
/* `Kind::Task`: сессия субагента, дерево ходов которой рисует окно.
     * Идентификатор идёт ОТДЕЛЬНЫМ полем, а не через метаданные, чтобы окно
     * не знало, что там за ключи (Д2) — тем же приёмом, что и `files`
     * вместо `metadata.filediff`.
     *
     * Три состояния, а не два признака «записан/не записан»: у фоновой
     * постановки поля `session_saved` НЕТ ВООБЩЕ (субагент ещё работает), и
     * прочитать «не записано» из отсутствия поля значило бы сказать человеку
     * «дерева не будет» там, где оно ещё просто не выросло. */
    std::string child_session;
    bool child_saved = false;     /* файл сессии записан и его можно читать */
    bool child_pending = false;  /* субагент ещё работает (фоновая постановка) */
};

/* Тело виджета по снимку. */
Widget build(const CallView& view);

/* Подпись панели: сколько виджетов показано и сколько раскрытых осталось за
 * кадром. */
std::string panel_head(size_t shown, size_t omitted);

/* Что панель показывает по типам: «виджет: 11 инструментов, текстом вывода —
 * 46». Один формат на панель, и числа берутся из ТОГО ЖЕ перечня, что и
 * `kind_of`: расхождение двух чисел означало бы, что перечень расползся. */
std::string kinds_line();

