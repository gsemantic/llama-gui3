#pragma once

/*
 * subagent.h — инструмент `task`: делегирование задачи субагенту (И8.7,
 * порт tool/task.ts).
 *
 * ЧТО ЭТОТ ФАЙЛ РЕШАЕТ
 * --------------------
 * До И8.7 реестр агентов был наполнен (И8.1–8.6), а цикл его не читал:
 * Engine::build_system_prompt склеивал базовый промпт, режим и навыки, и
 * агент был описанием без пользователя. Задача 8.7 — написать ПУТЬ, а не
 * только инструмент, и путь состоит из трёх решений:
 *
 *   1. КТО ВЫБИРАЕТ АГЕНТА. Модель, вызывая `task`, передаёт имя в
 *      `subagent_type`; имя нормализуется и ищется в реестре
 *      (AgentRegistry::find). Звать можно не всякого: агент с
 *      `mode: primary` — это выбор пользователя, а не делегирование, и
 *      скрытый агент — «не показывать», а не «выключить» (И8.1). Поэтому
 *      допустимые имена берутся из того же списка, из которого собирается
 *      выбор агента пользователем, — subagent_names(), а не из find().
 *
 *   2. КАК ПРОМПТ АГЕНТА ПОПАДАЕТ В СИСТЕМНЫЙ. Склеиванием базового
 *      промпта и промпта агента занимается Engine::build_system_prompt —
 *      тот же код, что и у хода сессии. Отдельная сборка «субагентского»
 *      промпта была бы второй копией одного и того же текста, и они
 *      разошлись бы при первом изменении базового промпта.
 *
 *   3. ПО ЧЕМУ РЕШАЕТ СУБАГЕНТ. Правила агента уже сложены поверх
 *      правил сессии (agent::Info, И8.4), и enforcement остаётся там же,
 *      где был, — в ToolRunner::run. Инструмент НЕ проверяет права
 *      ребёнка: он лишь подменяет область выполнения (RunScope), и всё
 *      остальное движок уже делает сам.
 *
 * ГРАНИЦА С ЗАДАЧАМИ, КОТОРЫЕ БУДУТ ПОСЛЕ
 * --------------------------------------
 *   8.8 — предел глубины стал настраиваемым (`wp_coder.subagent_depth`).
 *         Он и дальше проверяется здесь, потому что вопрос «не слишком ли
 *         глубоко» — это вопрос «кто сейчас выполняет ход» (RunScope),
 *         а не свойство инструмента; поменялся источник значения, а не
 *         поведение.
 *   8.9 — дочерняя сессия: `parent_id`, `title`, `task_id` возобновляет
 *         существующую. Здесь она написана: история ребёнка уходит в файл
 *         `sessions/sub/<ses_…>.json`, а `task_id` подставляет её в начало
 *         хода, и тогда prompt — это ПРОДОЛЖЕНИЕ того же разговора.
 *         Подкаталог `sub` выбран не «для порядка», а потому, что
 *         правило resume берёт самый свежий файл из каталога сессий
 *         нерекурсивно: файл ребёнка рядом с сессией человека стал бы
 *         «текущей сессией», и resume открыл бы диалог субагента.
 *         Побочный плюс: проверка «это задача субагента» получается
 *         бесплатно — идентификатор сессии человека в подкаталоге не
 *         лежит. Идентификатор задачи модель пока не видит (обёртка
 *         результата — 8.11), то есть продолжение работает, но узнать
 *         идентификатор можно только из уже сохранённой задачи; порядок
 *         задан планом, а не нами.
 *   8.11 — обёртка результата `<task id=… state=…><task_result>`.
 *         Здесь результат — итоговый текст субагента.
 *   8.13 — динамическое описание со списком субагентов. Здесь описание
 *         одно и постоянное, а список доступных имён попадает в текст
 *         ОТКАЗА (чтобы модель могла исправиться), и то и другое
 *         читается из subagent_names().
 *   8.14 — `background: true`. Объявлено в схеме и отклонялось явным
 *         отказом; теперь работает: вызов возвращает сразу, задача
 *         выполняется между ходами родителя, а её результат приходит в
 *         диалог синтетическим сообщением.
 *
 * ГДЕ ВЫПОЛНЯЕТСЯ ФОНОВАЯ ЗАДАЧА (И8.14) — ВЫБОР, А НЕ ТЕХНИКА
 * -------------------------------------------------------
 * Вариантов было два (решение принято вместо «посмотреть»):
 *
 *   а) ОЧЕРЕДЬ, РАЗБИРАЕМАЯ МЕЖДУ ХОДАМИ РОДИТЕЛЯ. Выбран.
 *   б) ХОД В СВОЁМ ПОТОКЕ, а область — переделать в «область хода».
 *
 * Почему не (б): область выполнения одна на весь движок (RunScope в
 * EngineState), а ход идёт на одном потоке. Ребёнок, поставивший свою
 * область поверх родительской, отдал бы РОДИТЕЛЮ enforcement по правилам
 * РЕБЁНКА — то есть тихо и в ту сторону, где опаснее: ограничение
 * «write: deny» у субагента запретило бы правки родителю, а «*: allow» у
 * ребёнка разрешил бы их. Чтобы этого избежать, область должна стать
 * «областью хода» — то есть перестать быть полем синглтона и стать
 * параметром каждого хода: правка цикла, ToolRunner::run, PermissionGate,
 * сборки системного промпта и списка субагентов. Это больше работы, чем
 * вся задача 8.14, и ломает единственную enforcement-точку, которая
 * сейчас специально одна (И8.7).
 *
 * Чем платим за (а), и это названо словами, потому что модель будет
 * читать это в описании инструмента: «фон» здесь означает «не держит
 * текущий ход до своего конца», а НЕ «работает одновременно с
 * родителем». Субагент стартует, когда ход родителя закончился, а его
 * результат приходит отдельным сообщением в следующем ходе. Написать
 * «работает параллельно» было бы враньём в описании инструмента.
 *
 * Отсюда и третья часть решения: доставить результат — значит начать
 * ход, а ход без запроса человека стоит денег. Цепочка таких ходов
 * ограничена (limits::kBackgroundTurnLimit) и обнуляется любым запросом
 * человека.
 *
 * Правила ребёнка снимаются В МОМЕНТ ПОСТАНОВКИ, а не выполнения: к
 * моменту выполнения область принадлежит сессии, и фоновая задача,
 * поставленная субагентом, выполнилась бы по правилам сессии — то есть
 * её внук получил бы права не того, кто звал (см. BackgroundTask).
 */

#include "agent_registry.h"
#include "engine.h"

#include <memory>
#include <string>
#include <vector>

namespace coder {

/* Регистрация инструмента `task` в реестре. Зовётся из
 * register_base_tools(): инструмент принадлежит базовому набору, и
 * заводить для него отдельный вход регистрации значило бы забыть его в
 * одном из вызывающих (плагин, тесты). */
void register_task_tool();

/* Список субагентов одной строкой — для текста отказа. Общий с
 * динамическим описанием (8.13), чтобы перечислить агентов можно было
 * было одним вызовом из одного места. */
std::string subagent_names_line();

/* Выполнить задачи, поставленные в фон, и доставить их результаты в
 * сессию (И8.14).
 *
 * Забирает очередь целиком под локом и выполняет задачи ПО ОДНОЙ, уже без
 * него: запрос к модели идёт без лока движка (D1 — висящий GUI). Область
 * выполнения подменяется на время каждой задачи (ScopedAgentScope) и
 * возвращается, то есть область не конкурентна ни с чем.
 *
 * Результаты — ОДНО синтетическое сообщение пользователя в конце: модель
 * получает их одним куском, и одна доставка на сколько угодно задач, а не
 * по ходу на задачу. Возвращает true, если сообщение доставлено.
 *
 * При отмене («стоп») результаты в сессию НЕ кладутся: цикл на отмене
 * чистит историю, и доставка в пустую сессию воскресила бы диалог, от
 * которого человек отказался. Дочерние сессии при этом сохраняются —
 * работа сделана, и её можно продолжить по идентификатору. */
bool run_background_tasks(Engine& engine);

/* --- Правила ребёнка (И9.7) ---
 *
 * ША, А НЕ СТРОКА В ИНСТРУМЕНТЕ. Здесь решается, каким профилем harness и
 * какими правилами живёт ребёнок, и решает это владелец правил (Info,
 * И8.4), а не инструмент `task`. Проверка доходит до этой функции, а не
 * до инструмента: прогон мутаций показал, что строка
 * «Info::for_subagent(..., profile.get())» внутри инструмента не
 * закрывается ничем — до правил ребёнка оттуда не достучаться, не
 * поднимая worker-поток, а именно этот шов и есть привязка профиля к
 * конфиг-агенту (строка задачи 9.7).
 *
 * base — ПРАВИЛА СЕССИИ; сужает их конструктор (for_subagent), а не
 * вызывающий. diags — необязателен, и в него попадает причина, если
 * профиль назван, но не читается.
 *
 * Нечитающийся профиль — НЕ отказ: ребёнок работает со своими правилами,
 * а причина уходит в diags. Отказ был бы нечестным — необязательная
 * настройка превратилась бы в требование, и зовёшь вполне известного
 * агента, а он молчит. */
std::shared_ptr<agent::Info> build_child_info(
    Engine& engine, const AgentDef& def,
    std::vector<AgentLoadDiag>* diags = nullptr);

} // namespace coder
