#pragma once

/*
 * subagent.h — инструмент `task`: делегирование задачи субагенту (И8.7,
 * порт tool/task.ts).
 *
 * ЧТО ЭТОТ ФАЙЛ РЕШАЕТ
 * --------------------
 * До И8.7 реестр агентов был наполнен (И8.1–8.6), а цикл его не читал:
 * Engine::build_system_prompt склеивал базовый промпт, режим и навыки, и
 * агент был описанием без пользователя. Задача 8.7 — написать ПУТЬ, а не
 * только инструмент, и путь состоит из трёх решений:
 *
 *   1. КТО ВЫБИРАЕТ АГЕНТА. Модель, вызывая `task`, передаёт имя в
 *      `subagent_type`; имя нормализуется и ищется в реестре
 *      (AgentRegistry::find). Звать можно не всякого: агент с
 *      `mode: primary` — это выбор пользователя, а не делегирование, и
 *      скрытый агент — «не показывать», а не «выключить» (И8.1). Поэтому
 *      допустимые имена берутся из того же списка, из которого собирается
 *      выбор агента пользователем, — subagent_names(), а не из find().
 *
 *   2. КАК ПРОМПТ АГЕНТА ПОПАДАЕТ В СИСТЕМНЫЙ. Склеиванием базового
 *      промпта и промпта агента занимается Engine::build_system_prompt —
 *      тот же код, что и у хода сессии. Отдельная сборка «субагентского»
 *      промпта была бы второй копией одного и того же текста, и они
 *      разошлись бы при первом изменении базового промпта.
 *
 *   3. ПО ЧЕМУ РЕШАЕТ СУБАГЕНТ. Правила агента уже сложены поверх
 *      правил сессии (agent::Info, И8.4), и enforcement остаётся там же,
 *      где был, — в ToolRunner::run. Инструмент НЕ проверяет права
 *      ребёнка: он лишь подменяет область выполнения (RunScope), и всё
 *      остальное движок уже делает сам.
 *
 * ГРАНИЦА С ЗАДАЧАМИ, КОТОРЫЕ БУДУТ ПОСЛЕ
 * --------------------------------------
 *   8.8 — лимит глубины станет настраиваемым. Здесь он уже есть и равен
 *         единице: без него инструмент позволял бы вкладывать вызовы в
 *         вызовы неограниченно, то есть отдать модели рекурсивный
 *         генератор LLM-запросов. Проверка — одна функция, и 8.8 меняет
 *         у неё значение, а не пишет вторую.
 *   8.9 — дочерняя сессия (`parent_id`, `title`, `task_id` возобновляет
 *         существующую). Здесь история ребёнка ЛОКАЛЬНА и не сохраняется,
 *         а `task_id` объявлен в схеме (портовская подпись) и честно
 *         отклоняется: объявленный и молча проигнорированный параметр —
 *         хуже, чем явный отказ, потому что модель будет считать, что
 *         продолжение сработало.
 *   8.11 — обёртка результата `<task id=… state=…><task_result>`.
 *         Здесь результат — итоговый текст субагента.
 *   8.13 — динамическое описание со списком субагентов. Здесь описание
 *         одно и постоянное, а список доступных имён попадает в текст
 *         ОТКАЗА (чтобы модель могла исправиться), и то и другое
 *         читается из subagent_names().
 *   8.14 — `background: true`. Объявлен в схеме и отклоняется, см. 8.9.
 */

#include <string>

namespace coder {

/* Регистрация инструмента `task` в реестре. Зовётся из
 * register_base_tools(): инструмент принадлежит базовому набору, и
 * заводить для него отдельный вход регистрации значило бы забыть его в
 * одном из вызывающих (плагин, тесты). */
void register_task_tool();

/* Список субагентов одной строкой — для текста отказа. Общий с
 * динамическим описанием (8.13), чтобы перечислить агентов можно было
 * было одним вызовом из одного места. */
std::string subagent_names_line();

} // namespace coder
