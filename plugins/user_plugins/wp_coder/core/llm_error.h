#pragma once

/*
 * llm_error.h — Таксономия ошибок провайдера (И12.5, порт
 * `packages/core/src/v1/session.ts:36`).
 *
 * ЧТО БЫЛО НЕ ТАК
 * ----------------
 * Сбои приходили от провайдера ТЕКСТОМ, и текст classifiesлся в двух местах
 * независимо друг от друга:
 *
 *   - `LlmResponse::reduce` по умолчанию ставил `FailureKind::Provider`
 *     всему, что пришло событием ProviderError, кроме явной отмены;
 *   - ретраи в `src/plugin_main.cpp` решали «повторять ли» своим
 *     `is_retryable_error`, который искал подстроки «429», «5xx»,
 *     «таймаут» прямо в тексте ошибки.
 *
 * Два разбора одного и того же текста в двух местах — это D12: они
 * разъедутся при первой же правке. И разъехались бы не abstract, а
 * видимо: классификатор ретраев считал «исчерпан» (контекст закончился)
 * ПОВТОРЯЕМЫМ, потому что это стояло в одном списке с «429». Повторять
 * запрос, который не помещается в контекст, бессмысленно — он не
 * поместится и в третий раз; лечится это сжатием истории, а не
 * ожиданием.
 *
 * Что пользователю показывалось — тоже следствие этого: «ошибка сети» на
 * месте «ключ недействителен» и на месте «контекст исчерпан». С И7.5 один
 * из случаев (ContextOverflow) был выделен, остальные остались в
 * Provider, и И7.5 прямо оставил полную таксономию за И12.5.
 *
 * ЧТО СТАЛО
 * ---------
 * ОДИН классификатор на текст отказа, который возвращает пару
 * «ВИД СБОЯ + повторяемо ли». Вид едет на событии (LlmEvent), повторяемость
 * — тоже (без неё поле было бы мёртвым: единственное место, где решают
 * «повторять», это цикл ретраев, и он должен читать то же, что видит UI).
 *
 * ВидыFailureKind расширены тремя: Auth, OutputLength, ContentFilter.
 * Прежние Provider / Tool / Aborted / ContextOverflow остаются — переименование
 * сломало бы всех потребителей ради cosmetics.
 *
 * ПОЧЕМУ КЛАССИФИКАЦИЯ ПО ТЕКСТУ, А НЕ ПО HTTP-КОДУ
 * -------------------------------------------------
 * Потому что кода там нет. `llm_chat_messages` отдаёт `{"ok":0,"error":"…"}` —
 * это всё, что есть на этом уровне; отдельного поля со статусом ни в ABI, ни
 * в разборе ответа нет. Порт поступает так же: его «7 семейств регулярных
 * выражений» для повторяемости (это И12.6) работают по строке. То есть
 * текст здесь — не суррогат, а единственный носитель.
 *
 * ЧЕСТНО ОБ ОГРАНИЧЕНИИ. Классификация ищет подстроки, и подстрока может
 * прийти из ТЕКСТА ЗАПРОСА: некоторые провайдеры кладут в `error` эхо
 * запроса. Тогда «429» в сообщении человека станет «повторяемым». Это
 * ограничение метода, а не ошибка реализации, и оно записано здесь, чтобы
 * следующая сессия не искала его заново. Лечится оно не внимательностью к
 * regex, а отдельным полем со статусом в ABI — и это отдельная задача.
 *
 * ПОВТОРЯЕМОСТЬ ВЫВОДИТСЯ ИЗ ВИДА, А НЕ ЖИВЁТ ОТДЕЛЬНОЙ ТАБЛИЦЕЙ
 * ----------------------------------------------------------
 * Из пяти видов повторяем только два: сетевые сбои с маркером
 * транзиентности. Остальные не повторяются по построению — ключ не
 * станет действительным, фильтр контента не снимется, контекст не уменьшится.
 * Если бы «повторяемость» была своей таблицей, её второй экземпляр
 * разошёлся бы с первым при первом же новом виде сбоя — то есть новый вид
 * по умолчачал бы стал бы «неповторяемым» тихо и правильно, и читающий не
 * заметил бы, что решает не то.
 */

#include "llm_event.h"

#include <string>

namespace coder {

/* Классифицированный отказ провайдера: ЧТО сломалось и повторять ли. */
struct ProviderFailure {
    FailureKind kind = FailureKind::Provider;
    bool retryable = false;
};

/* Вид отказа по ТЕКСТУ, который прислал провайдер.
 *
 * Порядок проверки — от частного к общему: «ключ недействителен» и
 * «контекст исчерпан» оба лежат в Provider, и кто проверится первым,
 * тот и победит. Обратный порядок отдавал бы всё в Provider, то есть
 * вернул бы ровно то, что было до И12.5.
 *
 * Пустая строка — Provider без повтора: отсутствие причины не повод
 * повторять (иначе «LLM-ошибка (ok=0)» превратилась бы в три попытки). */
ProviderFailure classify_provider_failure(const std::string& error);

/* Вид по finish_reason провайдера, для хода, который ОТВЕТИЛ.
 *
 * Отдельная функция, потому что это другой вход: `length` и
 * `content_filter` приходят на успешном ответе, где `error` пуст, и
 * искать их в тексте ошибки бессмысленно. Именно поэтому «упёрлась в
 * лимит токенов» до И12.5 было видно только как Status-сообщение в цикле,
 * а не как вид сбоя. */
FailureKind failure_for_finish_reason(const std::string& finish_reason);

} // namespace coder