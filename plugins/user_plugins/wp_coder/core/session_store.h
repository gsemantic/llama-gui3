#pragma once

/*
 * session_store.h — сессия на диске (И5.6).
 *
 * Формат меняется целиком, и это осознанно: история перестала быть
 * списком строк и стала структурой (И5.4). Старый файл
 * `<data_dir>/wp_coder/session.json` хранил массив {role, content}, где
 * принадлежность выражения инструмента выражалась префиксом
 * «RESULT [read_file]:» — то есть текстом, который можно и подделать, и
 * испортить. Части, parent_id и состояние вызова в нём не помещались
 * физически.
 *
 * Что из этого следует и что НЕ следует:
 *   - resume-история, записанная версией до И5, не подхватится. Старый
 *     файл не удаляется, но и не читается. Миграция одного формата в
 *     другой ради истории, которую цикл всё равно переписывает на И5.7,
 *     стоила бы кода, который придётся удалить через одну задачу;
 *   - файл ПИШЕТСЯ атомарно (временный + rename). Обрезанный файл после
 *     падения читался бы как «пустая сессия» и затерел бы историю при
 *     следующем сохранении (D19);
 *   - версия формата обязательна и проверяется. Файл, записанный более
 *     новой версией плагина, читается как «слишком новый», а не как
 *     «частично валидный»: иначе старая версия молча выбросила бы то,
 *     чего не знает, и записала поверх свой файл.
 */

#include "id_prefix.h"
#include "json.h"
#include "message.h"

#include <string>
#include <vector>

namespace coder {

/* Версия формата. Повышается при несовместимом изменении. */
inline constexpr int kSessionFileVersion = 1;

/* Содержимое файла сессии. */
struct SessionFile {
    int version = kSessionFileVersion;
    std::string session_id;
    std::vector<Message> messages;
};

/* Сессионное хранилище: сериализация и файл.
 *
 * Все методы статические и не держат состояния: хранилище не владеет
 * историей, её владеет Engine. Иначе появился бы ещё один владелец
 * истории рядом с state_.session — два источника истины, которые
 * разъедутся (болезнь D12 в применении к данным). */
class SessionArchive {
public:
    /* --- Сериализация --- */

    /* Превращение в JsonValue. Только заполненные поля вида: файл должен
     * оставаться читаемым глазами, а не «простыней с девятью null». */
    static json::JsonValue to_json(const SessionFile& session);

    /* Разбор. При проблемах возвращает false и пишет причину в error.
     *
     * warnings — необязательный список «что поняли не полностью»:
     * неизвестный вид части, неизвестное состояние вызова, старая
     * версия формата. Такое НЕ роняет загрузку (одна незнакомая часть не
     * должна обнулять историю) и НЕ проходит молча: вызывающий печатает
     * предупреждения, и пропажа видна. */
    static bool from_json(const json::JsonValue& value, SessionFile& out,
                          std::string* error,
                          std::vector<std::string>* warnings = nullptr);

    /* --- Файл --- */

    /* <data_dir>/wp_coder/sessions/<session_id>.json */
    static std::string file_path(const std::string& data_dir,
                                 const std::string& session_id);

    /* Текущий файл сессии: самый свежий по времени изменения, а при
     * равном времени — с большим номером идентификатора.
     *
     * Почему так, а не «файл с именем, записанным в настройке»: указатель
     * на активную сессию стал бы вторым местом, где живёт один и тот же
     * факт, и при рассинхронизации resume открыл бы не тот диалог.
     * Одновременно активных сессий у плагина всё равно одна.
     *
     * Развязка по номеру, а не по имени: точность времени файла бывает в
     * секунду, и две сессии подряд получают равные времена, а имя
     * ses_000000000009 «новее» ses_000000000010 при сравнении строк. */
    static std::string current_file(const std::string& data_dir);

    /* Запись (атомарная) и чтение. Обе возвращают false с причиной. */
    static bool save(const std::string& path, const SessionFile& session,
                     std::string* error);
    static bool load(const std::string& path, SessionFile& out,
                     std::string* error,
                     std::vector<std::string>* warnings = nullptr);
    static bool remove(const std::string& path);
};

} // namespace coder
