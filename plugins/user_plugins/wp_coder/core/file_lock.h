#pragma once

/*
 * file_lock.h — сериализация правки одного файла (И4.5, порт opencode
 * Semaphore(1) на filePath).
 *
 * Зачем это, если «агент ходит по шагам»:
 *
 * 1. Правку файла запускает НЕ ТОЛЬКО агент. Engine::pending_apply
 *    вызывается из UI-потока по кнопке «применить» и тоже пишет файл.
 *    Оба действия пишут один и тот же файл из двух потоков, а каждое —
 *    цикл «прочитал → изменил → записал». Без блокировки возможен сценарий
 *    «прочитал A, дописал своё, записал поверх чужой правки» — и файл
 *    остаётся с правкой одной стороны, без всякой ошибки.
 *
 * 2. Инструменты ждут разрешения пользователя (PermissionGate ждёт
 *    кондивар). Пока агент висит на вопросе, UI вполне может применить
 *    отложенную правку того же файла.
 *
 * То есть блокировка нужна не «на всякий случай», а на конкретном
 * известном пути из двух потоков в одну файловую систему.
 *
 * Реализация — полосы (striping), а не карта путей: 64 мьютекса на
 * хеше пути. Карта требовала бы общего мьютекса и weak_ptr, а плюс
 * единственное — не блокировать несвязанные файлы — тут не требуется:
 * два разных файла, попавшие на одну полосу, просто ждут друг друга
 * миллисекунды. Побочных эффектов у полос меньше: ничего не выделяется,
 * ничего не освобождается, ничего не может утечь.
 *
 * Порядок блокировок: file_lock берётся ВНУТРИ state_.mtx (pending_apply
 * держит state_.mtx) или вовсе без него. Наоборот нельзя: код, уже
 * держащий state_.mtx, не вправе ждать ещё и файловое семафор, если
 * где-то ещё путь блокировок ведёт в обратную сторону.
 */

#include <string>

namespace coder {
namespace file_lock {

/* RAII-блокировка по пути. Держится всё время «прочитал → изменил →
 * записал», то есть создавать его надо ДО чтения файла. */
class Guard {
public:
    explicit Guard(const std::string& path);
    ~Guard();

    Guard(const Guard&) = delete;
    Guard& operator=(const Guard&) = delete;

private:
    void* slot_;
};

} // namespace file_lock
} // namespace coder
