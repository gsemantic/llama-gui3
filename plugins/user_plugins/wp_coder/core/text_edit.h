#pragma once

/*
 * text_edit.h — текст файла как строки + сохранение формата (И4.2, И4.3,
 * И4.5).
 *
 * Зачем отдельный тип, если есть std::getline: правка файла должна НЕ
 * менять его формат. Два свойства ломаются молча, и оба выглядят как
 * «агент испортил файл, а я не понимаю почему»:
 *
 *   - BOM (EF BB BF). Windows-редактор и часть CI ожидают его в .php и
 *     .json; UTF-8 без BOM для них — уже другой файл. Перезапись без
 *     BOM ломает сравнение и подпись.
 *   - CRLF. Скрипты проверки (git diff --check, .gitattributes) считают
 *     файл с изменёнными переносами изменённым целиком: замена двух
 *     строк превращается в «переписан весь файл».
 *
 * Поэтому единственное место, где файл читается на правку и собирается
 * обратно, — здесь. И apply_patch (И4.2), и каскад заменителей (И4.3),
 * и write_file (И4.5) идут через него, а не каждый своими getline.
 *
 * Про границы строк: пустой файл — это ноль строк, а не одна пустая.
 * Иначе apply_patch дописал бы в него лишний перевод строки, и
 * `git diff` показывал бы изменение файла, которого не было.
 */

#include <string>
#include <vector>

namespace coder {

struct TextFile {
    /* "\xEF\xBB\xBF" или пусто. */
    std::string bom;
    /* Файл использует CRLF. Определяется по первому найденному CRLF. */
    bool crlf = false;
    /* Строки без завершающих \n и \r. */
    std::vector<std::string> lines;
    /* Заканчивается ли файл переводом строки. */
    bool trailing_newline = true;
};

/* Разобрать содержимое файла. */
TextFile split_text(const std::string& raw);

/* Собрать обратно, сохранив BOM, стиль переносов и завершающий перевод. */
std::string join_text(const TextFile& f);

/* Равенство строк с игнором хвостовых пробелов и \r. Второй проход
 * (после точного) нужен, потому что модели присылают окно файла, скопированное
 * из редактора с визуальными отступами. */
bool same_line(const std::string& a, const std::string& b);

/* Убрать хвостовые пробелы и \r — для сравнения и для записи. */
std::string trim_end(const std::string& s);

/* --- И4.3: каскад заменителей (порт opencode tool/edit.ts:682) ---
 *
 * До И4 замена требовала БУКВАЛЬНОГО совпадения, и это превращалось в
 * цикл неудачных шагов: модель переписывает отступы, забывает
 * завершающий перевод строки, присылает «\n» вместо перевода — и получает
 * «текст не найден», не понимая, что не так. opencode проходит девять
 * стадий, и ошибка выносится только на исчерпании всех.
 *
 * Стадии идут от строгой к размытой, и это порядок безопасности:
 * сначала точное совпадение, потом разница только в хвостовых пробелах,
 * и лишь затем — нечёткое (BlockAnchor) и нормализующее текст. Каждая
 * стадия обязана дать РОВНО ОДНО место замены: «нашлось, но в трёх
 * местах» — это не замена, а отказ с требованием добавить контекст.
 *
 * MultiOccurrence (замена всех вхождений) включается только явным
 * replace_all: иначе «заменить return» молча переписал бы пол-файла, а
 * модель об этом узнала бы из diff постфактум.
 */
enum class EditStrategy {
    Simple,
    LineTrimmed,
    BlockAnchor,
    WhitespaceNormalized,
    IndentationFlexible,
    EscapeNormalized,
    TrimmedBoundary,
    ContextAware,
    MultiOccurrence,
};

const char* edit_strategy_name(EditStrategy s);

/* И4.4 — порог непропорционального спана (порт edit.ts:731).
 *
 * Правка, где искомых строк заметно больше, чем новых, — это не правка,
 * а переписывание файла целиком, замаскированное под «замену фрагмента».
 * Модель так делает, когда не может найти нужное место: прислать «весь
 * файл» проще, чем три строки вокруг цели. Цена — тихая перезапись
 * чужого кода, видна только в diff.
 *
 * Формула из плана: searchLines >= max(oldLines + 3, oldLines * 2), где
 * searchLines — размер ЗАМЕНЯЕМОГО блока, а oldLines — размер нового
 * (названия в плане перепутаны относительно интуиции; подстановка «как
 * есть» дала бы условие, которое не выполняется никогда). Смысл обеих
 * частей: «+3» не даёт отказать честной правке маленького блока, а «* 2»
 * не даёт протащить правку, которая в разы больше исходной. */
inline constexpr size_t kMaxSpanRatio = 2;

struct EditRequest {
    std::string old_text;
    std::string new_text;
    /* Заменить все вхождения. Без этого флага каскад на множественных
     * совпадениях заканчивается ошибкой — как раньше. */
    bool replace_all = false;
    /* И4.4: порог «непропорционального спана». 0 — проверка выключена
     * (для внутренних вызовов, где размер задан осознанно). */
    size_t max_span_ratio = kMaxSpanRatio;
};

struct EditResult {
    bool ok = false;
    /* Человекочитаемая причина отказа + что делать. */
    std::string error;
    EditStrategy used = EditStrategy::Simple;
    /* Сколько мест заменено (1 или N при replace_all). */
    size_t occurrences = 0;
    /* Номер первой затронутой строки, 1-based — для отчёта и diff. */
    size_t line = 0;
    TextFile file;
};

/* Применить замену к файлу. Ничего не пишет: возвращает новое содержимое
 * либо причину отказа. */
EditResult apply_edit(const TextFile& in, const EditRequest& req);

/* Сходство двух строк: 1 — совпали, 0 — ничего общего. Используется
 * только нечёткой стадией BlockAnchor, поэтому дёшево: отсекаем по длине
 * и первому символу до того, как считать расстояние. */
double line_similarity(const std::string& a, const std::string& b);

} // namespace coder
