#pragma once

/*
 * llm_source.h — источник событий: хост + протокол его ответа (И5.7).
 *
 * Зачем файл, если «спросить модель» — одна строка. До И5.7 строка была
 * не строкой, а ПРОТОКОЛОМ: ответ приходил строкой, внутри которой блок
 * вызова инструмента приходилось вырезать шестью эвристиками
 * (core/tool_protocol.cpp), а цикл знал и про `extract_action`, и про
 * `parse_action`, и про строку «RESULT [инструмент]:» для результата.
 * Три места, где одно и то же описано по-разному, — и есть та рассинхронизация,
 * которая стоила D2 (инструмент есть, а о нём не сказано) и D12 (версия в
 * четырёх файлах).
 *
 * Здесь протокол собран в одном месте и наружу выдаёт только события
 * (core/llm_event.h). Дальше — И5.8 (условие завершения) и И6.1
 * (стриминг): циклу не придётся меняться, потому что «хост ответил»
 * и «хост прислал поток событий» — это один и тот же вызов
 * llm_source::fetch с той же подписью.
 *
 * Что здесь НЕ живёт и почему:
 *   - цикл, условие завершения, счётчик шагов: это политика агента,
 *     она в AgentLoop (core/agent_components.cpp);
 *   - права и режимы инструментов: enforcement-point один на весь
 *     плагин — ToolRunner::run (core/agent_components.cpp);
 *   - знание о том, что у провайдера бывает кэш токенов: это Usage
 *     (core/llm_event.h), здесь только передаются числа провайдера.
 *
 * Граница с И6.1. Сейчас fetch кладёт в events вектор, собранный из
 * одного ответа целиком. Стриминг заменит наполнение, а не подпись:
 * цикл получит те же события, только по мере их поступления. Поэтому
 * цикл сворачивает события самостоятельно (LlmResponse::reduce) и не
 * полагается на «вектор уже полный».
 */

#include "engine.h"
#include "llm_event.h"
#include "message.h"

#include <string>
#include <vector>

namespace coder {
namespace llm_source {

/* Один ход: спросить хост и отдать поток событий ответа.
 *
 * history — сообщения для модели без системного промпта; собираются
 * функцией to_model_messages (core/message.h), а не хранятся в движке
 * как строки.
 *
 * ok=false означает «хост не ответил»; тогда events не пуст и содержит
 * ProviderError с текстом причины — вызывающий не обязан знать, откуда
 * взялась ошибка (сеть, таймаут, отказ режима на стороне хоста).
 *
 * Единственное место, где живёт запасной путь «старый хост без
 * llm_chat»: Planner, цикл и хвостовой ход спрашивали одинаково, и три
 * копии этого кода разъехались бы (D12). Старый хост получает одну
 * строку — последнюю реплику пользователя, — и метрики остаются нулевыми.
 */
bool fetch(const HostCallbacks& cb, const std::string& sys_prompt,
           const std::vector<ModelMessage>& history,
           std::vector<LlmEvent>& events);

/* Ответ, полученный целиком, → события.
 *
 * Вызов без стриминга (И6.1): провайдер отдал одну строку, в которой
 * блок вызова инструмента неотличим от прозы. Адаптер разрезает её на
 * TextDelta и ToolCall — и это единственное место в плагине, где
 * протокол wp_action разбирается для цикла.
 *
 * Порядок событий: StepStart, [TextStart/TextDelta/TextEnd],
 * [ToolInputStart/ToolInputDelta/(ToolCall)/ToolInputEnd/ToolError],
 * StepFinish, Finish. Он совпадает с порядком, в котором провайдер
 * присылает то же самое при стриминге, поэтому свёртка от порядка не
 * зависит, а тест на события — не на этот конкретный список.
 */
void reply_to_events(const LlmReply& reply, std::vector<LlmEvent>& events);

/* Свёртка потока в ответ. Обёртка над LlmResponse::reduce (И5.3): ею
 * пользуются все, кто получил события, и писать цикл свёртки вручную
 * в трёх местах — значит забыть его в четвёртом. */
LlmResponse fold(const std::vector<LlmEvent>& events);

} // namespace llm_source
} // namespace coder
