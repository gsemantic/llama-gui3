#pragma once

/*
 * hotkeys.h — перенос горячих клавиш (И11.11).
 *
 * ---------------------------------------------------------------------------
 * ПОЧЕМУ КЛАВИШИ ЧИТАЕТ САМ ПЛАГИН, А НЕ ХОСТ
 * ---------------------------------------------------------------------------
 *
 * У хоста есть `command_register(..., shortcut)`, и он выглядит ровно тем,
 * чем нужен: `src/plugins/plugin_manager.cpp:257` честно кладёт строку в
 * `CommandManager::registerShortcut`. Дальше её никто не читает.
 * `CommandManager::executeShortcut` (src/ui/command_manager.cpp:64) —
 * единственный читатель `shortcuts_` — не имеет НИ ОДНОГО вызывающего во всём
 * репозитории, а `AdvancedMenuSystem::handleKeyboardShortcuts`
 * (advanced_menu_system_rendering.cpp:247) обходит меню и ниже комментария
 * «In a real implementation, you'd parse the shortcut string» не делает
 * ничего. То есть строка «Ctrl+O» в меню выглядит как рабочее сочетание и не
 * является им.
 *
 * Это ровно тот класс, что D22 («зелёный свет в пустоту») и D23
 * («`LlmClient` не вызывался НИГДЕ в боевом коде»): механизм написан,
 * подключён и не работает. Регистрация сочетания дала бы зелёную сборку,
 * работающее меню и ноль нажатий.
 *
 * Поэтому окно читает клавиши само — в своём же кадре ImGui, где оно и так
 * рисует. Побочный факт, который стоит знать: `Ctrl+O` в хосте занят
 * (`registerShortcut("Ctrl+O", "open_file")`, command_manager.cpp:483), так
 * что при оживленииdispatch'а хоста это сочетание столкнётся. Сегодня обе
 * половины мертвы, и решение не в том, чтобы ждать этого.
 *
 * ---------------------------------------------------------------------------
 * ЧТО РЕШАЕТ ФАЙЛ, А ЧТО ОКНО
 * ---------------------------------------------------------------------------
 *
 * Здесь — ЧТО означает нажатие и КОГДА оно не должно срабатывать. Окно
 * (`ui/coder_window.cpp`) — только переводит состояние ImGui в `Event` и
 * выполняет вернувшееся `Action`. Тот же расклад, что у `cancel.h`,
 * `timeline.h` и `token_panel.h`: решение в core, иначе его нечем проверять.
 *
 * ---------------------------------------------------------------------------
 * ГЛАВНОЕ ПРАВИЛО: КЛАВИША ДЕЛАЕТ РОВНО ТО ЖЕ, ЧТО КНОПКА
 * ---------------------------------------------------------------------------
 *
 * `Esc` останавливает ровно тогда, когда `cancel::Panel::visible` — то есть
 * когда `cancel::phase_of` даёт `Working` или `Waiting`. Иначе нажатие
 * обещало бы отмену того, чего нет: ровно та ложь, которую закрыл И11.10,
 * только теперь с клавиатуры. Фаза берётся из `cancel`, а не вычисляется
 * здесь: второе место правды о том, «есть ли что отменять», разъехалось бы
 * при первой правке `phase_of` (тот же класс, что Д2).
 *
 * `Ctrl+Enter` снимает план-режим — ровно то, что делает его чекбокс, и
 * только когда режим включён: одобрять нечего, если плана нет.
 * `Ctrl+B` переключает `s_show_details` — ТОТ ЖЕ флаг, что у чекбокса, а не
 * его копия. `Ctrl+O` раскрывает «Правки по вызовам» и поднимает окно.
 *
 * ---------------------------------------------------------------------------
 * ПОЧЕМУ ПОЛЕ ВВОДА ПОБЕЖДАЕТ
 * ---------------------------------------------------------------------------
 *
 * `Esc`, `Ctrl+O`, `Ctrl+Enter` и `Ctrl+B` набраны в самых обычных полях
 * этого же окна (пароль приложения, каталог проекта, промпт агента) — и
 * `Ctrl+Enter` в многострочном поле вставляет перевод строки. Если бы
 * клавиша сработала там, она украла бы нажатие у поля: `Esc` отменял бы
 * правку поля и заодно глушил агента, а `Ctrl+B` сворачивал бы детали посреди
 * набора. Поэтому при активном элементе не срабатывает НИЧЕГО, и это
 * проверяется отдельной строкой, а не «по ощущениям».
 */

#include "cancel.h"

#include <ostream>
#include <string>
#include <vector>

namespace coder {
namespace hotkeys {

/* Клавиша — не код ImGui и не SDL: core не знает ни про того, ни про другого,
 * иначе файл перестал бы проверяться без их заголовков. Окно переводит. */
enum class Key {
    None = 0,
    O,       /* Ctrl+O — правки по вызовам */
    B,       /* Ctrl+B — свернуть/развернуть детали */
    Enter,   /* Ctrl+Enter — одобрить план (KeypadEnter приводится сюда же) */
    Escape,  /* Esc — стоп */
};

struct Mods {
    bool ctrl = false;
    bool shift = false;
    bool alt = false;
};

/* Одно нажатие. Модификаторы — ровно нажатые: лишний Shift делает нажатие
 * ЧУЖИМ, а не «тем же самым». */
struct Event {
    Key key = Key::None;
    Mods mods;
};

/* Что плагин знает о себе в этот момент. Собирается окном под локом и
 * передаётся копией — тот же довод, что у `cancel.h` (D1). */
struct Context {
    /* Активен элемент интерфейса: поле ввода, зажатая кнопка. */
    bool item_active = false;
    /* Что делает агент — ответ `cancel::phase_of`, а не его копия. */
    cancel::Phase phase = cancel::Phase::Idle;
    /* Открыт диалог: сочетание не должно перехватывать закрытие. */
    bool popup_open = false;
    /* План-режим включён: одобрять имеет что. */
    bool plan_mode = false;
};

/* Что означает нажатие. Ничего — если сработать не должна. */
enum class Action {
    None = 0,
    OpenEdits,     /* Ctrl+O */
    ApprovePlan,   /* Ctrl+Enter */
    Stop,          /* Esc */
    ToggleDetails, /* Ctrl+B */
};

/* Имя действия. Не украшение: `ASSERT_EQ` печатает оба операнда при
 * падении, и без этого проверка падала бы списком кандидатов C++ вместо
 * «ждали Stop, получили None». */
std::string action_name(Action action);

/* Печать в поток — чтобы `ASSERT_EQ` назвал действие, а не тип. */
std::ostream& operator<<(std::ostream& os, Action action);

/* Решение. Единственное место, где клавиша превращается в действие. */
Action action_for(const Event& ev, const Context& ctx);

/* Объявленное сочетание — для подсказки в окне и для сверки перечня. */
struct Binding {
    std::string keys;  /* «Ctrl+O» — так же, как в меню окна */
    Action action = Action::None;
};

/* Все четыре сочетания. Объявленный перечень, а не вычисляемый: перечень
 * виден в подсказке, и новое действие обязано в него попасть (проверяется
 * сверкой в обе стороны). */
const std::vector<Binding>& bindings();

/* Подсказка одной строкой — что нажимать. Собирается из `bindings()`, то
 * есть строки не расходятся с тем, что сочетание действительно делает. */
std::string help_line();

}  // namespace hotkeys
}  // namespace coder