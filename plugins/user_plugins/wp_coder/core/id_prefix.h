#pragma once

/*
 * id_prefix.h — идентификаторы сообщений, частей и сессий (И5.5).
 *
 * Зачем они монотонны и сортируемы. Событийная модель И5 хранит
 * части внутри сообщений, а UI (И11) показывает их в порядке появления.
 * Порядок по времени отдельно не хранится: он и есть порядок
 * идентификаторов. Сортировка по id — единственный способ восстановить
 * «что было раньше» после перезагрузки сессии, и она обязана совпадать с
 * порядком создания.
 *
 * А вот здесь и ловушка, ради которой файл существует: «msg_9» при
 * лексикографической сортировке БОЛЬШЕ, чем «msg_10», потому что
 * сравниваются символы, а не числа. Сортированный список ходов
 * разъезжался бы после десятого сообщения — и ровно там, где это не
 * заметно на маленьком тесте. Поэтому число дополняется нулями до
 * фиксированной ширины, и 12 цифр здесь не запаса: 10^12 сообщений за
 * одну сессию не бывает, а вот «после миллиарда перестало работать»
 * случалось бы.
 *
 * Счётчик общий для всех трёх префиксов: тогда идентификаторы уникальны
 * внутри запуска целиком, а не только внутри вида, и в логе видно, что
 * часть создана раньше сообщения, а не наоборот (с раздельными
 * счётчиками по обоим было бы «msg_1» и «prt_1» без всякого смысла).
 */

#include <atomic>
#include <cstddef>
#include <string>

namespace coder {

/* Префиксы. Строковые константы, а не enum: префикс попадает в файл
 * сессии и в JSON для UI, и там он строка. */
inline constexpr const char* kMsgPrefix = "msg_";
inline constexpr const char* kPartPrefix = "prt_";
inline constexpr const char* kSessionPrefix = "ses_";

/* Ширина числа в идентификаторе. */
inline constexpr size_t kIdDigits = 12;

/* Монотонная последовательность идентификаторов.
 *
 * Потокобезопасна: идентификатор может создать и worker-поток агента, и
 * UI-поток (открытие сохранённой сессии), а пересечение двух
 * последовательностей дало бы два сообщения с одним id — и историю,
 * которую нельзя ни сохранить, ни разобрать. */
class IdSequence {
public:
    IdSequence() = default;

    /* Следующий идентификатор с префиксом. */
    std::string next(const char* prefix);

    std::string next_msg() { return next(kMsgPrefix); }
    std::string next_part() { return next(kPartPrefix); }
    std::string next_session() { return next(kSessionPrefix); }

    /* Поднять счётчик так, чтобы уже выданные идентификаторы не
     * повторились.
     *
     * Нужно при загрузке сессии с диска (И5.6): счётчик процесса стартует
     * с нуля, а в файле уже есть msg_000000000412. Без этого первый же
     * новый ход получил бы идентификатор, который в истории уже занят,
     * и два сообщения слиплись бы в одно — молча, потому что обе части
     * выглядели бы валидно. */
    void observe(const std::string& id);

    /* Сброс к началу. Только для тестов: в рантайме сброс означал бы
     * повтор идентификаторов. */
    void reset() { next_.store(0, std::memory_order_relaxed); }

    /* Последний выданный номер (для тестов и диагностики). */
    unsigned long long last() const {
        return next_.load(std::memory_order_relaxed);
    }

private:
    std::atomic<unsigned long long> next_{0};
};

/* Общая последовательность плагина. */
inline IdSequence& ids() {
    static IdSequence kIds;
    return kIds;
}

/* Число из идентификатора. 0, если это не идентификатор или формат не
 * тот же (другая ширина, чужой префикс, не цифры). */
unsigned long long id_number(const std::string& id);

/* Идентификатор ли это, и чужой ли префикс. */
bool id_has_prefix(const std::string& id, const char* prefix);

} // namespace coder
