#pragma once

/*
 * gbnf.h — Генерация GBNF-грамматики вызова инструмента из его JSON-схемы
 * (И12.7).
 *
 * ЗАЧЕМ
 * -----
 * Парсер вызова хрупок не потому, что написан плохо, а потому, что модель
 * пишет JSON текстом: лишняя запятая, одинарные кавычки, обрыв на середине
 * — и разбор падает. Ограниченная выборка (GBNF) делает такой текст
 * НЕВОЗМОЖНЫМ: модель физически не может выбрать токен, который нарушает
 * правило. Это единственный способ починить хрупкость, не разбирая вслух
 * каждую ошибку разбора.
 *
 * ЧИСТОТА
 * -------
 * Чистая функция от схемы к строке: ни сети, ни модели, ни состояния. И
 * потому её можно проверить на двадцати схемах за секунды, тогда как
 * проверить «грамматика работает» можно только на живой модели — а её под
 * рукой нет. Поэтому проверяется ГРАММАТИКА как строка (правила, имена,
 * порядок), а не её исполнение, и граница названа явно (см. И12.7 в §4).
 *
 * ЧТО ПОДДЕРЖИВАЕТСЯ И ЧТО НЕТ
 * ---------------------------
 * Поддержано то, что встречается в схемах инструментов этого плагина:
 * объект, массив, строка, целое, число, булево, `enum` для строк,
 * вложенность и `required`.
 *
 * НЕ поддержано сознательно: `additionalProperties` со свободной схемой
 * (падает в общий `value`, то есть ограничение ослабляется, а не
 * становится ложным), `oneOf`/`anyOf`/`allOf` (то же самое — общий
 * `value`), форматы (`format: date-time` — не влияет на грамматику,
 * ложь была бы в том, что грамматика его проверяет).
 *
 * ПОЧЕМУ КЛЮЧИ В ЛЮБОМ ПОРЯДКЕ, А НЕ КАК В СХЕМЕ
 * ---------------------------------------------
 * Схема перечисляет `properties` в порядке объявления, и наивная грамматика
 * заставила бы модель выдавать ключи именно в этом порядке. Порядок в JSON
 * не значит ничего, а принуждение к нему — это ограничение ради
 * ограничения: модель, которой пришлось переставить ключи, чтобы попасть в
 * грамматику, выдаёт худший результат. Поэтому ключи разрешены в любом
 * порядке и в любом подмножестве — если `required` пуст, ключа может не
 * быть вовсе.
 */

#include "json.h"

#include <string>
#include <vector>

namespace coder {

/* Сгенерировать GBNF для одного значения по схеме.
 *
 * Схема — подсхема одного аргумента (`ToolDef::parameters` целиком тоже
 * подходит: это объект с `properties`). Схема без `type` даёт общий
 * `value`: ограничение ослабляется до «любой JSON», но не становится
 * неверным — то есть на худшем грамматика безвредна.
 *
 * Имя корневого правила — `root`, как того ждёт llama.cpp. */
std::string gbnf_from_schema(const json::JsonValue& schema);

/* Сгенерировать грамматику ВЫЗОВА одного из перечисленных инструментов.
 *
 * `names` — имена инструментов, допустимые в поле `tool`. Порядок важен
 * только для читаемости правила; на язык он не влияет.
 *
 * Пустой список даёт ПУСТУЮ СТРОКУ, то есть «чем ограничивать нечего».
 * Не грамматику с пустой альтернативой: `()` — синтаксическая ошибка GBNF,
 * и ошибка молчаливая. */
std::string gbnf_for_tool_call(const std::vector<std::string>& names);

} // namespace coder