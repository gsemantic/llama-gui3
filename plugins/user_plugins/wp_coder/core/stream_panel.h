#pragma once

/*
 * stream_panel.h — панель стриминга: что модель печатает ПРЯМО СЕЙЧАС (И11.6).
 *
 * Зачем отдельная панель, когда есть таймлайн (И11.3–11.5). Разница во
 * времени, а не в данных: таймлайн показывает ходы, которые УЖЕ
 * закрылись и легли в историю, а эта — ход, который идёт сейчас, и в
 * истории его ещё нет. Пока модель печатает, человек должен видеть
 * текст; когда ход закроется, текст появится в таймлайне, и панель
 * погаснет сама.
 *
 * Что здесь и почему именно здесь. Окно ImGui непроверяемо юнит-тестом
 * (тот же довод, что у 11.1, 11.4 и 11.5): собирать подписи и решать,
 * что видно, прямо в окне значит проверять там, где проверять нечем.
 * Поэтому здесь — МОДЕЛЬ панели и все решения: что показано, что
 * скрыто, какой инструмент активен, что панель напечатает при пустом
 * ходе. Окно рисует готовые строки.
 *
 * ТРИ ВЕЩИ, КОТОРЫЕ ПАНЕЛЬ НЕ ВЕДЁТ САМА, И КАЖДАЯ ОТВЕЧАЕТ НА ВОПРОС
 * «ПОЧЕМУ ТАК»
 *
 * 1. Текст хода НЕ хранится здесь заново. Дельты копятся в буфере,
 *    а по закрытии хода текст берётся из ИСТОРИИ (`MessagePart::text`),
 *    которая уже написана циклом. Дублировать текст в двух местах —
 *    значит получить две правды: панель показала бы одно, таймлайн —
 *    другое, и расхождение появилось бы при первой же неудачной
 *    синхронизации. Панель показывает НЕДОПИСАННЫЙ ход, и только его:
 *    как только ход закрылся, его место в истории.
 *
 * 2. «Размышление» (reasoning) — отдельный поток, а не часть текста.
 *    Провайдер присылает его другими дельтами, и смешивать с текстом
 *    нельзя: человек читал бы мысли модели как ответ. Панель держит их
 *    раздельно и показывает раздельно.
 *
 * 3. Активный инструмент берётся из ИСТОРИИ, а не из отдельного поля
 *    состояния: вызов, помеченный `set_running()`, уже лежит в сессии
 *    (цикл пишет его до запуска инструмента), и второе место правды
 *    «какой инструмент работает» разъехалось бы при первой же правке.
 *
 * ГРАНИЦА ПРЕДЕЛА. Буфер дельт ограничен (`limits::kMaxStreamPanelChars`),
 * и при переполнении он обрезается С НАЧАЛА: у отброшенного текста
 * причина названа (панель печатает, сколько потеряно), а у молча
 * обрезанного — человек видел бы текст, который начинается с середины
 * слова, и не понял бы почему. Обрезать с конца нельзя: там как раз
 * конец хода, то есть самое интересное.
 */

#include "limits.h"
#include "llm_event.h"

#include <cstddef>
#include <string>
#include <vector>

namespace coder {
namespace stream_panel {

/* Живой буфер одного незакрытого хода. */
struct StreamBuffer {
    /* Текст и размышление копятся ОТДЕЛЬНО: смешивать их нельзя
     * (п. 2 в шапке). */
    std::string text;
    std::string reasoning;
    /* Что сейчас печатает модель. Пусто — блок закрыт. */
    bool text_open = false;
    bool reasoning_open = false;
    /* Вызов, аргументы которого пишутся прямо сейчас. */
    bool tool_open = false;
    std::string tool_call_id;
    std::string tool_name;
    /* Ход идёт: буфер принадлежит незакрытому ходу. Сбросится на
     * пустой, когда ход закроется (см. finish_turn). */
    bool active = false;
    /* Сколько символов отброшено переполнением. Показывается числом:
     * молча обрезанный текст выглядит как «модель так начала». */
    std::size_t dropped_chars = 0;
    /* Шаг агента — для подписи «шаг N». */
    int step = 0;

    void clear();
    /* Дописать дельту с учётом предела. Возвращает false, если текст
     * отброшен пределом (вызывающий ничего не делает — состояние уже
     * отражено в dropped_chars). */
    bool push_text(const std::string& delta);
    bool push_reasoning(const std::string& delta);
    /* Сколько символов пришлось отбросить, чтобы влезть предел. */
    std::size_t trim_to(std::string& buf, std::size_t limit);
};

/* Приём события в буфер. Событие, которого буфер не ждал (например,
 * конец блока, который не открывался), ИГНОРИРУЕТСЯ, а не создаёт
 * блок: иначе провайдер, приславший `text_end` без `text_start`,
 * показал бы пустую строку с закрытым блоком. */
void feed(StreamBuffer& buf, const LlmEvent& event);

/* Закрытие хода: буфер гаснет, а панель перестаёт что-либо показывать
 * до следующего хода. Идемпотентно — закрытый буфер закрывается
 * повторно без последствий, потому что вызывать его дважды можно с
 * двух сторон (цикл и таймаут). */
void finish_turn(StreamBuffer& buf);

/* --- Модель панели: всё, что окно рисует, собрано здесь --- */

/* Активный инструмент: вызов, помеченный Running, из последнего хода.
 * Пусто — инструментов нет или все закрыты. */
struct ActiveTool {
    std::string call_id;
    std::string tool_name;
    std::size_t elapsed_ms = 0;
};

/* Что показывать. Окно рисует поля как есть и ничего не решает. */
struct Panel {
    /* Панель видна вообще: есть ли незакрытый ход с чем показать. */
    bool visible = false;
    /* Подпись шага: «шаг 3» и подобное. Пусто — шаг неизвестен. */
    std::string step_line;
    /* Текст модели (не закрытый). */
    std::string text;
    /* Размышление модели (не закрытое). */
    std::string reasoning;
    bool reasoning_open = false;
    /* Пишет ли модель текст прямо сейчас — по этому признаку рисуется
     * курсор, и «печатает» должно отличаться от «дописала и молчит». */
    bool text_open = false;
    /* Активный инструмент. */
    bool has_tool = false;
    ActiveTool tool;
    /* Пишет ли модель аргументы вызова. */
    bool tool_open = false;
    std::string tool_call_id;
    std::string tool_name;
    /* Отброшено пределом: показывается, а не прячется. */
    std::size_t dropped_chars = 0;
    /* Подпись пустой панели: что человек видит, когда хода нет. */
    std::string empty_line;
};

/* Сборка панели из буфера и активного инструмента.
 *
 * active_tool берётся из ИСТОРИИ вызывающим (п. 3 шапки) и сюда
 * приходит готовым: core не знает про сессию, и не должен — панель
 * собирается из двух источников, а не ходит по чужим структурам. */
Panel build(const StreamBuffer& buf, const ActiveTool& active_tool);

/* Подпись для пустой панели. Отдельная функция, а не константа в
 * структуре: строка должна проверяться, и константа в заголовке
 * проверке недоступна. */
std::string empty_line();

}  // namespace stream_panel
}  // namespace coder