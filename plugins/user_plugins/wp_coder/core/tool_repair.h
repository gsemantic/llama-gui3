#pragma once

/*
 * tool_repair.h — Починка вызова инструмента (И12.3, порт
 * `experimental_repairToolCall`, llm.ts:296).
 *
 * ЧТО БЫЛО НЕ ТАК
 * ----------------
 * Модель почти никогда не ошибается в регистре, но ошибается довольно
 * часто: `Read`, `READ`, `git_Status` — и всё. Реестр имена инструментов
 * хранит в нижнем регистре, поэтому такой вызов не находился и уходил в
 * отказ «неизвестный инструмент» с перечислением доступных. То есть
 * агент, назвавший инструмент правильно иначе, чем в каталоге, получал
 * ровно то же самое, что при выдуманном имени, — и разницы, ради которой
 * каталог вообще печатается, не было.
 *
 * Вторая ошибка противоположная: имя действительно выдумано. Раньше такой
 * вызов становился ОТКАЗОМ (`ToolOutcome::error`), то есть событием
 * ToolError. Для модели это не результат вызова, а протокольная ошибка
 * чужого слоя: у вызова нет результата, есть неудача. Модель на таком
 * ответе часто не переписывает вызов, а начинает заново рассуждать — то
 * есть платит за опечатку в имени всем контекстом, который до этого
 * накопила.
 *
 * ЧТО СТАЛО
 * ---------
 * Два шага, оба — до того, как вызов дойдёт до исполнения:
 *
 *   1. Имя в нижнем регистре, ЕСЛИ ТАКОЕ ИМЯ ЕСТЬ В РЕЕСТРЕ. Только при
 *      отсутствии точного совпадения: иначе приведение к регистру
 *      переименовывало бы существующий инструмент в другой существующий.
 *   2. Иначе — маршрутизация в СКРЫТЫЙ инструмент `invalid` с аргументами
 *      `{tool, error}`. Модель получает настоящий результат вызова и
 *      читает, какого инструмента нет; переписать вызов — её дело.
 *
 * ПОЧЕМУ `invalid` НЕ ЗАРЕГИСТРИРОВАН В РЕЕСТРЕ
 * --------------------------------------------
 * Это решение, а не недосмотр, и оно держит три свойства сразу:
 *
 *   * СКРЫТ. Реестр — единственный источник того, что модель видит:
 *     build_tool_catalogue, build_tool_specs_json и join_tools читают его
 *     же. Инструмента в реестре нет — значит, он не попадёт ни в
 *     каталог промпта, ни в нативный вызов, ни в перечисление доступных
 *     при ошибке. Отдельный флаг «скрытый» означал бы второе место,
 *     где про этот инструмент можно забыть, а первое забыть нельзя.
 *
 *   * НЕ СПРАШИВАЕТ РАЗРЕШЕНИЯ. У зарегистрированного инструмента есть
 *     permission_key, а значит он попадает под правила и может вызвать
 *     вопрос пользователю. Вопрос «разрешить вызов инструмента invalid?»
 *     — это ровно тот абсурд, ради которого починка и затевалась:
 *     человек был бы вовлечён в исправление опечатки модели.
 *
 *   * НЕ ПОДЧИНЯЕТСЯ РЕЖИМУ. В research/plan инструмент без
 *     классификации (TF_UNCLASSIFIED) запрещён fail-closed. Для
 *     настоящей ошибки имени это значило бы, что в режиме «только
 *     чтение» опечатка даёт отказ по режиму вместо подсказки — то есть
 *     починка работала бы не везде, и худший случай совпал бы с
 *     худшим.
 *
 * Плата за это — `invalid` не проходит через общий путь
 * ToolsRegistry::run_output, а значит не получает общий предел вывода
 * и санитайзер UTF-8. Здесь это безопасно: текст собирается из имени
 * вызова и списка имён реестра, то есть ограничен по построению
 * (~1 КБ на 60 инструментов), а предел реестра — 50 КБ.
 *
 * ЧИСТОТА
 * -------
 * repair_tool_call — чистая функция: читает реестр (const), ничего не
 * пишет, не ходит в состояние движка и не берёт мьютексов. Её можно
 * проверять без Engine, а ToolRunner::run остаётся единственным местом,
 * где вызов исполняется, — починка не создаёт второго.
 */

#include "json.h"
#include "tool.h"

#include <string>

namespace coder {

/* Имя скрытого инструмента починки. Живёт здесь, а не в реестре:
 * единственное место, где оно названо. */
constexpr const char* kInvalidTool = "invalid";

/* Куда направить вызов, который прислала модель.
 *
 * requested — имя как прислала модель (в выдаче и в сообщении нужно
 * именно оно: «Read» читается как опечатка, а не как «read»).
 * tool — имя, по которому вызов исполнять.
 */
struct ToolRepair {
    std::string requested;
    std::string tool;
    /* Найденное описание. nullptr ТОЛЬКО при routed_to_invalid: там
     * исполнять нечего.
     *
     * Указатель, а не имя, — чтобы исполнение не ходило в реестр
     * второй раз. Иначе проверка «починка ничего не сломала» держалась
     * бы на предположении, что два обращения к реестру дают одно и то
     * же, а реестр — общий объект, и вторая точка истины — это ровно
     * тот класс дефекта, который починка чинит. */
    const ToolDef* def = nullptr;
    /* Имя починено приведением к нижнему регистру. */
    bool repaired_case = false;
    /* Вызов ушёл в скрытый `invalid` — исполнять нечего, модели
     * возвращается результат вызова `invalid`. */
    bool routed_to_invalid = false;
    /* Аргументы для `invalid`: {tool, error}. Для обычного вызова
     * пустой объект — аргументы модели не меняются. */
    json::JsonValue invalid_args = json::JsonValue::object();
};

/* Починить вызов по имени. Реестр — единственный источник истины о
 * том, какие инструменты существуют: отдельный список имён здесь означал
 * бы, что починка чинит по неточному представлению о плагине. */
ToolRepair repair_tool_call(const std::string& tool_name);

/* Результат скрытого инструмента `invalid` — то, что увидит модель.
 *
 * Текст собирается ОДНОЙ функцией и подставляется и в invalid_args
 * (`error`), и сюда: две копии одного сообщения разошлись бы при первой
 * же правке (D12). */
ToolOutput invalid_tool_output(const ToolRepair& repair);

} // namespace coder