#pragma once

/*
 * todo_panel.h — панель плана задачи с чекбоксами (И11.7).
 *
 * Отличие от чек-листа в виджете `todowrite` (core/tool_display.h, И11.4)
 * — в том, ОТКУДА берутся пункты. Виджет строится по АРГУМЕНТАМ
 * конкретного вызова, то есть это снимок того, что модель написала
 * ТОГДА; план, который действует СЕЙЧАС, лежит в `state_.todos`, и его
 * кладёт сам инструмент. Два источника означали бы две правды о плане,
 * расходящиеся на первом же шаге после `todowrite`.
 *
 * ГЛАВНОЕ РЕШЕНИЕ: клик по чекбоксу МЕНЯЕТ ПЛАН. Не «выглядит как
 * галочка», а пишет новый статус в `state_.todos` и сбрасывает кэш
 * системного промпта — после чего модель видит правку в следующем ходу.
 * Основание — не «так удобнее», а текст самого промпта: план печатается
 * в нём со словами «план показывается пользователю, и он им вмешивается»
 * (core/engine.cpp, раздел «ПЛАН ЗАДАЧИ»). Показывать план и не давать им
 * вмешаться — значит писать модели untrue: обещать вмешательство, которого
 * нет.
 *
 * ЧТО ЭТО НЕ ДЕЛАЕТ И ПОЧЕМУ ЭТО НАЗВАНО. Человек может отметить
 * выполненным то, что не сделано, и модель это примет — план переписывает
 * человек, не агент. Отмены клика нет: чекбокс переключает
 * «выполнено / не выполнено», а не открывает историю правок. Оба решения
 * осознанные: отмена требовала бы хранить историю правок плана (новое
 * состояние, персистентность, «а что считать правдой» при загрузке
 * сессии), а переключатель даёт человеку ровно то, ради чего панель
 * затевалась. Смена статуса на ТРЕТИЙ (cancelled / in_progress) здесь не
 * доступна сознательно: это решения агента, и человек, ставящий «отмена»,
 * не разбирался бы в её плане.
 *
 * ЧТО ПРО ПЕРСИСТЕНТНОСТЬ, И ПОЧЕМУ НЕ ТРОГАЕТСЯ. `state_.todos` не
 * сохраняется в файле сессии (в core/session_store.cpp его нет), то есть
 * план живёт только в памяти и пропадает при перезагрузке окна. Это
 * существующее поведение, а не следствие панели; исправление — это
 * отдельное решение о формате файла сессии, и оно не входит в 11.7.
 * Названо здесь, чтобы панель не выглядела обещанием сохранения.
 */

#include "engine.h"

#include <cstddef>
#include <string>
#include <vector>

namespace coder {
namespace todo_panel {

/* Один пункт в том виде, в каком его рисует окно. */
struct Item {
    /* Идентификатор из плана (`todos[].id`). Пусто — пункт без
     * идентификатора, и клик по нему ничего не найдёт. */
    std::string id;
    std::string content;
    std::string status;    /* как в engine.h::kTodoStatuses */
    std::string priority;  /* как в engine.h::kTodoPriorities */

    /* Готовое решение окна: галочка нажата или нет. */
    bool checked = false;
    /* Статус ЗАПРЕЩЁН к отмечанию: план не меняется. */
    bool locked = false;
};

/* Модель панели. Окно рисует поля как есть и ничего не решает. */
struct Panel {
    /* Панель показывается, когда есть что показывать. Пустой план —
     * это не «панель без пунктов», а отсутствие панели: рамка с
     * заголовком и нулём выглядела бы как «план сломался». */
    bool visible = false;
    std::vector<Item> items;
    /* Счётчик незавершённых: ровно то, за чем человек сюда смотрит. */
    std::size_t remaining = 0;
    std::size_t total = 0;
    /* Подпись счётчика. Собрана в core, потому что окно не должно
     * собирать подписи — их нечем проверять (см. 11.1, 11.4, 11.6). */
    std::string counter_line;
    /* Что показать, когда панели нет. */
    std::string empty_line;
    /* Правки, которые панель уже просила применить, — чтобы окно
     * показало «применяется» и не ждало мгновенной реакции. */
    bool has_pending_edit = false;
    std::string pending_edit_line;
};

/* Статус, который получит пункт по клику. Переключатель, а не замена
 * «на completed»: из `in_progress` человек чаще хочет «выполнено», но
 * одним правилом для всех состояний пункт «в работе» нельзя было бы
 * вернуть в «ожидает» без второго клика по другому месту.
 *
 * Отмена клика (`completed` → `pending`) означает, что человек ошибся и
 * хочет вернуть пункт в работу. */
std::string next_status(const std::string& current);

/* Заблокирован ли пункт для клика.
 *
 * Пункт БЕЗ идентификатора заблокирован: вернуть правку нечем, а
 * «галочка на которую можно нажать и ничего не происходит» хуже
 * негалочки. */
bool is_locked(const std::string& id);

/* Сборка панели из текущего плана. План снимается вызывающим под
 * `state_.mtx` и передаётся копией. */
Panel build(const std::vector<TodoItem>& todos);

/* Применение клика к плану.
 *
 * Возвращает true, если план ИЗМЕНИЛСЯ. Вызывающий обязан по этому
 * сбросить кэш системного промпта: иначе модель до конца сессии видела
 * бы старый список и правило «держи план в актуальном состоянии»
 * работало бы вхолостую.
 *
 * Пункт ищется ПО ИДЕНТИФИКАТОРУ, а не по позиции: список мог измениться
 * между кадром и кликом, и правка по индексу изменила бы не тот пункт.
 * Идентификатор не найден — план не трогаем и возвращаем false. */
bool apply_toggle(std::vector<TodoItem>& todos, const std::string& id);

/* Подпись для пустой панели. Отдельная функция, а не константа:
 * строка должна проверяться. */
std::string empty_line();

/* Подпись счётчика. */
std::string counter_line(std::size_t remaining, std::size_t total);

}  // namespace todo_panel
}  // namespace coder