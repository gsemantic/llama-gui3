#pragma once

/*
 * diff.h — И10.5: построчный diff для показа в UI.
 *
 * Задача 10.5 — «diff для каждого снапшота доступен UI». Здесь ровно
 * половина этой задачи: половина считает diff, вторая отдаёт его UI
 * (core/snapshot.h → Engine::level_diff → ui/coder_window.cpp).
 *
 * ---------------------------------------------------------------------------
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПАРА ФУНКЦИЙ В snapshot.cpp
 * ---------------------------------------------------------------------------
 *
 * 1. ЕГО НЕ ЧИТАЕТ НИКТО, КРОМЕ UI, и его не зовёт агент. Снимки читает
 *    откат (10.3), а diff читает человек, нажавший кнопку. Смешанный
 *    файл «откат и просмотр» читался бы как одно, а отличаются они
 *    всем: откат меняет файлы, diff только читает, и предел у них
 *    общий с инструментами (2000 строк) — а здесь свой.
 *
 * 2. ФОРМАТ ОДИН, ИСТОЧНИК РАЗНЫЙ. Unified diff напечатан один раз
 *    здесь, а получают его двумя путями: git-путь берёт готовый вывод
 *    `git diff` (core/snapshot.cpp), копия каталога — строит этот код.
 *    Пересобирать git-вывод своим кодом было бы второй реализацией
 *    одного и того же, и она разошлась бы с git в деталях, которые
 *    человек видел тысячи раз: `\ No newline at end of file`, права
 *    файла, бинарники. Свой код печатает unified-разметку, но не
 *    изобретает её заново.
 *
 * ---------------------------------------------------------------------------
 * ГРАНИЦЫ, КОТОРЫЕ ОБЯЗАНЫ БЫТЬ СКАЗАНЫ (их читают перед правкой)
 * ---------------------------------------------------------------------------
 *
 *   1. ЭТО НЕ ПРИГЛАЖЕНИЕ. Diff ничего не откатывает: он отвечает на
 *      вопрос «что изменится», а меняет состояние только `undo`. Человек
 *      смотрит diff и сам решает, нажимать ли. Поэтому здесь нет и не
 *      будет ничего, что пишет в проект.
 *   2. ДВОИЧНЫЙ ФАЙЛ — НЕ ПУСТОЙ DIFF. У git для него есть отдельная
 *      строка `Binary files a/x and b/x differ`, и подменять её пустым
 *      патчем нельзя: «изменений нет» и «изменился файл, который нечем
 *      показать» — это разные вещи, и человек потерял бы правку. Поэтому
 *      у FileDiff есть `binary`, а счётчики остаются нулевыми.
 *   3. ОБРЕЗАННЫЙ DIFF ГОВОРИТ ОБ ЭТОМ. `truncated` — не украшение:
 *      пределы (core/limits.h) существуют, чтобы окно не зависло, и
 *      молча обрезанный patch выглядел бы как полный.
 *   4. ФОРМАТ ФАЙЛА — ЧЕРЕЗ core/text_edit.h, А ПОКАЗ — КАК У GIT.
 *      Структура файла (BOM, CRLF, завершающий перевод) читается
 *      split_text(), а не собственным разбором: правило 9 SESSION_START.
 *      Но в diff строки сравниваются ТАК, как их печатает git, то есть
 *      вместе с `` и с BOM на первой строке. Проверено на живом git
 *      2.39: смена CRLF на LF показывает изменением КАЖДУЮ строку
 *      (`-a^M` / `+a`), а добавление BOM — первую. Нормализовать их
 *      было бы «удобно» и неверно: человек, читающий окно, увидел бы
 *      «изменилось две строки» там, где изменились все, и нажал бы
 *      «отменить» не зная, что именно вернётся.
 *      Названное ограничение: у файла со СМЕШАННЫМИ переводами строк
 *      split_text() определяет `crlf` по первому найденному CRLF, и
 *      строки сравняются как будто переводы везде одинаковы. На
 *      одинаковых смешанных файлах это незаметно, а на разных —
 *      показаны будут «лишние» изменённые строки, то есть diff
 *      покажет больше, чем изменилось. Ложь в сторону «больше», а не
 *      «меньше»: человек увидит правку, которой не было, и откатит
 *      лишнее сам.
 *
 * ---------------------------------------------------------------------------
 * АЛГОРИТМ И ЕГО ЧЕСТНОЕ ОГРАНИЧЕНИЕ
 * ---------------------------------------------------------------------------
 *
 * Сравнение — общий префикс и суффикс, затем LCS по остатку (_dynamic
 * programming_, одна плоская таблица). Это точный алгоритм на том, что
 * реально правится: человек или модель меняют несколько строк в файле,
 * и префикс/суффикс отсекают всё остальное.
 *
 * На файле, где изменено ВСЁ (или где остаток после отсечения всё ещё
 * огромен), таблица не помещается в предел kMaxDiffMatrix, и файл
 * показывается как «заменено N строк на M». Это НЕ точный diff, и об
 * этом сказано в `note` — иначе человек прочитал бы грубую правку как
 * построчную и не увидел бы, что она не разбиралась. Точный алгоритм
 * (Myers, линейная память) дал бы столько же: хоть и без предела, он
 * печатает те же сплошные замены на таком файле, и разница была бы в
 * цене, а не в результате.
 */

#include <cstddef>
#include <string>
#include <vector>

namespace coder {
namespace diff {

/* Строка одна: context — есть и там, и там; removed — только «до»;
 * added — только «после». Номера строк — в своей стороне, поэтому у
 * removed old_no заполнен, а new_no нулевой, и наоборот. */
enum class LineKind { Context, Added, Removed };

struct DiffLine {
    LineKind kind = LineKind::Context;
    std::string text;      /* без завершающего перевода строки */
    size_t old_no = 0;     /* 1-based; 0 — строки в этой стороне нет */
    size_t new_no = 0;
};

/* Один файл. Поля `file`/`patch`/`additions`/`deletions` — это ровно та
 * форма, которую И11.2 называет для `ToolOutput::metadata.filediff`, и
 * она определена ОДИН раз здесь: если бы 11.2 завёл свою, поля
 * разошлись бы (Д2, Д12). */
struct FileDiff {
    std::string file;
    std::string patch;         /* unified, без завершающего перевода */
    size_t additions = 0;
    size_t deletions = 0;
    bool binary = false;
    bool truncated = false;
    /* Человекочитаемое объяснение: «двоичный файл», «прав не было»,
     * «показана замена целиком». Пусто — значит обычный diff. */
    std::string note;

    bool empty() const { return patch.empty() && additions == 0 && deletions == 0; }
};

/* Построчное сравнение. Номера строк проставляются здесь, 1-based.
 *
 * `coarse` — РАБОЧИЙ выход, а не украшение: когда таблица сравнения не
 * помещается в limits::kMaxDiffMatrix, сравнение становится сплошной
 * заменой, и вызывающий ОБЯЗАН это объявить (make_file_diff пишет это
 * в note). Молчаливая замена выглядела бы как точный diff. */
std::vector<DiffLine> diff_lines(const std::vector<std::string>& before,
                                 const std::vector<std::string>& after,
                                 bool* coarse = nullptr);

/* Unified diff одного файла по его СОДЕРЖИМОМУ. Содержимое с форматом
 * (BOM/CRLF) разбирается через split_text(), поэтому `patch` может
 * содержать `\ No newline at end of file`. При заполненном пределе
 * limits.h ставит truncated и пишет об этом в note. */
FileDiff make_file_diff(const std::string& file,
                        const std::string& before_raw,
                        const std::string& after_raw);

/* Двоичный ли файл — тем же правилом, что у git: NUL в первых 8000
 * байтах. Правило названо, а не выбрано: git считает двоичным именно
 * его, и наш «двоичный файл» должен совпадать с тем, что человек видел
 * в `git diff`, иначе один и тот же файл будет то показан, то нет. */
bool looks_binary(const std::string& raw);

/* Имя файла из строки заголовка unified-патча — поле после `--- ` или
 * `+++ `, БЕЗ завершающего перевода строки.
 *
 * Формы взяты с живого git 2.39, и две из них противоречат друг другу
 * так, что «просто убрать префикс a/» не работает:
 *   - `--- a/keep.txt` и `--- "a/q\"uote.php"` — имя с кавычкой или с
 *     не-ASCII печатается В КАВЫЧКАХ с восьмеричными побегами;
 *   - `--- a/ascii space.txt<TAB>` — имя с ПРОБЕЛОМ и без кавычек, и
 *     разделяет его ТАБУЛЯЦИЯ в конце строки (проверено: в выводе это
 *     видно как `a/ascii space.txt^I`). Без этого табуляция имя и поле
 *     заголовка неразделимы;
 *   - `--- /dev/null` — у нового файла нет имени на этой стороне.
 *
 * Пустая строка на выходе — ОТКАЗ, и это не пустое имя: имя приходит
 * из вывода git, а подобранное на глаз имя показало бы diff чужого
 * файла, то есть в UI человек прочитал бы правку одного файла на
 * файле с другим именем. */
std::string parse_git_header_name(const std::string& field);

} // namespace diff
} // namespace coder
