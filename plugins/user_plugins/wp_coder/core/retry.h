#pragma once

/*
 * retry.h — Политика повторов обращения к провайдеру (И12.6, порт
 * `session/retry.ts`).
 *
 * ЗАМЕНЯЕТ ЧТО
 * -------------
 * «3 попытки, задержки 1 с и 3 с» в `src/plugin_main.cpp`. Задержки были
 * константами рядом с циклом, то есть политика жила вплотную к месту, где
 * её нетрудно было бы забыть, а испытать её в отрыве от хоста было нельзя.
 * Теперь это чистая функция, а цикл остаётся тонким.
 *
 * ЧИСТОТА
 * -------
 * Ни одна функция здесь не спит, не печатает и не ходит в состояние. Задержка
 * и текст уведомления считаются, а ждёт вызывающий.
 *
 * Про ДРОБЬ ДЛЯ ДЖИТТЕРА: `retry_delay_ms` принимает `roll` — число из [0, 1) —
 * ОТ ВЫЗЫВАЮЩЕГО, а не тянет генератор случайных чисел сам. Иначе функция не
 * была бы чистой и каждая проверка зависела бы от того, как легло зерно:
 * проверка «джиттер даёт 75 % и 125 %» либо прошла бы случайно, либо
 * падала бы случайно. `retry_delay_ms_random` — тонкая обёртка для
 * вызывающего, которому случайность нужна по-настоящему.
 *
 * ЗАГОЛОВКИ `retry-after`
 * ----------------------
 * Политика их УМЕЕТ (приоритет отдан серверу, джиттер к нему не применяется:
 * сервер сказал, когда вернуться, — значит, и вернуться надо тогда же), но
 * через ABI они недостижимы: `llm_chat_messages` и `on_done` отдают
 * `{"ok":0,"error":"…"}` и больше ничего, ни кода, ни заголовков (то же
 * ограничение, что в отклонении 97). Поэтому `server_suggested_ms` — это
 * параметр, который сегодня всегда -1, и причина стоит тут же, чтобы её не
 * искали заново. Механизм не мёртвый: он читает поле `retry_after_ms` из
 * ответа хоста, если хот�� его когда-нибудь отдаст, и меняется тогда только
 * сборка ответа на стороне хоста.
 *
 * ОБРАТНЫЙ ОТСЧЁТ
 * ---------------
 * Уведомление одно и называет СКОЛЬКО ждать, а не тикает по секундам. Лента
 * событий держит последние сорок записей, и отсчёт по секунде на задержке в
 * минуту вытеснил бы из неё всё, ради чего человек её смотрит. Отклонение
 * 209.
 */

#include "llm_event.h"

#include <string>

namespace coder {

/* Параметры политики. Значения — из задачи; меняются только проверками и
 * настройкой, которой пока нет. */
struct RetryPolicy {
    /* Задержка перед первой повторной попыткой. */
    int initial_ms = 2000;
    /* Во сколько раз каждая следующая задержка больше предыдущей. */
    double factor = 2.0;
    /* Разброс ± доля: 0.25 означает «от 75 % до 125 % от расчётной». */
    double jitter = 0.25;
    /* Сколько попыток ВСЕГО, первой включительно. */
    int max_attempts = 5;
    /* Потолок задержки: без него 2^n на пятом разе уходит за минуту, и
     * человек успевает забыть, чего ждал. */
    int max_delay_ms = 60000;
};

/* Задержка перед повторной попыткой.
 *
 * attempt — сколько попыток УЖЕ сделано, с нуля: 0 означает «первая
 * попытка провалилась», и ждать до неё initial_ms.
 *
 * server_suggested_ms >= 0 — сервер назвал своё время (retry-after в
 * миллисекундах), и оно выигрывает у расчётного. Обрезается потолком так
 * же, иначе «приходи через 6 часов» превратило бы повтор в зависание.
 */
int retry_delay_ms(const RetryPolicy& policy, int attempt, double roll,
                   int server_suggested_ms = -1);

/* Обёртка с настоящей случайностью. Единственное место в модуле, где есть
 * rand(), и поэтому единственное, что нельзя проверить покомпонентно. */
int retry_delay_ms_random(const RetryPolicy& policy, int attempt,
                          int server_suggested_ms = -1);

/* Повторять ли. attempt — сколько попыток уже сделано (0-based).
 *
 * Повторяемость приходит ГОТОВОЙ (И12.5, classify_provider_failure): здесь
 * она не вычисляется заново, потому что это был бы второй разбор того же
 * текста — то есть D12. */
bool should_retry(const RetryPolicy& policy, bool retryable, int attempt);

/* Текст уведомления для ленты.
 *
 * Называет ВИД сбоя из таксономии (И12.5), потому что ради него пользователь
 * и смотрит: «провайдер» и «доступ к провайдеру» лечатся совсем разными
 * руками, а строка «503» говорит только то, что и так видно в тексте ошибки.
 */
std::string retry_notice(const std::string& error, FailureKind kind, int attempt,
                         int max_attempts, int delay_ms);

} // namespace coder