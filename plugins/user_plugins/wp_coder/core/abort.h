#pragma once

/*
 * abort.h — отмена хода (И6.6).
 *
 * Зачем файл, если есть `EngineState::abort_requested`. Затем, что флагом
 * нельзя разбудить ожидание. Три места ждут события, и все три делали это
 * так, что «отмена» означала «мы вернулись, а работа продолжается»:
 *
 *   - ожидание ответа LLM ждало future с таймаутом (И2.2), и деструктор
 *     future от std::async БЛОКИРУЕТ до конца задачи — то есть «Стоп» и
 *     «таймаут» не возвращали управление вовсе, а делали вид, что вернули;
 *   - сетевое ожидание без отмены «теряло» кусок ответа, а провайдерский
 *     поток продолжал работать в фоне;
 *   - инструмент не знал об отмене вовсе (это И6.7).
 *
 * AbortToken решает ровно это: он не просто «помечен», он будит ожидание.
 * Сделать это std::atomic<bool> нельзя — ждать на нём нечем.
 *
 * Чего AbortToken НЕ делает и почему это важно понимать:
 *   - он не отменяет работу. Он сообщает, что её надо прекратить, и будит
 *     того, кто ждёт. Прекращение работы — дело того, кто её выполняет:
 *     у LLM это отмена HTTP-запроса (host_bridge + llm_chat_cancel), у
 *     `bash` — kill (И6.7);
 *   - он одноразовый. Повторная отмена того же токена — не ошибка, но и
 *     не «переотмена»: токен остаётся в том же состоянии, а следующий
 *     ход получает СВОЙ токен. Иначе «Стоп» во второй раз отменил бы
 *     следующую задачу, то есть отмену нельзя было бы снять.
 *
 * Живой токен, а не глобальный флаг, — потому что у отмены есть
 * владелец и время жизни: ход начался, ход кончился, токен исчез. Общий
 * для всего плагина флаг жил бы вечно и «Стоп» нельзя было бы отменить.
 */

#include <chrono>
#include <condition_variable>
#include <mutex>

namespace coder {

class AbortToken {
public:
    AbortToken() = default;

    /* Токен не копируется намеренно: копия означала бы второй наблюдатель
     * с собственной судьбой, а отмена должна быть одна и общая. Передаётся
     * по ссылке или через shared_ptr. */
    AbortToken(const AbortToken&) = delete;
    AbortToken& operator=(const AbortToken&) = delete;

    /* Запросить отмену. Идемпотентно: второй вызов ничего не меняет. */
    void abort()
    {
        {
            std::lock_guard<std::mutex> lk(mtx_);
            if (aborted_) return;
            aborted_ = true;
        }
        /* Снятие замка ДО notify_all: иначе разбудить пришлось бы ещё под
         * замком, и будильщик проснулся бы в пустоте. */
        cv_.notify_all();
    }

    bool aborted() const
    {
        std::lock_guard<std::mutex> lk(mtx_);
        return aborted_;
    }

    /* Ожидание «отмена или timeout». Возвращает true, если отмена пришла.
     *
     * timeout < 0 — ждать без срока. Ноль — «не ждать вовсе», и это честный
     * вызов: ждать ноль означает проверить состояние и уйти.
     */
    bool wait(int timeout_ms) const
    {
        std::unique_lock<std::mutex> lk(mtx_);
        if (timeout_ms < 0) {
            cv_.wait(lk, [this] { return aborted_; });
            return true;
        }
        return cv_.wait_for(lk, std::chrono::milliseconds(timeout_ms),
                            [this] { return aborted_; });
    }

private:
    mutable std::mutex mtx_;
    mutable std::condition_variable cv_;
    bool aborted_ = false;
};

} // namespace coder
