#pragma once

/*
 * permission_panel.h — диалог разрешения (И11.8).
 *
 * Механизм И2.5–2.7 (PermissionEngine::ask / reply / approve) написан и
 * работает; окно до сих пор рисует вопрос и кнопки само
 * (ui/coder_window.cpp). Здесь — РЕШЕНИЕ о том, что человек увидит:
 * какая строка что значит, какие кнопки доступны и что будет с
 * остальными вопросами в очереди. Окно рисует готовые поля.
 *
 * ПОЧЕМУ НЕ ПРОСТО ПЕРЕНЕСЛИ ТЕКСТ. У окна был один настоящий изъян,
 * и он не был виден по строкам: кнопка «Всегда» обещает постоянное
 * разрешение, а `PermissionEngine::reply` пишет правило только при
 * НЕПУСТОМ `suggested` (permission_engine.cpp, тело reply). У вопроса о
 * зацикливании suggested пуст намеренно — «повторять один и тот же вызов
 * можно сколько угодно, записывать это в постоянные правила нечего»
 * (agent_components.cpp). То есть на doom_loop «Всегда» была кнопкой,
 * которая делала ровно то же, что «Разрешить разово». Это тот же класс
 * дефекта, что в И11.14: обещание, написанное в шапке и не подкреплённое
 * исполнением. Здесь такое обещание просто не показывается — по
 * аналогии с решением 11.7 п.6 (заблокированный пункт рисуется без
 * чекбокса, а не серым: «можно, но нельзя» стоит клика, чтобы выяснить
 * почему).
 *
 * ЧТО ЭТО НЕ ДЕЛАЕТ. Панель не решает за человека и не меняет правила:
 * единственное её действие — превратить запрос в подписи и признак
 * «кнопка «Всегда» существует». Ответ уходит через
 * `Engine::permission_reply` ровно как раньше.
 *
 * ОХВАТ. Только PermissionEngine. Второй диалог окна — PermissionGate,
 * путь за пределами проекта (ui/coder_window.cpp), — живёт на
 * `state_.pending_permission_path` и своём `permission_cv`, то есть это
 * ДРУГОЙ механизм с ДРУГИМ мьютексом. Сведение их в одну панель забрало
 * бы в 11.8 правку PermissionGate и его ожидание по `state_.mtx`,
 * который снимает 11.12; две правды об одном действии (кнопки «Разрешить
 * разово» / «Всегда» / «Отклонить» в двух местах) — это D2/D12, и
 * снимается вместе с ним.
 */

#include "permission_engine.h"

#include <cstddef>
#include <string>
#include <vector>

namespace coder {
namespace permission_panel {

/* Один вопрос в том виде, в каком его рисует окно. */
struct Ask {
    /* Адрес для ответа. Отвечать нужно по нему, а не по позиции: между
     * кадром и кликом очередь может измениться (каскад отклоения снимает
     * вопросы пачкой), и ответ по индексу ушёл бы не тому. */
    uint64_t id = 0;

    std::string permission;   /* ключ: "bash", "deploy", "read"… */
    std::string metadata;     /* человеческое описание: команда, путь */
    std::vector<std::string> patterns; /* что именно спрашиваем */
    std::string suggested;    /* что запишется при «Всегда» */

    /* Есть ли кнопка «Всегда». false — при пустом suggested (см. шапку). */
    bool can_always = false;

    /* Заголовок и подписи, собранные в core: окно их не проверяемо. */
    std::string headline;
    std::string once_label;
    std::string always_label;
    std::string reject_label;
    /* Подпись «всегда разрешит: …». Пустая, когда кнопки нет — окно по
     * пустой строке не рисует ничего, и обещания на экране не будет. */
    std::string suggest_line;
    /* Что скажет «Отклонить» остальным вопросам. Пустая, когда других
     * вопросов нет. */
    std::string cascade_line;
};

/* Модель панели. Окно рисует поля как есть и ничего не решает. */
struct Panel {
    /* Панель показывается, когда есть что отвечать. */
    bool visible = false;
    Ask ask;
    /* Сколько вопросов ждут ответа, кроме показанного. */
    std::size_t others = 0;
};

/* Сборка панели из снимка очереди.
 *
 * Показывается ПЕРВЫЙ вопрос: остальные видны числом и появляются по мере
 * ответа. Показывать все сразу — значит рисовать список, который живой
 * агент дописывает и снимает каскадом, пока человек читает; строки уезжали
 * бы под кнопками, и ответ по такой строке ушёл бы не туда.
 *
 * Пустая очередь — не «панель без вопроса», а отсутствие панели.
 *
 * РЕШЁННЫЕ ЗАПРОСЫ ПРОПУСКАЮТСЯ (см. реализацию): они висят в очереди
 * до тех пор, пока проснётся и вычистит их поток агента, а показать их
 * — значит показать панель, кнопки которой ничего не делают. */
Panel build(const std::vector<PermissionRequest>& pending);

/* Подпись каскада: «Отклонить» убьёт и остальные вопросы. Названо
 * словами, потому что иначе человек узнаёт о последствии после нажатия —
 * ровно то, чего не знает кнопка «Отклонить» сама по себе (механизм
 * И2.6, permission_engine.cpp).
 *
 * others == 0 → пустая строка: каскадом нечего угрожать, и пугать
 * «отклонится ещё 0 вопросов» нельзя. */
std::string cascade_line(std::size_t others);

/* Подпись предложенного «всегда»-паттерна. Пустая — когда suggested
 * пуст: кнопки нет, и обещать нечего. */
std::string suggest_line(const std::string& suggested);

/* Заголовок вопроса. */
std::string headline(const std::string& permission);

}  // namespace permission_panel
}  // namespace coder