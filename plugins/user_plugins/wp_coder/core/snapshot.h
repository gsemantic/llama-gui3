#pragma once

/*
 * snapshot.h — снимок состояния рабочего каталога (И10.1).
 *
 * Задача 10.1 — ПЕРВАЯ задача отката: она создаёт снимки и только их.
 * Восстановление по снимку (10.3), список изменившихся файлов (10.2) и
 * стек снапшотов (10.4) — отдельные задачи, и здесь их намеренно нет:
 * снимок, который никто не читает, всё равно полезен (у 10.2 будет чем
 * мерить «до»), а полуработающая откатка хуже отсутствующей.
 *
 * Где снимок берётся. Плана достаточно: «на step-start и на каждый ход».
 * В нашем цикле (AgentLoop::run, И5.7) ход и шаг — ОДНО И ТО ЖЕ место:
 * за итерацию цикла создаётся ровно одно сообщение ассистента и
 * выполняются его вызовы инструментов. Поэтому один снимок в начале
 * итерации — это и «на step-start», и «на каждый ход», а второго вызова
 * не нужно: он снял бы второй снимок того же состояния и только зря
 * запустил git.
 *
 * Чем снимок является. Для проекта под git — tree-hash, который называет
 * состояние всех файлов. Способ назван планом: `git stash create` (он
 * создаёт объект-коммит и НЕ трогает ни рабочее дерево, ни индекс, ни
 * список stash — проверено на живом репозитории) и, когда стэшить нечего,
 * `git write-tree` (состояние индекса). Для проекта без git — копия
 * каталога; это и есть тот фолбэк, который требует план.
 *
 * Границы честности, которые обязаны быть в шапке, а не в журнале:
 *
 *   1. `git stash create` НЕ берёт неотслеживаемые файлы (проверено на
 *      git 2.39: `stash create --include-untracked` молча отдаёт пустое
 *      и файл в снимок не попадает). Значит файл, созданный агентом и
 *      ещё не добавленный в индекс, в дерево снимка не войдёт. Это
 *      свойство git, а не наш выбор, и 10.3 обязана это учитывать:
 *      «файлы, которых нет в дереве снимка, удаляются» — неверно.
 *   2. Копия каталога копирует ВСЁ (включая `vendor` и `node_modules`),
 *      кроме одного: самого каталога копий, если он оказался внутри
 *      проекта. Список исключений в остальном не заведён намеренно: он
 *      был бы вторым набором правил рядом с первым (где кончается
 *      проект), а молчаливое усечение копии выглядело бы как рабочий
 *      откат — вернулось бы не всё, и человек узнал бы об этом по
 *      исходникам. Исключение каталога копий не про «что копировать», а
 *      про то, что копия обязана не содержать саму себя.
 *   3. Снимок НЕ хранит состояние `.git`: он и не обязан, откат идёт по
 *      содержимому файлов.
 */

#include <string>

namespace coder {
namespace snapshot {

/* Вид снимка. */
enum class Kind {
    None,     /* снимка нет; Snapshot::reason объясняет почему */
    GitTree,  /* состояние названо tree-hash репозитория */
    DirCopy,  /* состояние лежит копией каталога (проект не под git) */
};

struct Snapshot {
    Kind kind = Kind::None;
    /* GitTree: tree-hash. DirCopy: имя копии внутри store_dir. */
    std::string hash;
    /* DirCopy: путь к копии; при Kind::None и DirCopy без каталога — "". */
    std::string dir;
    /* Непусто только при Kind::None: причина, по которой снимка нет. */
    std::string reason;

    bool ok() const { return kind != Kind::None; }
    const char* kind_name() const;
};

/* Каталог копий: <data_dir>/wp_coder/snapshots.
 * Пустая строка — хранить некуда (нет data_dir), и копия не делается.
 * Тот же приём, что у shell::spill_dir. */
std::string store_dir(const std::string& data_dir);

/* Первая строка вывода git, похожая на tree-hash; "" — если такой нет.
 *
 * Отдельная функция, а не деталь внутри take(): команда идёт через
 * обёртку shell с `2>&1`, то есть в stdout может попасть любое
 * предупреждение git, и «первая непустая строка» была бы им. Проверять
 * это на живом git нельзя детерминированно (ни один сценарий не
 * заставляет git напечатать предупреждение и отдать код 0), а вот на
 * тексте — сколько угодно, поэтому разбор и вынесен.
 *
 * Порог — длина строки, а не «это hex»: разбор хеша здесь был бы вторым
 * местом с правилом «что считается хешем», и ошибка в нём уехала бы и в
 * код, и в проверку одинаково. */
std::string parse_hash(const std::string& output);

/* Есть ли в project_dir репозиторий git. Репозиторий поднимается вверх
 * от каталога, поэтому проверка идёт от project_dir, как это делает и
 * env-блок (И9.4). */
bool is_git_repo(const std::string& project_dir);

/* Снять снимок состояния project_dir.
 *
 * store_dir — куда класть копию каталога (см. store_dir()). Для проекта
 * под git он не нужен и может быть пустым.
 *
 * Функция не бросает исключений и не пишет в проект: единственный её
 * побочный эффект — каталог копии в store_dir. Любая неудача приходит
 * как Kind::None с заполненным reason, потому что «снимка нет» — это
 * тоже ответ, который обязан быть назван, а не молчаливый пропуск. */
Snapshot take(const std::string& project_dir, const std::string& store_dir);

} // namespace snapshot
} // namespace coder