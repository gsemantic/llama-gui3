#pragma once

/*
 * glob.h — поиск файлов по шаблону пути (И4.1, порт opencode tool/glob.ts).
 *
 * До И4 у агента не было инструмента «найти файлы»: repo_map звал
 * file_utils::walk_files и печатал всё подряд, grep_search искал по
 * СОДЕРЖИМОМУ, а list (тогда list_dir) показывал один уровень. Модели оставалось
 * угадывать имена файлов вместо того, чтобы спросить «где тут лежат
 * тесты».
 *
 * Язык шаблонов (как у glob(7) и у opencode):
 *   **     — любое число сегментов каталога, включая ноль
 *   *      — любые символы внутри одного сегмента (не '/')
 *   ?      — ровно один символ
 *   {a,b}  — альтернативы (вложенные скобки разрешены)
 *
 * Два решения, которые неочевидны и поэтому зафиксированы здесь:
 *
 * 1. Скрытые файлы матчит обычный '*'. В bash `*` не матчит `.github`,
 *    и для человека это привычно, но агенту нужно другое: он ищет
 *    `.github/workflows/deploy.yml`, `.eslintrc`, `.env.example`. Если бы
 *    glob их не видел, модель получала бы пустой результат на законном
 *    вопросе и делала вывод «файла нет». Каталоги по умолчанию при этом
 *    не раскрываются (include_dirs = false) — иначе шаблон «две звёздочки
 *    и слэш» на репозитории дал бы десятки тысяч каталогов раньше файлов.
 *
 * 2. Время изменения (mtime) берётся для СОРТИРОВКИ, а не для вывода.
 *    Эпоха std::filesystem::file_time_type не задана стандартом, поэтому
 *    печатать это число как дату было бы прямой ложью. Порядок «свежие
 *    сверху» полезен агенту: он почти всегда ищет недавно изменённое.
 *
 * Симлинки не разворачиваются (directory_options::none): обход по ссылкам
 * либо зацикливается, либо выходит из проекта мимо гейта. Обход чикает
 * счётчик посещённых записей — иначе «*.zip в /» превратился бы в
 * минутное сканирование диска. Обе остановки ЧЕСТНО отражаются в
 * Result: результат, который выглядит полным, а неполон, хуже отказа.
 */

#include "limits.h"

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace coder {
namespace fileglob {

/* Каталоги, которые не обходятся по умолчанию. Совпадает с kSkipDirs
 * в base_tools.cpp — тот же список, чтобы glob и repo_map видели одно
 * и то же дерево. */
const std::vector<std::string>& default_skip_dirs();

/* Сопоставить путь шаблону. path — относительный путь с '/' в качестве
 * разделителя. Служебная функция, вынесенная наружу ради тестов:
 * правило «** матчит ноль сегментов» иначе нечем проверить. */
bool match_pattern(const std::string& pattern, const std::string& path);

struct Entry {
    /* Путь относительно корня обхода, разделитель '/'. */
    std::string path;
    /* Путь как есть (то, что вернул fs) — нужен вызывающему для чтения. */
    std::string abs_path;
    /* Имя файла или каталога. */
    std::string name;
    /* Время изменения в наносекундах от эпохи file_clock. Только для
     * сортировки: значение НЕ является датой (см. файл). */
    long long mtime_ns = 0;
    bool is_dir = false;
};

struct Options {
    /* Фильтр по расширению без точки, в нижнем регистре: {"php", "js"}.
     * Пусто — любые расширения. */
    std::vector<std::string> extensions;
    /* Сколько совпадений вернуть. */
    size_t limit = limits::kGlobLimit;
    /* Сортировать по убыванию времени изменения. */
    bool newest_first = true;
    /* Включать каталоги в результат. */
    bool include_dirs = false;
    /* Пропускаемые при обходе каталоги. Пусто — default_skip_dirs(). */
    std::vector<std::string> skip_dirs;
    /* Предохранитель обхода: сколько записей каталога осмотреть максимум. */
    size_t max_visited = limits::kGlobMaxVisited;
    /* Глубина обхода: 1 = только корень, 2 = один уровень вглубь.
     * 0 = без ограничения (для glob, которому нужна вся глубина).
     * Нужна инструменту list (И4.9): обход у них с файлом один, и вторая
     * реализация «обход с ограничением глубины» разошлась бы с первой. */
    size_t max_depth = 0;
};

struct Result {
    std::vector<Entry> entries;
    /* Сколько записей совпало с шаблоном ДО применения limit. */
    size_t matched = 0;
    /* limit сработал: entries — не полный список. */
    bool truncated = false;
    /* Обход остановлен предохранителем: найдено не всё, что есть. */
    bool walk_capped = false;
    /* Сколько записей каталога осмотрено. */
    size_t visited = 0;
    /* Непусто — почему поиск не выполнялся (нет такого каталога, пустой
     * шаблон). entries при этом пуст. */
    std::string error;
};

/* Найти файлы под root, соответствующие pattern.
 *
 * pattern задаётся относительно root. Абсолютный шаблон допускается:
 * если он начинается с root, префикс отбрасывается — модели регулярно
 * присылают путь целиком, и отказ здесь был бы не информативным.
 * Обратные слэши приводятся к '/' (модели пишут Windows-пути). */
Result find(const std::string& root, const std::string& pattern,
            const Options& options = Options());

} // namespace fileglob
} // namespace coder
