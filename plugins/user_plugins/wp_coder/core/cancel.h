#pragma once

/*
 * cancel.h — отмена работающего инструмента и индикатор отменяемости
 * (И11.10).
 *
 * ---------------------------------------------------------------------------
 * ЗАЧЕМ ФАЙЛ, ЕСЛИ ОТМЕНА УЖЕ ЕСТЬ
 * ---------------------------------------------------------------------------
 *
 * Отмена есть и работает: `Engine::request_abort` гасит токен хода
 * (core/abort.h), `LlmClient::fetch` рвёт на нём ожидание провайдера,
 * `bash` убивает группу процессов (И6.7). Чего не было — двух вещей, и
 * обе были про правду на экране:
 *
 * 1. ОТМЕНА НЕ ДОХОДИЛА ДО БОЛЬШЕЙ ЧАСТИ ИНСТРУМЕНТОВ. Таблица паритета
 *    так и говорила: «остальные инструменты отмену по требованию не
 *    проверяют». Инструмент, который не спрашивает токен, не остановится
 *    никогда: «стоп» на `repo_map` по большому дереву или на `docker
 *    build` ждал бы полного обхода и полной сборки. Теперь спрашивают
 *    (`ToolContext::cancelled`, `shell::run_capture_cancel`), а
 *    перечень — здесь, потому что он и есть ответ на вопрос «что именно
 *    прервётся».
 *
 * 2. ЧЕЛОВЕК НЕ ЗНАЛ, ЧТО СДЕЛАЕТ «СТОП». Кнопка выглядела одинаково
 *    всегда, а означала разное: ожидание модели обрывается мгновенно,
 *    `bash` убивается мгновенно, а запись файла нельзя прервать на
 *    середине (оборванный файл хуже недописанного намерения) — там отмена
 *    сработает ПОСЛЕ вызова. Одно молчание вместо трёх разных ответов —
 *    то есть ложь ровно там, где человек принимает решение ждать или
 *    жать.
 *
 * ---------------------------------------------------------------------------
 * КАК ОТМЕНЯЕМЫЙ ИНСТРУМЕНТ ОПРЕДЕЛЯЕТСЯ
 * ---------------------------------------------------------------------------
 *
 * Объявленным перечнем (`interruptible_tools`), а не флагом в ToolDef.
 * Флаг стоил бы рядом с обработчиком, и «проверяет ли инструмент токен»
 * осталось бы свойством, которое никто не сверяет: забытый флаг тихо
 * превратил бы обещание панели в ложь, а проверка «в перечне есть всё,
 * что помечено» — в форму. Перечень, наоборот, проверяется в обе
 * стороны: имя из перечня должно быть в живом реестре, а обработчик,
 * который спрашивает токен, должен быть в перечне (сканирование исходников
 * в тестах).
 *
 * ---------------------------------------------------------------------------
 * ЧТО ПАНЕЛЬ ГОВОРИТ ЧЕСТНО
 * ---------------------------------------------------------------------------
 *
 * 1. «СТОП» НЕ ВСЕГДА ОСТАНАВЛИВАЕТ — И ПАНЕЛЬ ГОВОРИТ, КОГДА ИМЕННО.
 *    Три разных ответа (сейчас / после вызова / уже запрошена) сведены в
 *    одну строку: `stop_now` — флаг для окна.
 *
 * 2. АТОМАРНЫЙ ИНСТРУМЕНТ НЕ ОБРЫВАЕТСЯ НА СЕРЕДИНЕ, И ЭТО НЕ ДЕФЕКТ
 *    ожидания, а решение: `write_file`, `apply_patch`, создание сайта —
 *    операции, у которых промежуточное состояние хуже отсутствия
 *    результата. Отмена для них — «дождаться и не продолжать».
 *
 * 3. НУЛЕВОЙ ВЫЗОВ НЕ ОТМЕНЯЕТСЯ. Токена нет — отменять нечем, и
 *    инструмент обязан отработать до конца (то же у `abort()` —
 *    nullptr не ошибка).
 *
 * ---------------------------------------------------------------------------
 * ПОЧЕМУ ЗДЕШНЯ ЛОК БЕРЁТ ВЫЗЫВАЮЩИЙ
 * ---------------------------------------------------------------------------
 *
 * Снимок снимается под `state_.mtx` и передаётся копией — тот же довод,
 * что у `token_panel` и `stream_panel`: мьютекс нерекурсивный и общий с
 * UI-потоком, а удерживать его под ImGui нельзя (D1, правило 3
 * SESSION_START). Полное снятие лока из отрисовки — И11.12.
 */

#include "engine.h"

#include <string>
#include <vector>

namespace coder {
namespace cancel {

/* Состояние агента с точки зрения отмены: ЧЕТЫРЕ ответа, а не семь имён
 * FSM (phase_of — единственное место, где они разложены).
 *
 * Отдельный перебор нужен из-за `Done`/`Error`/`Aborted`: ход закончен,
 * агент не работает, но состояние не Idle — кнопка «Стоп» по признаку
 * «не Idle» осталась бы на экране и обещала бы отмену того, что уже не
 * идёт. То же самое обещание, разбираемое в И11.14 для текста ошибки:
 * вид сбоя должен отличаться от «работа продолжается».
 *
 * Имена FSM сюда не заведены: панели нужен ответ на вопрос «есть ли что
 * отменять», а не весь список состояний движка. */
enum class Phase {
    Idle,      /* задачи нет */
    Working,   /* идёт ход: план, цикл, инструмент */
    Waiting,   /* ждёт решения человека */
    Finished,  /* ход закончен — отменять нечего */
};

/* Разложение состояния движка в ответы панели. */
Phase phase_of(AgentState state);

/* Когда подействует отмена, если человек нажмёт «Стоп» сейчас. */
enum class Interrupt {
    /* Инструмент сам спрашивает токен в своей работе и останавливается. */
    Now = 0,
    /* Инструмент атомарен: внутри него прерываться нельзя, отмена
     * сработает после возврата. */
    AfterCall,
};

/* Инструменты, останавливающиеся сами. Объявленный перечень: см. шапку. */
const std::vector<std::string>& interruptible_tools();

/* Отменяемость по имени. Инструмента нет или он не проверяет токен —
 * AfterCall: это правда по умолчанию, и она не обещает того, чего нет. */
Interrupt interrupt_of(const std::string& tool_name);

/* Снимок: что делает агент и что сделает «Стоп».
 *
 * Активный инструмент приходит ГОТОВЫМ, как в `stream_panel`: он берётся
 * из истории вызовом (шапка stream_panel.h, п. 3) — второе место правды
 * «что работает» разъехалось бы при первой же правке счётчика. */
struct Snapshot {
    /* Что агент делает сейчас: из этого решается, показывать ли кнопку. */
    Phase phase = Phase::Idle;
    /* Состояние движка словами («Выполнение»). Пусто — неизвестно. */
    std::string state_name;
    /* Активный вызов: имя инструмента и сколько он идёт. */
    std::string tool_name;
    long long tool_elapsed_ms = 0;
    /* Отмена уже запрошена: показать «останавливается», а не обещание. */
    bool cancel_requested = false;
    /* Агент ждёт решения человека (PermissionGate или PermissionEngine). */
    bool waiting_permission = false;
};

/* Модель панели. Окно рисует поля как есть и ничего не решает. */
struct Panel {
    /* Показывать: есть что отменять. */
    bool visible = false;
    /* Что агент делает сейчас. */
    std::string head_line;
    /* Что сделает «Стоп» — причина, по которой кнопка выглядит именно
     * так, и она же объясняет, почему нажатие может «не сработать». */
    std::string stop_line;
    /* Отмена сработает немедленно (окно красит строку акцентом). */
    bool stop_now = false;
    /* Отмена уже запрошена и ждёт. */
    bool stopping = false;
};

/* Сборка панели из снимка. Единственное место, где собираются подписи. */
Panel build(const Snapshot& snap);

/* Подпись того, что сделает «Стоп». Отдельная функция: решение «обещать
 * мгновенную отмену или сказать про конец вызова» проверяется отдельно от
 * остальной сборки. */
std::string stop_line(const Snapshot& snap);

}  // namespace cancel
}  // namespace coder