#pragma once

/*
 * token_panel.h — панель токенов и стоимости (И11.9).
 *
 * Панель отвечает на четыре вопроса, на которые человек раньше получал не
 * все ответы: сколько токенов ушло на вход и на выход, сколько из этого
 * кэш и размышление, сколько это стоило и сколько контекста занято.
 * Токены и скорость кое-где показывались — одной строкой в двух окнах, —
 * но стоимости не было нигде, а «размышление» и «кэш» не показывались
 * нигде: провайдер их присылает, состояние их не хранило (до И11.9), и
 * человек не видел, сколько запросов было дешёвыми.
 *
 * ---------------------------------------------------------------------------
 * ПОЧЕМУ РЕШЕНИЕ ЗДЕСЬ, А ОКНО ТОЛЬКО РИСУЕТ
 * ---------------------------------------------------------------------------
 *
 * Окно ImGui юнит-тестом не проверяется (тот же довод, что у 11.1, 11.4,
 * 11.5, 11.6, 11.7, 11.8): собирать подписи и решать, что видно, прямо в
 * окне значит проверять там, где проверять нечем. Здесь — снимок, все
 * решения и все подписи; окно рисует готовые строки.
 *
 * Снимок берётся ПОД ЛОКОМ и передаётся копией (то же, что у
 * `tool_display::snapshot`): `state_.mtx` нерекурсивный и общий с
 * UI-потоком, а удерживать его под ImGui — висящий UI (дефект D1,
 * правило 3 SESSION_START). Правка снятия лока целиком — И11.12.
 *
 * ---------------------------------------------------------------------------
 * ЧТО ПАНЕЛЬ ГОВОРИТ ЧЕСТНО, А ЧТО НЕ ГОВОРИТ
 * ---------------------------------------------------------------------------
 *
 * 1. СЧЁТЧИКИ — ЗА ЗАДАЧУ, А НЕ ЗА СЕССИЮ: `reset_task_metrics` обнуляет
 *    их на каждой задаче, и «итог» живёт ровно одну задачу. Панель, сложившая
 *    бы числа за сессию, врала бы о том, что агент потратил на этой задаче.
 *
 * 2. НОЛЬ ЦЕНЫ — «ЦЕНА НЕ ЗАДАНА», А НЕ «$0.00». Ставки приходят из
 *    настроек плагина (`wp_coder.price_input_per_1m`,
 *    `wp_coder.price_output_per_1m`), потому что у хоста их взять нечем: ABI
 *    отдаёт плагину только CUSTOM-настройки (`settings_get` →
 *    `Settings::has_custom_setting`), а цена модели лежит в настройках
 *    облачного провайдера хоста и наружу не выдаётся. Ноль цены означает
 *    «человек не задал», и «$0.00» утверждало бы, что работа была
 *    бесплатной, — самое частое и самое неверное прочтение такой панели.
 *    Отличить «бесплатно» от «не задано» движок не может, и панель не
 *    притворяется, что может.
 *
 * 3. ЦЕНА СЧИТАЕТСЯ ЦЕЛИКОМ: обе ставки заданы. Задана одна — сумма была бы
 *    посчитана по половине ставок и выглядела бы как итог; подпись называет,
 *    какой ставки не хватает.
 *
 * 4. КЭШ ТАРИФИЦИРУЕТСЯ ПО ЦЕНЕ ВХОДА, И ЭТО НАЗВАНО. Отдельной цены кэша
 *    настройка не задаёт: по инварианту `Usage` (`non_cached_input +
 *    cache_read + cache_write == input`) кэш ВНУТРИ входа, и складывать его
 *    второй раз нельзя. У части провайдеров кэш дешевле входа, поэтому сумма
 *    здесь верхняя оценка — панель говорит об этом словами, а не выдаёт
 *    число как точный счёт.
 *
 * 5. СКОРОСТЬ — ИЗ ИЗМЕРЕНИЯ ИЛИ НИКАКАЯ. `Engine::run_task` подставляет в
 *    `last_tokens_generated` ОЦЕНКУ (chars/4), когда провайдер не прислал
 *    usage, и `last_tokens_per_second` считается уже по ней. Такую скорость
 *    панель не показывает вовсе: «42 ток/с» рядом с «измерено» для контекста
 *    читалось бы как измерение, чем оно не является (тот же класс, что
 *    «измерено/оценка» в `compaction::ContextUsage`, И7.2). Источник числа
 *    приходит в снимке флагом — иначе панель судила бы о нём по нулю.
 *
 * 6. ДОЛЯ КОНТЕКСТА — ИЗ ТОГО ЖЕ ИСТОЧНИКА, ЧТО У КОМПАКШНА.
 *    `compaction::context_usage` и `compaction::usable` — единственные
 *    места, где выбирается измерение против оценки и порог окна. Панель не
 *    пересчитывает их своими формулами: второй расчёт разошёлся бы с
 *    порогом, по которому агент сжимает историю.
 *
 * 7. ПУСТОЙ ПАНЕЛИ НЕТ. Ноль токенов, ноль шагов и ноль времени — это «задача
 *    не идёт», а не «агент ничего не потратил»; рамка с заголовком и нулями
 *    выглядела бы как сломанный счётчик.
 */

#include "compaction.h"

#include <string>

namespace coder {
namespace token_panel {

/* Снимок того, что панель показывает. Снимается вызывающим под
 * `state_.mtx` и передаётся копией — по правилам шапки. */
struct Snapshot {
    /* Счётчики задачи: их копит `record_turn_usage`, а обнуляет
     * `reset_task_metrics` (п. 1). */
    long long input = 0;
    long long output = 0;
    long long reasoning = 0;
    long long cache_read = 0;
    long long cache_write = 0;

    /* Скорость из `EngineState::last_tokens_per_second` — единственное
     * число скорости в состоянии, второго панель не заводит (п. 5).
     * `tokens_estimated` — правда ли оно посчитано по измеренному usage:
     * иначе оценка chars/4 выдавала бы себя за измерение. */
    double tokens_per_second = 0;
    bool tokens_estimated = false;

    /* Время по задаче и отдельно по обращениям к модели. */
    double response_seconds = 0;
    double llm_seconds = 0;
    int steps = 0;

    /* Ставки за 1M токенов. Ноль — «не задана» (п. 2). */
    double input_price_per_1m = 0;
    double output_price_per_1m = 0;

    /* Контекст: столько занял последний запрос (`ContextUsage.source`
     * несёт, измерено это или оценка) и сколько помещается. */
    compaction::ContextUsage context;
    long long context_room = 0;
};

/* Модель панели. Окно рисует поля как есть и ничего не решает. */
struct Panel {
    /* Панель показывается, когда есть что показывать (п. 7 шапки). */
    bool visible = false;
    /* Вход с разбивкой по кэшу; выход с разбивкой по размышлению. */
    std::string input_line;
    std::string output_line;
    /* Стоимость либо слова о том, почему её нет. */
    std::string cost_line;
    /* Скорость из измерения либо объяснение, почему её нет. */
    std::string speed_line;
    /* Контекст: занято/помещается, доля и источник числа. */
    std::string context_line;
    /* Контекст упёрся в порог: окно красит строку предупреждением. */
    bool context_tight = false;
    /* Шаги и время задачи. */
    std::string steps_line;
};

/* Сборка панели из снимка. Единственное место, где собираются подписи. */
Panel build(const Snapshot& snap);

/* Число с разделителем разрядов: «12 345», а не «12345». Функция, а не
 * константа в шапке, — строка должна проверяться. */
std::string format_count(long long value);

/* Сумма по ставкам за 1M. Ноль при нулевой или отрицательной цене —
 * «считать нечего», а не «бесплатно»: вызывающий сам решает, что с этим
 * делать, по признакам «цена задана». */
double cost_for(const Snapshot& snap);

/* Подпись стоимости. Самостоятельная функция: решение «показать сумму или
 * сказать, чего не хватает» проверяется отдельно от арифметики. */
std::string cost_line(const Snapshot& snap);

/* Подпись скорости: измерение, оценка (не показывается) или её
 * отсутствие с причиной. */
std::string speed_line(const Snapshot& snap);

/* Подпись контекста: доля, источник числа и — если порог неизвестен —
 * слова о том, что порог не задан. */
std::string context_line(const Snapshot& snap, bool* tight);

}  // namespace token_panel
}  // namespace coder