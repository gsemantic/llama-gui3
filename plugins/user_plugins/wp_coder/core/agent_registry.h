/* Кому доступен агент (порт config/agent.ts: `mode`).
 *
 * Это НЕ режим работы агента из настроек движка (research/code/review,
 * И1.7): здесь «кто может его позвать». Смешение двух понятий в одном
 * слове `mode` уже стоило проекту переименования `Action` в
 * `PermissionAction` (отклонение №9). */
enum class AgentMode {
    Primary,   /* выбирает пользователь (в том числе через slash-команду) */
    Subagent,  /* звать может только инструмент task (И8.7) */
    All        /* и то и другое — умолчание, как в порте */
};

/* Имя режима строкой — для дампа, UI и сообщений об ошибке. */
const char* agent_mode_name(AgentMode mode);

/* Имя агента в канонической форме: без пробелов по краям, в нижнем
 * регистре. Проверки на допустимость здесь НЕТ — она отдельная, чтобы
 * нормализация и валидация не были двумя половинами одного правила.
 * Возвращает false, если после нормализации имя пусто. */
bool normalize_agent_name(const std::string& raw, std::string* out);

/* Допустимо ли имя. why — необязательный; при отказе в него кладётся
 * причина ПО-РУССКИ И С НАЗВАНИЕМ ВИНОВНОГО СИМВОЛА: имя приходит из
 * файла конфига, и «неверное имя» без указания, что не так, заставит
 * искать ошибку в парсере frontmatter (И8.2), где её нет. */
bool valid_agent_name(const std::string& name, std::string* why);

/* Правило из `permission:` в frontmatter, ЕЩЁ не нормализованное.
 *
 * И8.2 читает их как есть (ключ + паттерн + действие, в порядке
 * объявления), а И8.3 превращает в Ruleset: правила из `tools`,
 * склейка `write`/`edit`/`patch` в один ключ. Разделение не формальное:
 * упорядоченность правил — семантика (last match wins, core/permission.h),
 * и потерять её на разборе нельзя. */
struct PermissionEntry {
    std::string key;
    std::string pattern = "*";
    PermissionAction action = PermissionAction::Ask;
};

/* Что удалось понять из одного файла агента.
 *
 * `path` — откуда, чтобы сообщение пользователю называло файл, а не
 * «агент». Молча упавший конфиг — худший вид: агента нет, и неизвестно
 * почему. */
struct AgentLoadDiag {
    std::string path;
    std::string message;
};

/* Определение агента (И8.1).
 *
 * Поля И8.1 (`name`, `description`, `mode`, `hidden`) отвечали на
 * вопрос «кого видно». Остальные пришли в И8.2 из frontmatter и
 * разбираются в И8.3; здесь они лежат РАЗОБРАННЫМИ, но ещё не
 * приведёнными к правилам — `tools` остаётся legacy-картой bool,
 * `permission` — списком записей, а не Ruleset.
 *
 * Числа хранятся вместе с признаком «заданы»: `temperature: 0` и
 * «температура не задана» — разные вещи, и без признака первая
 * молча стала бы второй (это значения по умолчанию провайдера, а не
 * ноль). */
struct AgentDef {
    std::string name;
    std::string description;
    AgentMode mode = AgentMode::All;
    bool hidden = false;

    /* Тело файла (или ключ `prompt`, если он задан — см. ниже). */
    std::string prompt;

    std::string model;   /* пусто — модель сессии */
    std::string color;   /* для UI; на поведение не влияет */

    /* И9.7: имя профиля harness (`profile:` во frontmatter). Пусто —
     * профиля нет. Разбирается и проверяется владельцем правил (Info),
     * а не здесь: агент_registry не знает, где лежат файлы профилей, и
     * знать не должен — каталог приходит настройкой (И9.7). */
    std::string profile;

    bool has_temperature = false;
    double temperature = 0.0;
    bool has_top_p = false;
    double top_p = 0.0;
    bool has_steps = false;
    int steps = 0;

    /* `tools:` в его legacy-виде (карта «инструмент → можно»). */
    std::map<std::string, bool> tools;
    /* `permission:` — в порядке объявления (см. PermissionEntry). */
    std::vector<PermissionEntry> permission;
    /* Права В РОЛИ СУБАГЕНТА (И8.10). Заполняют только встроенные агенты
     * (register_builtin_agents); у агентов из файлов поле пусто, и их
     * правами управляет `permission`.
     *
     * Отдельное поле, а не ещё одна строка в `permission`, по причине,
     * которую видно только в 8.10: субагент наследует от сессии ТОЛЬКО
     * запреты, поэтому встроенному агенту, который должен что-то делать
     * без вопроса, это «что-то» надо разрешить именно здесь. В общем
     * `permission` такое правило перекрыло бы решение ПОЛЬЗОВАТЕЛЯ в
     * сессии (правила агента идут после базовых, И8.4) — то есть
     * встроенный агент, написанный не пользователем, отменял бы его
     * запрет. Права субагента не должны этого уметь. */
    std::vector<PermissionEntry> subagent_permission;
    /* Ключи, которых нет в известном наборе, — плюс содержимое группы
     * `options:` (разворачивается в имена БЕЗ префикса: карта
     * `options: {retries: "2"}` даёт опцию `retries`, а не
     * `options.retries`). Вложенность внутри — через точку
     * (`a: {b: 1}` → `a.b`): у options один тип, строка, и это тот же
     * тип, который читают человек и И8.3. */
    std::map<std::string, std::string> options;

    /* Откуда взялось (имя файла). Пусто у агентов из кода. */
    std::string source_path;
};

/* --- Загрузка из `.wpcode/agent/*.md` (И8.2, порт config/agent.ts:11) ---
 *
 * ФОРМАТ (подмножество YAML, ровно то, что нужно агенту):
 *
 *   ---
 *   description: Обзор проекта        # скаляр
 *   mode: subagent                    # primary | subagent | all
 *   model: qwen3-coder
 *   temperature: 0.2                  # число
 *   top_p: 0.95
 *   steps: 8                          # целое
 *   color: green
 *   hidden: true                      # true/false/yes/no/on/off
 *   tools:                            # legacy-карта «инструмент → можно»
 *     read: true
 *     bash: false
 *   permission:                       # правила (И8.3 превратит в Ruleset)
 *     bash: deny                      # → {bash, "*", deny}
 *     edit:
 *       "*": ask                      # → {edit, "*", ask}
 *       "*.env": deny                 # → {edit, "*.env", deny}
 *   options:
 *     retries: "2"                    # неизвестный ключ
 *   ---
 *
 *   Здесь начинается промпт — всё, что после закрывающего `---`.
 *
 * Что подмножество НЕ умеет и почему это приемлемо: многострочные
 * значения (`|` и `>`), списки словарей (`- key: value`), якоря и
 * вложенность глубже двух уровней. Для описания агента они не нужны,
 * а недоспарсенная конструкция не должна молча становиться строкой —
 * поэтому незнакомое отвергается с сообщением, а не игнорируется.
 *
 * ГРАНИЦЫ, ЗА КОТОРЫЕ ПРИНЯТО РЕШЕНИЕ (каждое — с последствием):
 *   - Нет строки `---` в начале файла → агент НЕ регистрируется,
 *     диагностика. Молча принятый файл дал бы агента без описания и
 *     без промпта, и он был бы виден в списке как пустая строка.
 *   - Неизвестное значение `mode` → агент НЕ регистрируется. Это
 *     единственное место, где отказ строгий: режим решает, может ли
 *     агент править файлы (wp_plan — не может), и опечатка, превращённая
 *     в «all», тихо дала бы редактирующего агента вместо
 *     спрашивающего. Остальные неверные значения (число, флаг, не
 *     известный инструмент) — диагностика без отказа: агент остаётся
 *     рабочим, а неверное поле просто не применяется.
 *   - Повтор ключа → последнее значение + диагностика (не ошибка:
 *     так же и в YAML, но молча).
 *   - Тело пустое и `prompt:` не задан → агент без промпта плюс
 *     диагностика: он не сломан, но человек наверняка что-то забыл.
 *   - `prompt:` в frontmatter перекрывает тело, и при обоих — диагностика:
 *     два промпта у одного агента означают, что правит один из них, а
 *     какой — узнать нельзя.
 */

/* Разбор одного файла. name — имя агента (обычно имя файла без .md);
 * source_path — путь для диагностики; пустой = имя агента.
 * нормализуется и проверяется реестром, а не здесь: правило имени
 * должно быть ОДНИМ, иначе загрузчик и реестр разойдутся на
 * файле вроде «My Agent.md».
 *
 * false — файл не годится и агент не будет зарегистрирован; о причинах
 * в diags. true — разбор состоялся, даже если были замечания (пустой
 * промпт, неизвестный ключ). */
bool parse_agent_markdown(const std::string& text, const std::string& name,
                          AgentDef* out, std::vector<AgentLoadDiag>* diags,
                          const std::string& source_path = "");

/* Загрузка каталога `*.md`. Файлы берутся в алфавитном порядке имени,
 * чтобы результат не зависел от порядка чтения каталога (при подмене
 * по имени — «Foo.md» и «foo.md» — побеждает более поздний, а «позже»
 * должно значить одно и то же при двух прогонах).
 *
 * Отсутствующий каталог — НЕ ошибка и не диагностика: `.wpcode/agent`
 * есть у единиц проектов, и предупреждение при каждой инициализации
 * движка было бы шумом. */
std::vector<AgentLoadDiag> load_agents_from_directory(
        const std::string& dir, std::vector<AgentDef>* out);

/* --- Нормализация (И8.3, порт agent/agent.ts:40-69) ---
 *
 * `tools:` (legacy-карта «инструмент → можно») и `permission:` —
 * два способа сказать одно и то же, и агент их читает как одно:
 *
 *   tools: {bash: false}                  →  bash: "*" → deny
 *   tools: {write_file: true}             →  write: "*" → allow
 *   permission: {edit: deny}              →  write: "*" → deny
 *   permission: {edit: {"*.env": deny}}   →  write: "*.env" → deny
 *
 * Три решения, каждое с последствием:
 *
 *   1. КЛЮЧ ПРИВОДИТСЯ К КАНОНИЧЕСКОМУ (canonical_permission_key,
 *      core/tool.h), а не наоборот: `edit`/`patch` — имена из
 *      словаря порта, а ключ нашей группы называется `write`
 *      (см. отклонение). Правило, написанное по порту, должно
 *      работать у нас, а не наоборот.
 *
 *   2. СНАЧАЛА `tools`, ПОТОМ `permission`. Совпадение берёт
 *      ПОСЛЕДНЕЕ правило (last match wins, core/permission.h), и
 *      `permission` — более точное высказывание (у него есть
 *      паттерн), поэтому оно идёт вторым. Обратный порядок отдал бы
 *      победу `tools`, и `permission: {bash: ask}` не смог бы
 *      перекрыть `tools: {bash: false}` — то есть более сильное
 *      правило не работало бы.
 *
 *   3. НЕИЗВЕСТНОЕ ИМЯ ОСТАЁТСЯ КЛЮЧОМ + ЗАМЕЧАНИЕ. Правило по
 *      несуществующему ключу безвредно и заработает, если
 *      инструмент появится; молча выбросить его значило бы узнать
 *      об опечатке по тому, что ограничение не сработало.
 *
 * diags необязателен: нормализация ничего не разрушает, и замечания
 * нужны только там, где результат показывают человеку. */
/* База правил РЕБЁНКА (И8.10) разложена на ДВЕ части, и разложена не
 * «для удобства», а потому что части стоят в разных концах набора.
 *
 * 1. subagent_place_rules — только `external_directory`, целиком, вместе с
 *    разрешениями на доверенные каталоги. Идёт ПЕРВЫМ: «куда можно ходить»
 *    не то же самое, что «что можно делать», и спрашивать пользователя у
 *    каждого субагента про /tmp значило бы превратить доверенный каталог в
 *    помеху. Своим правилом агент может это сузить (`wp_caged`, И8.7).
 * 2. subagent_inherited_denies — только запреты, и идут ПОСЛЕДНИМИ.
 *    Побеждает последнее совпадение, поэтому запрет в базе перекрывался бы
 *    grant'ом встроенного агента: плагин отменил бы «я запретил себе
 *    писать». Решение человека не отменяется правилом, которое человек не
 *    писал (8.15).
 *
 * Права на действия не наследуются: см. Info::for_subagent. */
Ruleset subagent_place_rules(const Ruleset& session_rules);
Ruleset subagent_inherited_denies(const Ruleset& session_rules);

