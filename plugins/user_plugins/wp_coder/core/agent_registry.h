/*
 * agent_registry.h — Реестр агентов плагина (И8.1).
 *
 * Почему свой, а не хостовый `src/agents/agent_registry.cpp`
 * -----------------------------------------------------------
 * Хостовый AgentRegistry — плоская таблица для slash-команд: по имени
 * находится объект, у него зовётся execute() с готовым JSON-запросом,
 * наружу уходит AgentResult. Цикла агента там нет: нет истории
 * сообщений, нет инструментов, нет разрешений, нет отмены, нет
 * дочерних сессий. Реестр плагина — часть ядра (D-7, wp_coder_core
 * не зависит от хоста) и часть цикла: он решает, кого вообще можно
 * позвать и что этому агенту дозволено.
 *
 * Что именно здесь, а что в следующих задачах
 * --------------------------------------------
 * И8.1 — САМ РЕЕСТР: имена, порядок, видимость, потокобезопасность.
 * И8.2 принесёт разбор frontmatter, И8.3 — нормализацию `tools` в
 * правила, И8.4 — рантайм-структуру `Agent::Info`. Поля ниже выбраны
 * по одному признаку: реестр заводит только то, по чему сам решает,
 * КОГО видно. Тело агента (prompt, model, temperature, tools,
 * permission, steps, options) — это И8.2–8.4; описывать их здесь
 * заранее значило бы завести поля, которые ещё никто не читает.
 *
 * Четыре решения, которые здесь принимаются и на которых потом стоит
 * всё остальное
 * -----------------------------------------------------------------
 * 1. ИМЯ НОРМАЛИЗУЕТСЯ, А НЕ ОТВЕРГАЕТСЯ ПО РЕГИСТРУ. `find()`
 *    принимает "WP_Build" и находит `wp_build`. Причина не в удобстве:
 *    имя приходит от модели (аргумент `subagent_type` инструмента
 *    `task`, И8.7) и от имени файла конфига, и оба пишут его
 *    «как получилось». Отказ по регистру означал бы, что агент
 *    существует, виден в списке — и не находится, то есть отказ
 *    выглядит как «нет такого агента». Пробелы по краям срезаются
 *    (имя файла приходит с ними), а вот недопустимые символы —
 *    отвергаются: имя попадает в описание инструмента и в текст
 *    ошибки, и `*` или пробел посередине сделали бы описание нечитаемым.
 *
 * 2. ПОРЯДОК РЕГИСТРАЦИИ СОХРАНЯЕТСЯ, И ЗАМЕНА МЕСТА НЕ МЕНЯЕТ.
 *    По этому порядку собирается и список в UI, и динамическое
 *    описание инструмента `task` (И8.13), то есть он попадает в
 *    КАЖДЫЙ ход. Если бы переопределение двигало агента в конец,
 *    добавление одного файла `.wpcode/agent/my.md` меняло бы весь
 *    промпт, а сравнение двух ходов перестало бы значить что-либо.
 *
 * 3. ОПРЕДЕЛЕНИЕ ПОСЛЕ РЕГИСТРАЦИИ НЕ МУТИРУЕТСЯ — на уровне типов.
 *    Наружу отдаётся `shared_ptr<const AgentDef>`, а замена подменяет
 *    сам указатель. Это не форма вежливости: И8.4 требует, чтобы
 *    Ruleset агента был ПРЕДВЫРОВЛЕН и не менялся во время работы
 *    (правило дописывается только одно — `approved`), а «не
 *    мутируется» на уровне соглашения рано или поздно нарушается
 *    вызывающим, который получил не-const ссылку.
 *
 * 4. РЕЕСТР — ОДНА ТОЧКА ПРАВДЫ О ВИДИМОСТИ. `primary_names()` и
 *    `subagent_names()` — это не две подсказки, а ответы на два
 *    разных вопроса («кого выбирает пользователь» и «кого можно
 *    вызвать из `task`»), и оба читают одно и то же состояние.
 *    Скрытый агент (`hidden`) не попадает ни в один список, но
 *    остаётся находимым по имени: скрытый — это «не показывать»,
 *    а не «выключить».
 *
 * Ограничения (общие для core/, повторяю здесь, потому что это
 * единственный класс, который читают и UI, и worker агента):
 *   - свой `mtx_`, и НИКОГДА `state_.mtx` (тот же запрет, что у
 *     PermissionEngine — И2.3);
 *   - наружу отдаются КОПИИ и `shared_ptr`, и лок живёт ровно до
 *     конца метода (D-6: считать под локом и отдать указатель в
 *     UI нельзя);
 *   - оба фильтра и `all()` строятся под локом целиком: список,
 *     собранный половиной, — это список, который на втором вызове
 *     окажется другим.
 */

