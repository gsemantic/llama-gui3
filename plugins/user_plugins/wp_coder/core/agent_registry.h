/* --- Рантайм-структура агента (И8.4) ---
 *
 * `AgentDef` — это то, что лежит в файле. `agent::Info` — то, с чем
 * работает цикл, и разница между ними не в «большем наборе полей», а в
 * трёх вещах, которые на файле делать нельзя:
 *
 *   1. ПРАВИЛА СВЕДЕНЫ И ПРИВЕДЕНЫ К КЛЮЧАМ (canonical_permission_key,
 *      И8.3) и разложены в правильном порядке: сначала база (дефолты
 *      уровня агента и правила пользователя), потом правила агента, то
 *      есть агент перекрывает базу, а не наоборот. Во время работы это
 *      уже не вычисляется — иначе решение «что разрешено» принималось бы
 *      заново на каждом вызове инструмента и могло бы разойтись с тем,
 *      что показано пользователю.
 *
 *   2. ЗАМОРОЖЕНО. `rules()` отдаёт `const Ruleset&`, и во время работы
 *      в неё не пишет НИКТО. Единственное, что растёт, — `approved`:
 *      ответы пользователя «всегда». Правило «не мутируй», написанное в
 *      комментарии, нарушается первым же вызывающим с не-const ссылкой;
 *      здесь эту возможность убрали типом и разделением на два набора.
 *
 *   3. ЗАПРЕТ ЦЕЛИКОМ РЕШАЕТСЯ ИЗ ЗАМОРОЖЕННЫХ ПРАВИЛ, а не из
 *      отдельного списка. Список «запрещённых ключей» тут был бы вторым
 *      местом одного факта: он считывается при сборке, а ответы
 *      «всегда» меняют картину позже, и список разошёлся бы с
 *      правилами — то есть инструмент остался бы скрытым при
 *      разрешении, которое пользователь только что дал. Ответ на
 *      «запрещён ли ключ целиком» — это `evaluate(ключ, "*")`: тот же
 *      самый вопрос, тем же кодом, с наложением `approved`.
 *
 * `approved` живёт под своим мьютексом именно потому, что он — единственная
 * растущая часть: она читается на каждом вызове инструмента (worker-поток)
 * и пополняется ответами пользователя (UI-поток), тогда как замёрзшая
 * `rules_` после сборки не меняется вовсе. */
namespace agent {

class Info {
public:
    /* Копирования нет: внутри мьютекс растущей части, и копия разошлась
     * бы с оригиналом по «всегда»-ответам. Делиться — можно, отсюда и
     * shared_ptr в сборке. */
    Info(const Info&) = delete;
    Info& operator=(const Info&) = delete;

    /* Сборка из определения и базовых правил сессии.
     *
     * shared_ptr, а не значение: рантайм-агента читают и worker-поток
     * (решение по каждому вызову инструмента), и UI (панель правил), и
     * копия правил «всегда» между ними — расхождение, после которого
     * агент ведёт себя не так, как показано пользователю.
     *
     * profile — профиль harness агента (`profile:`, И9.7). nullptr —
     * профиля нет. Его запреты кладутся в БАЗУ, до правил агента: файл
     * агента и профиль названы в одном frontmatter, и если бы запрет
     * профиля лег после `permission`, то агент не смог бы объявить себя
     * уже — то есть строка в том же файле была бы мёртвой. */
    static std::shared_ptr<Info> from_def(const AgentDef& def, const Ruleset& base,
                                          std::vector<AgentLoadDiag>* diags = nullptr,
                                          const harness::Profile* profile = nullptr);

    /* Сборка рантайма СУБАГЕНТА (И8.10). Отличие от from_def не в
     * оформлении, а в трёх правилах, и каждое стоит своего места:
     *   1. база — из правил сессии наследуется ТОЛЬКО ключ
     *      `external_directory` (subagent_place_rules). Разрешения и
     *      «спросить» не наследуются: решение пользователя «всегда
     *      разрешить» относится к ЕГО диалогу, и тихая передача его
     *      агенту означала бы, что делегирование обходит права, о которых
     *      человек знает;
     *   2. поверх базы — права агента (`permission`) и права в роли
     *      субагента (`subagent_permission`, встроенные агенты);
     *   3. авто-запрет на `task` и `todo` там, где агент не сказал о них
     *      ничего (порядок правил решает: запрет идёт последним и
     *      перекрывает);
     *   4. и последними — ЗАПРЕТЫ СЕССИИ (subagent_inherited_denies):
     *      встроенный grant не вправе отменить запрет человека.
     *
     * Вызывающий — инструмент `task` (subagent.cpp). Основной агент
     * собирается по-прежнему через from_def: сужение относится к
     * делегированию, а не к агенту вообще. */
    static std::shared_ptr<Info> for_subagent(
        const AgentDef& def, const Ruleset& session_rules,
        std::vector<AgentLoadDiag>* diags = nullptr,
        const harness::Profile* profile = nullptr);

    const std::string& name() const { return name_; }
    const std::string& description() const { return description_; }
    AgentMode mode() const { return mode_; }
    bool hidden() const { return hidden_; }
    const std::string& prompt() const { return prompt_; }
    const std::string& color() const { return color_; }
    const std::string& model() const { return model_; }
    bool has_temperature() const { return has_temperature_; }
    double temperature() const { return temperature_; }
    bool has_top_p() const { return has_top_p_; }
    double top_p() const { return top_p_; }
    /* Шаги агента; 0 — «не заданы», и тогда шаги сессии. */
    int steps() const { return steps_; }
    const std::map<std::string, std::string>& options() const { return options_; }
    const std::string& source_path() const { return source_path_; }

    /* Замороженные правила. Наружу — только для чтения: см. п. 2. */
    const Ruleset& rules() const { return rules_; }
    /* Решение по паре (ключ, значение): сначала замёрзшая часть, потом
     * `approved` — ответ «всегда» новее любого правила конфига. */
    PermissionAction evaluate(const std::string& key,
                               const std::string& pattern) const;

    /* Запрещён ли ключ ЦЕЛИКОМ — то есть скрывать ли инструмент из
     * каталога модели (И2.8, И8.13). Точечный запрет («edit: *.env →
     * запретить») инструмент не прячет: он запрещает значения, а сам
     * инструмент нужен. Ответ «всегда» скрытие снимает. */
    bool denies_whole_key(const std::string& key) const;

    /* Единственный способ изменить правила во время работы. */
    void approve(const std::string& key, const std::string& pattern);

private:
    /* Сборка живёт в конструкторе, а не в отдельной функции-фабрике:
     * класс с мьютексом нельзя ни скопировать, ни переместить, и
     * `make_shared` в private-конструктор тоже не пускает. */
    /* Роль определяет СБОРКУ правил (8.4 против 8.10), поэтому она
     * аргументом конструктора, а не флагом внутри from_def: одна
     * функция с булевым параметром «субагент ли» рано или поздно была бы
     * вызвана с флагом наоборот, и разница стала бы невидимой. */
    enum class Role { Primary, Subagent };

    Info(const AgentDef& def, const Ruleset& base,
         std::vector<AgentLoadDiag>* diags, Role role,
         const harness::Profile* profile);

    std::string name_;
    std::string description_;
    std::string prompt_;
    std::string model_;
    std::string color_;
    std::string source_path_;
    std::map<std::string, std::string> options_;
    AgentMode mode_ = AgentMode::All;
    bool hidden_ = false;
    bool has_temperature_ = false;
    double temperature_ = 0.0;
    bool has_top_p_ = false;
    double top_p_ = 0.0;
    int steps_ = 0;

    Ruleset rules_;                      /* заморожена */
    mutable std::mutex approved_mtx_;
    Ruleset approved_;                   /* единственная растущая часть */
};

} // namespace agent



class AgentRegistry {
public:
    /* Единственный экземпляр процесса — для кода (Engine, UI).
     * Тесты создают СВОИ экземпляры (`AgentRegistry reg;`): общий
     * синглтон протекал бы между тестами, а состояние агентов — из
     * тех, что положено восстанавливать (правило 5 SESSION_START). */
    static AgentRegistry& instance();

    AgentRegistry() = default;

    /* Регистрация агента.
     *
     * Возвращает false и заполняет error, только если имя недопустимо.
     * Агент с уже занятым именем НЕ считается ошибкой: он ЗАМЕЩАЕТ
     * прежнего (пользовательский конфиг перекрывает встроенного — так
     * и в порте) и сохраняет своё место в порядке перечисления.
     * Нужно ли было заменять — вызывающий узнаёт сам, ДО add():
     * `bool existed = reg.has(name);` — отдельного флага «заменён»
     * здесь нет намеренно, иначе одно и то же сказали бы два
     * способа (реестр и вызывающий), и они разошлись бы при гонке. */
    bool add(AgentDef def, std::string* error = nullptr);

    /* Поиск по имени. Аргумент нормализуется, поэтому find(" WP_Build ")
     * находит `wp_build`. Нет агента — nullptr. */
    std::shared_ptr<const AgentDef> find(const std::string& name) const;
    bool has(const std::string& name) const;

    /* Все агенты, включая скрытых, в порядке регистрации. Скрытость
     * относится к спискам (см. шапку), а не к самому агенту. */
    std::vector<std::shared_ptr<const AgentDef>> all() const;

    /* Списки видимых: для выбора агента пользователем и для описания
     * инструмента `task` (И8.13). Скрытые исключены из обоих. */
    std::vector<std::string> primary_names() const;
    std::vector<std::string> subagent_names() const;

    /* Снять агента по имени; true — был и снят. */
    bool remove(const std::string& name);
    /* Снять всех (перечитывание конфигурации, И8.2). */
    void clear();

    /* Загрузить агентов из каталога и зарегистрировать их (И8.2).
     * Возвращает диагностику: один плохой файл не отменяет остальные,
     * но пользователь должен увидеть, какой именно. Зовётся из
     * Engine::load_settings — иначе загрузчик существовал бы, а
     * никто его не звал бы (тот же класс, что D2). */
    std::vector<AgentLoadDiag> load_directory(const std::string& dir);

    size_t size() const;

private:
    /* Снимок под локом: оба фильтра отличаются от all() только
     * отбором, и собирать их здесь — значит не дать фильтру
     * разойтись с тем, что зарегистрировано. */
    std::vector<std::shared_ptr<const AgentDef>> snapshot_locked() const;

    mutable std::mutex mtx_;
    /* Порядок регистрации. Вектор, а не map: map отсортировал бы
     * имена по алфавиту, и встроенные агенты (wp_*) оказались бы
     * после пользовательских, а порядок в промпте менялся бы от
     * того, какие файлы лежат в каталоге. */
    std::vector<std::shared_ptr<AgentDef>> order_;
    /* Имя → позиция в order_. */
    std::map<std::string, size_t> index_;
};

/* --- Встроенные агенты (И8.5, порт agent/agent.ts:119-265) ---
 *
 * Встроенные агенты — это ТА ЖЕ структура, что и конфиг-агенты: тот же
 * AgentDef, тот же реестр, то же правило замены. Отдельный класс
 * «встроенных» означал бы второе место, где описаны агенты, и они
 * разошлись бы с конфиг-агентами по всем четырём свойствам сразу.
 *
 * ПОРЯДОК РЕГИСТРАЦИИ ЗАДАЁТ СМЫСЛ: встроенные идут первыми, поэтому
 * конфиг-агент с тем же именем ЗАМЕЩАЕТ встроенного на его месте, а не
 * переставляет его в конец списка (см. шапку, п. 2).
 *
 * Кто именно живёт здесь и почему не все семь (отклонение №75):
 *   wp_build    — агент по умолчанию: права сессии, ничего не сужает.
 *   wp_plan     — планировщик: `write` запрещён. Единственный агент,
 *                 которому нельзя редактировать, и это правило, а не
 *                 просьба в промпте.
 *   wp_general  — субагент для делегированной задачи (8.7).
 *   wp_explore  — чтение проекта без правок; полный набор инструментов
 *                 и промпт с тщательностью — 8.6.
 *   compaction / title / summary — НЕ заводятся: сводщик уже есть
 *                 кодом (И7.5), генератора названий нет, а «summary» у
 *                 нас называется `compaction`. Три описания поверх двух
 *                 сущностей — это ровно тот дрейф, который запрещён. */
void register_builtin_agents(AgentRegistry& reg);

