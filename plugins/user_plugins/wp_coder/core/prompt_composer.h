#pragma once

/*
 * prompt_composer.h — единый порядок слоёв системного промпта.
 *
 * Зачем отдельный модуль. Раньше порядок жил в цепочке `sys += ...` внутри
 * Engine::build_system_prompt: комментарий описывал его, но ничто не мешало
 * следующей правке поставить блок не туда. Здесь порядок — это enum, а
 * compose_prompt сортирует блоки по нему. Добавить слой «в середину» можно
 * только изменив enum, то есть осознанно.
 *
 * Порядок выбран по образцу OpenCode V2 (agents/instructions/skills/tools):
 * сначала ПРОТОКОЛ и роль, затем факты о проекте и правила, затем ЧТО
 * доступно (инструменты/навыки), и в самом конце — самое изменчивое
 * (план, режим). Изменчивый хвост не рушит префикс провайдерского кэша.
 *
 * Зафиксирован тестом test_prompt_composer.cpp: порядок — контракт, а не
 * комментарий.
 */

#include <string>
#include <vector>

namespace coder {

enum class PromptLayer {
    /* Корень проекта — первым и всегда: он должен выжить при любом
     * пользовательском override. */
    ProjectRoot = 0,
    /* Базовый протокол (провайдер/семейство модели) либо заменяющий его
     * пользовательский текст в режиме `replace`. */
    Base,
    /* Роль агента из agent.md — дополнение к базе, не замена. */
    AgentRole,
    /* Пользовательские инструкции: `agent_system_prompt` в режиме append. */
    UserInstructions,
    /* Страховка «сначала осмотри проект» — не зависит от выбранного
     * промпта. */
    Safety,
    /* Факты об окружении: каталог, git, платформа, дата. */
    Environment,
    /* AGENTS.md/CLAUDE.md и настроенные `instructions`. */
    Instructions,
    /* Системный промпт активного модуля (Python/WordPress/DevOps). */
    Module,
    /* Каталог инструментов — только для текстового протокола. */
    Tools,
    /* Индекс навыков: имена и описания, без тел. */
    Skills,
    /* План задачи (todowrite). */
    Plan,
    /* Переопределение текущего режима (research/review). */
    Mode,
    Count
};

struct PromptBlock {
    PromptLayer layer = PromptLayer::Base;
    std::string text;
};

/* Имя слоя — для дампа и сообщений об ошибке. */
const char* prompt_layer_name(PromptLayer layer);

/* Склеить блоки в каноническом порядке слоёв. Внутри одного слоя
 * сохраняется порядок добавления (stable sort). Пустые блоки
 * пропускаются, разделитель — пустая строка между блоками. */
std::string compose_prompt(std::vector<PromptBlock> blocks);

} // namespace coder
