#pragma once

/*
 * llm_client.h — единый вход к LLM: события по мере поступления (И6.5).
 *
 * Зачем отдельный файл, если llm_source::fetch уже есть. fetch отдаёт
 * ВЕКТОР событий, собранный из ответа целиком: цикл получает всё сразу и
 * ждёт. Стриминг меняет не подпись, а момент доставки — и менять три
 * места зова (Planner, цикл, хвостовой ход) нельзя, они разъедутся снова,
 * как разъехались в И5.
 *
 * Поэтому здесь одна функция с той же формой вызова:
 *
 *   out_events  — АВТОРИТЕТНАЯ последовательность хода. Собирается из
 *                 финального ответа тем же разбором протокола, что и
 *                 блокирующий путь (llm_source::reply_to_events), то есть
 *                 оба пути физически не могут разойтись: разбор один.
 *   on_event    — ЖИВАЯ доставка по мере поступления. Это предпросмотр:
 *                 блок вызова в нём ещё присутствует как текст, потому
 *                 что из потока его вырезать нельзя — блок известен только
 *                 в конце. Потребитель (UI, И11) показывает его как
 *                 «модель печатает», а собранный ход берёт из out_events.
 *
 * Почему это различие названо прямо, а не спрятано: если бы on_event и
 * out_events несли одно и то же, «блок вызова уехал в текст» тихо
 * испортило бы и историю, и следующий запрос. Два источника с разными
 * контрактами — это то, что можно проверить; два источника с одинаковым
 * контрактом и разным поведением — нет.
 *
 * Что здесь НЕ живёт и почему:
 *   - разбор протокола wp_action: он в llm_source (И5.7), и его
 *     дублирование здесь означало бы две версии одного протокола;
 *   - условие завершения хода: это политика агента (AgentLoop, И5.8);
 *   - отмена: хост её не умеет (И6.6). Здесь есть только таймаут и
 *     abandonment — чтобы прерванный по таймауту потет не продолжал
 *     дописывать текст в UI.
 */

#include "abort.h"
#include "engine.h"
#include "llm_event.h"

#include <functional>
#include <string>
#include <vector>

namespace coder {

class LlmClient {
public:
    /*
     * Один ход. Возвращает false, если ход не состоялся; тогда
     * out_events не пуст и содержит ProviderError — ровно как у
     * llm_source::fetch, чтобы вызывающий не знал, откуда пришла ошибка.
     *
     * on_event может быть пустым: тогда поведение совпадает с
     * llm_source::fetch один в один, и вызывающий может этим
     * пользоваться (например, в тестах, где интересует только результат).
     *
     * Функция БЛОКИРУЮЩАЯ. Стриминг меняет момент доставки on_event, а не
     * время возврата: циклу нужно знать, закончился ли ход, иначе он
     * продолжит работу с недописанным ответом. Ожидание ограничено
     * llm_timeout_ms — иначе хост, нарушивший контракт on_done, повесил бы
     * агента навсегда.
     *
     * abort — отмена хода (И6.6). Здесь она НАСТОЯЩАЯ, если у хоста есть
     * llm_chat_cancel: поток обрывается по-настоящему и локальный сервер
     * освобождает слот. Если поля нет (старый хост) — отмена означает
     * «перестать ждать»: генерация дойдёт до конца, и это ограничение хоста,
     * а не молчаливое обещание. Прерванный ход возвращает false и кладёт
     * ProviderError с текстом «Прервано пользователем» — вызывающий обязан
     * отличать отмену от сбоя, иначе «Стоп» выглядел бы как ошибка (И6.8
     * разводит эти состояния терминально).
     */
    static bool fetch(const HostCallbacks& cb, const std::string& sys_prompt,
                      const std::vector<ModelMessage>& history,
                      std::vector<LlmEvent>& out_events,
                      const std::function<void(const LlmEvent&)>& on_event = nullptr,
                      int timeout_ms = -1,
                      AbortToken* abort = nullptr);
};

} // namespace coder
