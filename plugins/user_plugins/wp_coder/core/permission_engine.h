#pragma once

/*
 * permission_engine.h — Движок разрешений (И2.3–2.8).
 *
 * Ruleset (core/permission.h) — это чистые данные: список правил и
 * функция «что они решили». PermissionEngine — то, что поверх них:
 *
 *   - ПРАВИЛА ЖИВУТ В СЕССИИ. Пользователь ответил «всегда» на деплой —
 *     и деплой больше не спрашивает до явного сброса. Поэтому движок
 *     принадлежит Engine (синглтону сессии), а не создаётся на один
 *     вызов инструмента.
 *
 *   - ПРАВИЛА МЕНЯЮТСЯ НА ЛЕТУ, значит нужен свой мьютекс. Но НЕ
 *     state_.mtx: state_.mtx нерекурсивный, общий с UI, и захват его
 *     здесь означал бы две разные блокировки в двух порядках
 *     (дедлок И0.1 в новом месте). Правило, которое держится всю
 *     итерацию: PermissionEngine НИКОГДА не берёт state_.mtx, пока
 *     держит свой mtx_, и никогда не ждёт на своём condvar, не отпустив
 *     mtx_. Касание состояния движка — короткими отдельными захватами
 *     (см. permission_engine.cpp, ask()).
 *
 *   - ЗАПРОС К ПОЛЬЗОВАТЕЛЮ = блокировка рабочего потока агента на
 *     condvar. Ровно так же, как уже работает PermissionGate для путей
 *     за пределами проекта (И0.3), только теперь ожидание умеет
 *     обслуживать несколько запросов сразу и каскадно отклоняться
 *     (И2.6).
 */

#include "permission.h"
#include "tool.h"

#include <functional>
#include <condition_variable>
#include <cstdint>
#include <mutex>
#include <string>
#include <vector>

namespace coder {

/* Состояние движка нужно только для моста в UI (WaitingPermission) и
 * для проверки прерывания. Полное объявление — в engine.h, здесь хватает
 * предварительного: permission_engine.h включается из engine.h. */
struct EngineState;

/* --- Запрос разрешения, висящий на пользователе (И2.5) --- */
struct PermissionRequest {
    uint64_t id = 0;                 /* для ответа из UI: «решаю вот этот» */
    std::string permission;          /* ключ: "bash", "deploy", "read"… */
    std::vector<std::string> patterns; /* что именно спрашиваем */
    std::string suggested;           /* предлагаемый паттерн для «всегда» */
    std::string metadata;            /* для панели: команда, путь, хост */
    bool decided = false;
    bool allowed = false;            /* заполняется при ответе */
    bool always = false;             /* ответили «всегда» */
};

/* Ответ на запрос разрешения. */
enum class PermissionReply { Once, Always, Reject };

class PermissionEngine {
public:
    PermissionEngine();

    /* Привязка к состоянию движка и логу событий. Без привязки движок
     * работает как чистая машина правил (тесты так и проверяют её),
     * но не умеет показать вопрос пользователю. Ставится один раз
     * из Engine::init. */
    void bind(EngineState* state, std::function<void(const std::string&)> push);

    /* --- Правила --- */
    Ruleset& rules() { return rules_; }
    const Ruleset& rules() const { return rules_; }
    /* Копия правил под локом. Нужна там, где Ruleset копируется в
     * долгоживущий объект (agent::Info, И8.7): правила меняются из
     * UI-потока, а ссылка пережила бы их изменение и разошлась бы с
     * тем, что показывает панель. */
    Ruleset rules_snapshot() const;
    void set_rules(Ruleset r);
    void add_rule(Rule r);
    /* Правила по-русски — для панели настроек. */
    std::string rules_dump() const;

    /* --- Решение --- */
    /* И2.3: что говорят правила про пару (ключ, значение). Правил нет —
     * Ask: не описанное поведение спрашивает, а не разрешает. */
    PermissionAction evaluate(const std::string& permission,
                    const std::string& pattern) const;

    /* Сброс правил и накопленных «всегда»-разрешений. Вызывается при
     * старте сессии и в тестах: Engine — синглтон, состояние между
     * тестами протекает. */
    void reset();

    /* Дефолты уровня агента (И2.4) — порт agent/agent.ts:119-140.
     * Ставится из Engine::load_settings(), потому что trusted_dirs
     * знает только он: data_dir приходит от хоста (HostCallbacks),
     * каталог навыков — от SkillsManager. Ядро разрешений о хосте
     * не знает ничего (D-7), поэтому список приходит снаружи.
     *
     * Идемпотентно: повторный вызов ничего не делает, чтобы настройки
     * не затирали ответы «всегда». Пересборка базы — только через
     * reset() + apply_agent_defaults(). */
    void apply_agent_defaults(const std::vector<std::string>& trusted_dirs);
    /* Установлены ли дефолты (нужно, чтобы load_settings можно было
     * звать повторно, не затирая ответы «всегда»). */
    bool has_agent_defaults() const;

    /* Сколько ждать ответа пользователя, мс. 0 (по умолчанию) — ждать
     * бесконечно, пока не ответят либо не прервут задачу. Тесты и
     * headless-режим ставят конечное значение: ожидание, на которое
     * никто не ответит, зависло бы насмерть — ровно тот класс висящего
     * GUI, который закрыл дефект D1. */
    void set_wait_timeout_ms(int ms);
    int wait_timeout_ms() const;

    /* Вызывается, когда правила изменились: у движка сбрасывается кэш
     * системного промпта (набор видимых инструментов мог измениться).
     * Ставится из Engine — core не знает про кэш промпта. */
    void set_on_change(std::function<void()> cb);

    /* --- Ожидание пользователя (И2.5) --- */

    /* Спросить пользователя и дождаться ответа. Блокирует worker-поток
     * агента — ровно так же, как PermissionGate блокирует его на пути
     * за пределами проекта, только запросов в очереди может быть
     * несколько и у каждого есть свой адрес для ответа.
     *
     * patterns      — что именно спрашиваем (путь, команда, хост):
     *                  показывается пользователю и уходит в правило
     *                  при ответе «всегда».
     * always_pattern— предлагаемый паттерн для кнопки «всегда».
     * metadata      — текст для панели и для лога.
     * always_out    — необязательный: «пользователь ответил ВСЕГДА, и
     *                  это правило уже записано». И8.7: правила агента
     *                  заморожены при сборке (И8.4), поэтому агент,
     *                  спросивший разрешения, должен узнать про ответ
     *                  иначе — он спросил бы то же самое при каждом
     *                  следующем вызове, и кнопка «всегда» выглядела бы
     *                  сломанной именно на субагенте. Про nullptr, как и
     *                  раньше: вызывающему, которому различие не нужно.
     *
     * Возвращает true, если разрешено. Отказ, отмена и отсутствие
     * ответа — false: fail-closed.
     *
     * ПРО ДЕДЛОК (тот же класс, что D1): mtx_ не берётся поверх
     * state_.mtx и не удерживается во время ожидания. Касание состояния
     * движка — отдельными короткими захватами до и после ожидания.
     * Поэтому из кода, который УЖЕ держит state_.mtx, ask() звать
     * нельзя. */
    bool ask(const std::string& permission,
             const std::vector<std::string>& patterns,
             const std::string& always_pattern,
             const std::string& metadata,
             bool* always_out = nullptr);

    /* Ответить на запрос по id. false — такого id уже нет (устарел или
     * отвечено): UI не должен этим пугать пользователя. */
    bool reply(uint64_t id, PermissionReply how);

    /* И2.7: внести постоянное разрешение «всегда» и ПЕРЕСКАНИРОВАТЬ
     * ожидающие: те, что под новое правило подпадают, разрешаются сами,
     * без второго щелчка пользователя по тому же решению. Публичный
     * вход: этим же методом постоянные разрешения заводятся из панели
     * настроек и из PermissionGate (путь за пределами проекта). */
    void approve(const std::string& permission, const std::string& pattern);

    /* То же для пути: «всегда» на каталог должен разрешать и всё внутри
     * него, иначе каждое обращение к файлу каталога спрашивало бы заново
     * и пользователь нажимал бы «всегда» десятки раз на одну папку. */
    void approve_path(const std::string& path);

    /* Снимок ожидающих запросов для UI. Возвращает копии и НИКОГДА не
     * держит лок на время отрисовки (D-6). */
    std::vector<PermissionRequest> pending() const;

    /* Сколько всего запросов ждёт ответа прямо сейчас. */
    size_t pending_count() const;

    /* И2.8: какие инструменты вообще показывать модели.
     *
     * Инструмент с правилом «<ключ> * → запретить» убирается из
     * каталога: модель не должна тратить шаг на заведомо отклонённый
     * вызов, а пользователь — читать отказ по каждому шагу (порт
     * permission/index.ts:204 disabled). Точечный запрет («read *.env»)
     * инструмент НЕ прячет: он запрещает конкретные значения, а сам
     * инструмент нужен. */
    std::vector<std::string> visible_tools(const std::vector<ToolDef>& all) const;

    /* Правила пользователя из настроек (JSON). Без этого запреты
     * недостижимы: правила меняет только approve(), а он добавляет
     * лишь Allow. Формат — массив объектов:
     *   [{"permission":"deploy","pattern":"*","action":"deny",
     *     "comment":"деплой запрещён на этой машине"}]
     * Правила дописываются ПОСЛЕ дефолтов, то есть перекрывают их. */
    void load_user_rules(const std::string& json_text);
    /* Обратно в JSON — для панели настроек и для save_settings. */
    std::string user_rules_json() const;

    /* Отменить все ожидающие (прерывание задачи, остановка движка,
     * каскад отклонения — И2.6). Проснувшиеся получают false. */
    void cancel_all();

    /* Снять отмену. Зовётся при поступлении НОВОЙ задачи: иначе после
     * «стоп» движок задавал бы мгновенные отказы до конца сессии, и
     * агент не смог бы объяснить пользователю причину. */
    void clear_cancel();

private:
    mutable std::mutex mtx_;
    Ruleset rules_;
    std::function<void()> on_change_;
    bool defaults_installed_ = false;
    bool user_rules_loaded_ = false;
    std::string last_user_rules_text_;
    int wait_timeout_ms_ = 0;

    /* Ожидание пользователя. */
    std::condition_variable cv_;
    std::vector<PermissionRequest> pending_;
    uint64_t next_id_ = 0;
    bool cancelled_ = false;
    EngineState* state_ = nullptr;
    std::function<void(const std::string&)> push_;
};

} // namespace coder
