#include <string>
#include <vector>

namespace coder {
namespace security {

/* Проверка path traversal: путь не должен содержать ".." после нормализации. */
bool is_path_safe(const std::string& path);

/* И13.1 (D6): находится ли путь ЗА пределами корня проекта.
 *
 * Обе стороны приводятся к каноническому виду `fs::weakly_canonical`, а
 * принадлежность корню проверяется относительным путём `lexically_relative`:
 * «внутри» тогда и только тогда, когда первым компонентом относительного
 * пути НЕ является `..`.
 *
 * Почему не сравнение строк (так было, и это был D6): строка
 * `/srv/site/wp-content` начинается с `/srv/site`, поэтому симлинк
 * `wp-content -> /etc` давал путь, который текстом лежит внутри проекта, а
 * на диске лежит снаружи. `weakly_canonical` симлинки РАЗВОРАЧИвает, и
 * сравнение идёт по тому, куда файл попадёт на самом деле, а не по тому,
 * как он назван.
 *
 * Три свойства, без которых проверка не годится:
 *   - `weakly_canonical`, а НЕ `canonical`: проверка обязана работать и для
 *     ещё не созданного файла (запись нового), и для ещё не созданного
 *     каталога. `canonical` на несуществующем пути возвращает пустой путь.
 *   - Канонизируется и КОРЕНЬ: если сам корень проекта reached через
 *     симлинку (`/var/www -> /srv/www`), то путь внутри и корень после
 *     разворачивания симлинков указывают в одно место. Без этого любой
 *     проект под симлинком выглядел бы «всё вне проекта».
 *   - Ошибка разбора (петля симлинков, нет прав на каталог) — это НЕ
 *     «внутри». Такой путь считается внешним: доказать, что он внутри, не
 *     удалось, а пользователь может разрешить его как внешний путь, и тогда
 *     доступ всё равно состоится. Обратное решение (считать внутренним)
 *     было бы отказом, который тихо мимо guard'а.
 *
 * Пустой project_dir — проверять нечего, путь считается своим
 * (иначе проект без каталога спрашивал бы разрешение на каждый файл). */
bool is_path_outside(const std::string& abs_path, const std::string& project_dir);

/* И13.1 (D6): разрешён ли путь — либо он внутри проекта, либо попал в
 * список разрешённых снаружи.
 *
 * Список `allowed` сравнивается с ПЕРВОНАЧАЛЬНЫМ путём, а не с каноническим:
 * список набирает человек (префиксом с `*`), и сверять его с уже
 * развёрнутыми симлинками значило бы переписывать то, что он написал.
 * Канонизация решает только вопрос «внутри ли проект». */
bool is_path_allowed(const std::string& abs_path,
                     const std::string& project_dir,
                     const std::vector<std::string>& allowed);

/* Проверка: project_dir не является корнем ФС. */
bool is_project_dir_valid(const std::string& project_dir);

/* Проверка: путь не является опасным (symlink на /etc/passwd и т.п.). */
bool is_path_not_dangerous(const std::string& abs_path);

/* Список запрещённых ШАБЛОНОВ для bash. И3: остался как первая
 * грубая линия перед политикой команд (core/command_policy.h), потому что
 * подстрока ловит и то, что разбор команды не понял. Перечислять плохие
 * строки нельзя — именно этим был дефект D5: `rm -rf ~` в списке не
 * значит, что он запрещён. Решение принимает CommandPolicy. */
const std::vector<std::string>& blocked_commands();

/* Проверка: команда не попала в грубый список подстрок. */
bool is_command_allowed(const std::string& cmd);

/* Проверка команды политикой команд (И3.6). Пустая строка — разрешено,
 * непустая — причина отказа по-русски, её показывает инструмент.
 *
 * check_command() — для произвольных команд, написанных моделью
 * (bash): подстроги + allowlist программ + allowlist хостов.
 * check_assembled_command() — для команд, которые собрал код плагина из
 * аргументов модели (git_*, deploy, systemd_*, docker_*, ssh_exec,
 * wp_cli, python_*): подстроки не проверяются, allowlist программ не
 * применяется, но все запреты по бинарнику действуют. */
std::string check_command(const std::string& cmd);
std::string check_assembled_command(const std::string& cmd);

/* Доверенные сетевые хосты для curl/wget: localhost по умолчанию,
 * wp_site_url / wp_local_url / deploy_host — из настроек (И3.6). */
void trust_command_hosts(const std::vector<std::string>& hosts);

/* Санитизация строки для использования в shell (экранирование). */
std::string shell_escape(const std::string& s);

/* Санитизация идентификатора: только alnum, _, -, точка.
 * Используется для имён контейнеров, сервисов, имён сайтов, опций и т.д.
 * Предотвращает shell injection через имена. */
std::string sanitize_ident(const std::string& s);

/* Валидация shell-аргумента: запрещает ; | & ` $ > < — метасимволы,
 * позволяющие инъекцию команд. Возвращает true если аргумент безопасен.
 *
 * И13.4: перевод строки — такой же разделитель команд, как `;`, и он
 * пропускался. Проверено на живой оболочке с manage.py: аргументы
 * «migrate\ntouch …» выполняли вторую команду. */
bool is_shell_arg_safe(const std::string& s);

/* Тот же вопрос, но с ответом: пусто — строка годится, иначе причина
 * отказа по-русски с названием символа.
 *
 * Зачем вторая функция, если есть первая: инструменту нужно показать
 * МОДЕЛИ, что именно не так («символ ';'»), иначе отказ читается как
 * «инструмент сломан» и модель повторяет то же самое. Набор запрещённых
 * символов живёт поэтому здесь, а не в инструменте: две копии одного
 * правила разъезжаются при первой же правке (D12). */
std::string shell_arg_refusal(const std::string& s);

} // namespace security
} // namespace coder
