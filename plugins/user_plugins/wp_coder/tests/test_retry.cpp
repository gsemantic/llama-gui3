/*
 * test_retry.cpp — И12.6: политика повторов обращения к провайдеру.
 *
 * ЧТО ПРОВЕРЯЕТСЯ И ПОЧЕМУ ИМЕННО ТАК
 * -----------------------------------
 * Проверяется не «функция вернула положительное число», а ЧИСЛА ИЗ ПЛАНА:
 * 2000 мс, фактор 2, джиттер 0.25, максимум 5 попыток. Проверка «задержка
 * больше нуля» прошла бы при любой политике вообще, включая «ждать 1 мс
 * всегда», — то есть была бы проверкой не задачи.
 *
 * ПОЧЕМУ ДРОБЬ ДЛЯ ДЖИТТЕРА ПЕРЕДАЁТСЯ СНАРУЖИ. `retry_delay_ms` принимает
 * roll из [0, 1), а не тянет генератор. Если бы она генерировала сама, то
 * проверка «джиттер даёт 75 % и 125 %» либо прошла бы случайно, либо падала
 * бы случайно — а тест, результат которого зависит от того, как легло зерно,
 * проверяет не политику, а удачу. Границы 75 % и 125 % обязаны быть
 * ВОСПРОИЗВОДИМЫ, иначе заявленный джиттер ничего не гарантирует.
 *
 * ПОЧЕМУ ОТДЕЛЬНО ПРОВЕРЯЕТСЯ ПРИОРИТЕТ ЗАГОЛОВКА. `retry-after` через ABI
 * недостижим (отдаётся только {"ok":0,"error":…}), то есть сегодня параметр
 * всегда -1, и проверка «приоритет у сервера» прошла бы на коде, который
 * этот параметр просто игнорирует. Именно потому она и нужна: механизм
 * ждёт, когда хост отдаст заголовок, и обязан быть готов к тому моменту.
 *
 * ПОЧЕМУ ПРОВЕРЯЕТСЯ И СОБЫТИЕ. «Событие retry в UI» — часть задачи, а не
 * украшение: повтор, о котором не сказано, выглядит как зависание. Отдельная
 * проверка на то, что Retry — самостоятельный вид события, а не Status:
 * иначе уведомление тонуло бы среди «Составляю план...».
 */

#include "test_framework.h"
#include "test_printers.h"
#include "../core/engine.h"
#include "../core/retry.h"

#include <string>
#include <vector>

using namespace coder;

namespace {

/* Политика из плана, названная один раз: проверки обязаны проверять именно
 * эти числа, иначе «проверка» подстроится под любую реализацию. */
RetryPolicy plan_policy() {
    RetryPolicy p;
    ASSERT_EQ(p.initial_ms, 2000);
    ASSERT_EQ(p.max_attempts, 5);
    return p;
}

/* roll = 0.5 — середина джиттера, где множитель равен ровно 1.0 и
 * проверка видит расчётную задержку без помех от разброса. */
constexpr double kMid = 0.5;

} // anonymous namespace

TEST(задержка_растёт_вдвое_от_первой_попытки) {
    const RetryPolicy p = plan_policy();
    /* Попытки считаются с НУЛЯ сделанных: attempt=0 — первая провалилась,
     * ждём initial_ms. Это соглашение важно: сдвиг на единицу тихо убрал бы
     * первую задержку целиком и удвоил последнюю. */
    ASSERT_EQ(retry_delay_ms(p, 0, kMid), 2000);
    ASSERT_EQ(retry_delay_ms(p, 1, kMid), 4000);
    ASSERT_EQ(retry_delay_ms(p, 2, kMid), 8000);
    ASSERT_EQ(retry_delay_ms(p, 3, kMid), 16000);
}

TEST(джиттер_даёт_ровно_четверть_в_каждую_сторону) {
    const RetryPolicy p = plan_policy();
    /* Нижняя и верхняя границы обязаны быть РОВНО 75 % и 125 %: джиттер,
     * который тихо сужается, хуже отсутствия джиттера — он обещает
     * разброс, а на деле не даёт его. */
    ASSERT_EQ(retry_delay_ms(p, 0, 0.0), 1500);   /* 2000 * 0.75 */
    ASSERT_EQ(retry_delay_ms(p, 0, 1.0), 2500);   /* 2000 * 1.25 */
    /* И на второй попытке тоже, а не только на первой. */
    ASSERT_EQ(retry_delay_ms(p, 1, 0.0), 3000);
    ASSERT_EQ(retry_delay_ms(p, 1, 1.0), 5000);
    /* Порядок: чем больше roll, тем дольше ждём — иначе «разброс» был бы
     * перевёрнут и все шли бы в одну сторону. */
    ASSERT_TRUE(retry_delay_ms(p, 2, 0.1) < retry_delay_ms(p, 2, 0.9));
}

TEST(задержка_обрезается_потолком) {
    RetryPolicy p = plan_policy();
    /* Без потолка 2^n на пятой попытке уходит далеко за минуту: человек
     * успевает забыть, чего ждал, и решить, что агент завис. */
    p.max_delay_ms = 10000;
    ASSERT_EQ(retry_delay_ms(p, 0, kMid), 2000);
    ASSERT_EQ(retry_delay_ms(p, 3, kMid), 10000);
    /* Обрезка — и на джиттере, и на вершине разброса, а не только в
     * середине. */
    ASSERT_EQ(retry_delay_ms(p, 3, 1.0), 10000);
    ASSERT_TRUE(retry_delay_ms(p, 4, kMid) <= p.max_delay_ms);
}

TEST(заголовок_сервера_важнее_расчёта_и_не_размывается) {
    const RetryPolicy p = plan_policy();
    /* Сервер сказал «через 8 с»: 8000 и есть ответ. Расчёт на первой
     * попытке дал бы 2000, то есть вдвое раньше обещанного. */
    ASSERT_EQ(retry_delay_ms(p, 0, kMid, 8000), 8000);
    /* Джиттер к серверному времени НЕ применяется: «приходи через 8 с» и
     * «приходи через 10 с» — разные обещания, и размытие второго
     * нарушало бы первое. */
    ASSERT_EQ(retry_delay_ms(p, 0, 0.0, 8000), 8000);
    ASSERT_EQ(retry_delay_ms(p, 0, 1.0, 8000), 8000);
    /* «Приходи через 6 часов» не должно превратить повтор в зависание. */
    ASSERT_EQ(retry_delay_ms(p, 0, kMid, 6 * 3600 * 1000), p.max_delay_ms);
    /* Минус единица — «сервер ничего не сказал», а не «жди минус миллисекунду
     * и падай в цикл». */
    ASSERT_EQ(retry_delay_ms(p, 0, kMid, -1), 2000);
}

TEST(повтор_ограничен_пятью_попытками_всего) {
    const RetryPolicy p = plan_policy();
    /* Повтор — это ПЯТАЯ попытка, а не пятый повтор: max_attempts=5 должно
     * дать четыре повтора, то есть решения «ещё раз» на попытках 0..3. */
    for (int attempt = 0; attempt < 4; ++attempt) {
        if (!should_retry(p, true, attempt)) {
            std::cerr << "  попытка " << attempt
                      << " отказана, хотя сбой повторяем" << std::endl;
            ASSERT_TRUE(false);
        }
    }
    ASSERT_FALSE(should_retry(p, true, 4));
    /* И неповторяемый сбой не повторяется НИ на какой попытке, даже первой:
     * иначе «повторяемость» была бы нужна только после первого провала. */
    for (int attempt = 0; attempt < 8; ++attempt) {
        ASSERT_FALSE(should_retry(p, false, attempt));
    }
}

TEST(уведомление_называет_вид_сбоя_попытку_и_время) {
    /* Вид сбоя — из таксономии И12.5, а не только текст ошибки: именно он
     * отвечает на вопрос, что человек будет делать дальше. */
    const std::string s = retry_notice("503 Service Unavailable",
                                       FailureKind::Provider, 0, 5, 2000);
    ASSERT_TRUE(s.find("провайдер") != std::string::npos);
    ASSERT_TRUE(s.find("503 Service Unavailable") != std::string::npos);
    /* Нумерация попыток — для ЧЕЛОВЕКА, то есть с единицы: после первого
     * провала идёт вторая попытка. */
    ASSERT_TRUE(s.find("2/5") != std::string::npos);
    ASSERT_TRUE(s.find("2 с") != std::string::npos);
    /* Вид отличает повторяемый сбой от соседних — иначе строка годилась бы
     * для чего угодно. */
    const std::string auth = retry_notice("invalid api key", FailureKind::Auth,
                                          0, 5, 2000);
    ASSERT_TRUE(auth.find("доступ к провайдеру") != std::string::npos);
}

TEST(секунды_округляются_вверх_чтобы_не_было_нуля) {
    /* 400 мс это ноль секунд: строка «через 0 с» читалась бы как «повтор
     * немедленно», а лента обновится через секунду, и человек увидел бы
     * расхождение между обещанием и тем, что он видит. */
    const std::string s = retry_notice("429", FailureKind::Provider, 0, 5, 400);
    ASSERT_TRUE(s.find("через 1 с") != std::string::npos);
    ASSERT_TRUE(s.find("через 0 с") == std::string::npos);
    /* Ровно секунда остаётся «одной», а не округляется до двух. */
    const std::string one = retry_notice("429", FailureKind::Provider, 0, 5, 1000);
    ASSERT_TRUE(one.find("через 1 с") != std::string::npos);
    ASSERT_TRUE(one.find("через 2 с") == std::string::npos);
}

TEST(повтор_это_отдельный_вид_события_а_не_статус) {
    /* Если бы это был Status, уведомление тонуло бы среди «Составляю
     * план...» и «Готово», а человек, у которого ход висит, не увидел бы
     * главного: агент не завис, а ждёт обещанного провайдером времени. */
    ASSERT_TRUE(static_cast<int>(AgentEvent::Retry) !=
                static_cast<int>(AgentEvent::Status));
    /* И событие доходит до ленты: без этого политика отработает в тишине. */
    AgentEvent ev;
    ev.kind = AgentEvent::Retry;
    ev.text = "[повтор] провайдер";
    ASSERT_EQ(ev.text, std::string("[повтор] провайдер"));
}