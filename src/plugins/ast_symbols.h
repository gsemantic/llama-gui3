#pragma once

/*
 * ast_symbols.h — символы одного файла для плагина (И6.3).
 *
 * Зачем файл, если «позвать парсер» — одна строка. Парсер в хосте уже есть
 * и грамматики в нём уже собраны, но добраться до него из плагина нельзя:
 * wp_coder_core — статическая библиотека без зависимости от хоста (D-7), и
 * единственный путь наружу это ABI. При этом плагину нужен не AST, а
 * короткий список «функция такая-то, строки такие-то»: отдавать ему дерево
 * узлов означало бы утянуть в ABI типы tree-sitter.
 *
 * Разбор — в хосте, решение о формате — здесь, и всё, что можно проверить
 * без дерева, проверяется здесь же: tests/core/test_ast_symbols.cpp собирает
 * узлы руками и не требует ни грамматик, ни файлов на диске.
 *
 * Что здесь НЕ живёт и почему:
 *   - обход дерева каталогов: у вызывающего свои правила пропуска и лимиты,
 *     а второй обход внутри хоста разошёлся бы с первым при первом же
 *     новом каталоге;
 *   - решение «AST или строковый скан»: это дело вызывающего, и хост
 *     честно отдаёт признак ast:false, а не пустой список.
 */

#include "core/ast_parser.h"

#include <nlohmann/json.hpp>
#include <string>
#include <vector>

namespace llama_gui {
namespace plugin {

/*
 * Короткий вид символа. Именно короткий: отдавать имя узла tree-sitter
 * («function_definition», «impl_item») значило бы заставить плагин знать
 * грамматики — то есть перенести знание о tree-sitter в то место, где его
 * быть не должно.
 *
 * Словарь маленький и закрытый: function, class, method, namespace, enum,
 * typedef, macro, block, unknown. Новый вид — новый элемент словаря, а не
 * новая строка от парсера.
 */
const char* ast_kind_for_type(const std::string& node_type);

/* Узлы парсера → массив символов. Чистая функция. */
nlohmann::json symbols_to_json(const std::vector<core::AstNode>& nodes);

/*
 * Разбор одного файла целиком: язык (по расширению, если не задан) →
 * проверка грамматики → разбор → символы.
 *
 * ok=true и ast=false — не ошибка, а «грамматики нет»: такой ответ обязан
 * оставаться ok, чтобы вызывающий отличал его от отказа. Иначе он увидит
 * ошибку на каждом php-файле и решит, что AST-разбор сломан, вместо того
 * чтобы молча уйти на строковый скан (и13.5).
 */
nlohmann::json ast_symbols_for_file(const std::string& path,
                                    const std::string& language);

} // namespace plugin
} // namespace llama_gui
